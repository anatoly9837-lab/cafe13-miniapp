"""Радиус, отступ и усечение в `styles.css` обязаны быть из состава.
Падающая проверка.

    python3 -I tools/check-sostav.py [--стили styles.css] [--состав <файл>]
    python3 -I tools/check-sostav.py --самопроверка

Коды: 0 — сошлось · 1 — КРАСНОЕ (значение вне шкалы и вне долга, либо мёртвая
строка долга) · 2 — НЕ ВЫПОЛНЕНО (нечего или нечем проверять) — читать как
«не выполнено», а не как зелёное.

ЗАЧЕМ. Состав — РЕШЕНИЕ о разрешённом наборе, и без прибора он украшение:
замер 06.11.2026 дал 11 разных длин радиуса, то есть сборщик брал похожее, а
не названное. Прибор судит СТАТИЧЕСКИЙ файл стилей — не поведение клиента и не
опись.

⚠ ШКАЛА И ДОЛГ ЧИТАЮТСЯ ИЗ СОСТАВА, а не повторены здесь: вторая копия чисел
разошлась бы с решением молча — наш записанный класс. Источник —
`_docs/recept/sostav-shkaly.md`, строки-пометки `ШКАЛА-РАДИУС` и `ДОЛГ-РАДИУС`.

⚠ ДОЛГ И ИСКЛЮЧЕНИЕ — РАЗНЫЕ СПИСКИ, и различает их НАЗВАННАЯ ПРИЧИНА:
значение, которому причину назвать можно, стоит исключением с этой причиной и
уходить не обязано; значение без причины — дрейф, оно в долгу и обязано уйти.
Прибор пропускает оба, но печатает отдельно: долг, который не убывает, виден
числом.

⚠ ПРИГОВОР ДВУСТОРОННИЙ. Мало краснеть на новом значении: у разрешающего
списка обязана краснеть и МЁРТВАЯ строка — долг или исключение, которого в
стилях уже нет. Без этой половины список зеленеет на пустом месте и растёт без
цены.

⚠ ВТОРАЯ ПОЛОВИНА — УСЕЧЕНИЕ. `text-overflow` и `-webkit-line-clamp` обязаны
стоять только у носителей из пометки `НОСИТЕЛЬ-УСЕЧЕНИЯ`: правило под место —
тот же дрейф, что новая длина радиуса. Исходов ТРИ, и третий назван вслух:
усечения в дереве нет вовсе — не зелёное и не красное, а «состав впереди
дерева» (носители приходят сборкой, до её мерджа судить нечего). Куплено
первой сборкой шага 13: правило усечения в рецепте было, носителя в клиенте
не было.

⚠ ОТСТУП судится по ДЛИНАМ, а не по строке целиком: разрешено объявление,
все длины которого из шкалы, остальное — долг или исключение по селектору.
Иначе `13px 15px` и `12px 15px` были бы двумя разными «значениями», и шкала
превратилась бы в перечень объявлений.

⚠ ЧЕГО ОН НЕ СУДИТ, названо вслух: перенос пользовательского текста (носителя
нет, два инлайновых правила — долг назван в составе), цвета и то, что ВИДНО на
отрисовке. Радиус из шкалы ничего не
говорит о контрасте и о том, влезает ли блок, — это снимок, а не файл.
"""
import io
import os
import re
import subprocess
import sys
import tempfile

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
СТИЛИ = os.path.join(КОРЕНЬ, 'styles.css')
СОСТАВ = os.path.join(КОРЕНЬ, '_docs', 'recept', 'sostav-shkaly.md')


def _пометка(текст, имя):
    м = re.search(r'<!--\s*%s:\s*(.*?)-->' % re.escape(имя), текст, re.S)
    return м.group(1).strip() if м else None


def прочитать_состав(путь):
    """Шкала и долг — из состава. Нет пометки — НЕ ВЫПОЛНЕНО, а не пустая шкала:
    пустая шкала покраснела бы на всём и выглядела работой."""
    if not os.path.exists(путь):
        return None, None, None, None, 'состава нет: %s' % путь
    текст = io.open(путь, encoding='utf-8').read()
    ш = _пометка(текст, 'ШКАЛА-РАДИУС')
    д = _пометка(текст, 'ДОЛГ-РАДИУС')
    if ш is None:
        return None, None, None, None, 'в составе нет пометки ШКАЛА-РАДИУС'
    шкала = set(ш.split())
    if not шкала:
        return None, None, None, None, 'шкала радиуса в составе пуста'
    и = _пометка(текст, 'ИСКЛЮЧЕНИЕ-РАДИУС')
    н = _пометка(текст, 'НОСИТЕЛЬ-УСЕЧЕНИЯ')
    if н is None:
        return None, None, None, None, 'в составе нет пометки НОСИТЕЛЬ-УСЕЧЕНИЯ'
    return шкала, _пары(д), _пары(и), _пары(н), None


def _пары(строка):
    """`селектор=значение | селектор=значение` → словарь. Разделитель — черта,
    а не пробел: в селекторе бывает пробел (`.wk > button`), и по пробелу он
    разъехался бы молча."""
    из = {}
    for кусок in (строка or '').split('|'):
        if '=' in кусок:
            с, _, з = кусок.rpartition('=')
            из[' '.join(с.split())] = з.strip()
    return из


def объявления(путь, свойство):
    """Селектор → значение свойства. Берётся ПОСЛЕДНЯЯ строка селектора: у
    правила в несколько строк предмет — та, рядом с которой стоит скобка.

    ⚠ ПРО ЯКОРЬ `(?:^|;)` — точно, потому что прогон поправил: от
    `padding-top` отступ защищает не он, а ДЕФИС (после `padding` в нём стоит
    `-`, а не `:`), и подлог со снятым якорем этот случай зелёным оставляет.
    Якорь нужен там, где имя свойства — ОКОНЧАНИЕ другого: `height` внутри
    `min-height`. У двух нынешних зовов (`padding`, `border-radius`) такого
    близнеца нет, поэтому якорь здесь — предосторожность, а не проверенная
    случаем защита. Назвать его «обязательным» значило бы обещать больше,
    чем держит прибор."""
    if not os.path.exists(путь):
        return None
    текст = io.open(путь, encoding='utf-8').read()
    найдено = []
    for м in re.finditer(r'([^{}]+)\{([^}]*)\}', текст):
        р = re.search(r'(?:^|;)\s*%s\s*:\s*([^;}]+)' % re.escape(свойство),
                      м.group(2))
        if not р:
            continue
        сел = ' '.join(м.group(1).strip().splitlines()[-1].split())
        найдено.append((сел, ' '.join(р.group(1).split())))
    return найдено


def радиусы(путь):
    return объявления(путь, 'border-radius')


def прочитать_отступ(путь):
    """Шкала отступа — из того же состава, своими пометками. Нет пометки —
    НЕ ВЫПОЛНЕНО: пустая шкала покраснела бы на всём и выглядела работой."""
    текст = io.open(путь, encoding='utf-8').read()
    ш = _пометка(текст, 'ШКАЛА-ОТСТУП')
    if ш is None:
        return None, None, None, 'в составе нет пометки ШКАЛА-ОТСТУП'
    шкала = set(ш.split())
    if not шкала:
        return None, None, None, 'шкала отступа в составе пуста'
    return (шкала, _пары(_пометка(текст, 'ДОЛГ-ОТСТУП')),
            _пары(_пометка(текст, 'ИСКЛЮЧЕНИЕ-ОТСТУП')), None)


def судить_составное(найдено, шкала, долг, исключения, имя_свойства):
    """Отступ — ЧЕТЫРЁХСТОРОННЕЕ значение, и судится он по ДЛИНАМ, а не по
    строке целиком: иначе `13px 15px` и `12px 15px` — два разных «значения»,
    и шкала превратилась бы в перечень объявлений. Разрешённым считается
    объявление, ВСЕ длины которого из шкалы; остальное — долг или исключение
    по селектору, как у радиуса."""
    красное, живые = [], {'долг': set(), 'исключение': set()}
    for сел, зн in найдено:
        чужие = [д for д in зн.split() if д not in шкала]
        if not чужие:
            continue
        if долг.get(сел) == зн:
            живые['долг'].add(сел)
            continue
        if исключения.get(сел) == зн:
            живые['исключение'].add(сел)
            continue
        красное.append('%s: %s «%s» — длины %s вне шкалы состава (%s), и ни '
                       'долга, ни исключения на этот селектор нет'
                       % (сел, имя_свойства, зн, ' '.join(чужие),
                          ' '.join(sorted(шкала))))
    for имя, список in (('долг', долг), ('исключение', исключения)):
        for сел in sorted(set(список) - живые[имя]):
            красное.append('%s %s «%s=%s» МЁРТВ: в стилях этого объявления '
                           'больше нет — снять строку из состава'
                           % (имя_свойства, имя, сел, список[сел]))
    return красное


УСЕЧЕНИЕ = ('text-overflow', '-webkit-line-clamp')


def усечения(путь):
    """Селектор → свойство усечения. Разбор тот же, что у радиуса: предмет —
    ПОСЛЕДНЯЯ строка селектора."""
    текст = io.open(путь, encoding='utf-8').read()
    найдено = []
    for м in re.finditer(r'([^{}]+)\{([^}]*)\}', текст):
        for св in УСЕЧЕНИЕ:
            if re.search(r'(?:^|;)\s*%s\s*:' % re.escape(св), м.group(2)):
                сел = ' '.join(м.group(1).strip().splitlines()[-1].split())
                найдено.append((сел, св))
    return найдено


def суд(стили, состав, печать=True):
    шкала, долг, исключения, носители, беда = прочитать_состав(состав)
    if not беда:
        шк_о, долг_о, искл_о, беда = прочитать_отступ(состав)
    if беда:
        if печать:
            print('ПРОВЕРКА НЕ ВЫПОЛНЕНА: %s' % беда)
        return 2
    найдено = радиусы(стили)
    if найдено is None:
        if печать:
            print('ПРОВЕРКА НЕ ВЫПОЛНЕНА: стилей нет: %s' % стили)
        return 2
    if not найдено:
        if печать:
            print('ПРОВЕРКА НЕ ВЫПОЛНЕНА: в стилях ни одного border-radius — '
                  'признак прибора слеп, а не стили чисты')
        return 2
    красное, живые = [], {'долг': set(), 'исключение': set()}
    for сел, зн in найдено:
        if зн in шкала:
            continue
        if долг.get(сел) == зн:
            живые['долг'].add(сел)
            continue
        if исключения.get(сел) == зн:
            живые['исключение'].add(сел)
            continue
        красное.append('%s: радиус %s вне шкалы состава (%s), вне долга и вне '
                        'исключений' % (сел, зн, ' '.join(sorted(шкала))))
    for имя, список in (('долг', долг), ('исключение', исключения)):
        for сел in sorted(set(список) - живые[имя]):
            красное.append('%s «%s=%s» МЁРТВ: в стилях этого радиуса больше нет — '
                            'снять строку из состава' % (имя, сел, список[сел]))
    # ── вторая половина: усечение живёт только в носителях ──────────────
    усеч = усечения(стили)
    живые_носители = set()
    if усеч:
        for сел, св in усеч:
            if сел in носители:
                живые_носители.add(сел)
            else:
                красное.append('%s: `%s` вне носителей усечения (%s) — своё '
                               'правило под место это и есть дрейф'
                               % (сел, св, ' '.join(sorted(носители)) or '—'))
        for сел in sorted(set(носители) - живые_носители):
            красное.append('носитель усечения «%s=%s» МЁРТВ: в стилях его нет, '
                           'а усечение в них есть' % (сел, носители[сел]))
    # ── третья половина: отступ по УРОВНЯМ ──────────────────────────────
    отступы = объявления(стили, 'padding')
    красное += судить_составное(отступы, шк_о, долг_о, искл_о, 'отступ')
    if печать:
        print('отступов в стилях %d · шкала %s · долг %d · исключений %d'
              % (len(отступы), ' '.join(sorted(шк_о)), len(долг_о),
                 len(искл_о)))
        print('радиусов в стилях %d · шкала %s · долг %d · исключений %d'
              % (len(найдено), ' '.join(sorted(шкала)), len(долг), len(исключения)))
        if усеч:
            print('усечений %d · носителей %d (%s)'
                  % (len(усеч), len(носители), ' '.join(sorted(носители))))
        else:
            # ⚠ НЕ зелёное и НЕ красное, а названный вслух порядок: носители
            #    приходят СБОРКОЙ, и до её мерджа судить нечего. Без этого
            #    различения прибор либо врёт зелёным на дереве без носителей,
            #    либо краснеет на законном «сборка раньше состава».
            print('усечения в этих стилях нет вовсе: носители состава (%s) '
                  'ждут сборки — состав впереди дерева, судить нечего'
                  % (' '.join(sorted(носители)) or '—'))
        for с in красное:
            print('КРАСНОЕ: %s' % с)
        if not красное:
            print('зелёное: вне шкалы только объявленный долг (радиус %d, '
                  'отступ %d) и исключения (%d), мёртвых строк нет; усечение %s'
                  % (len(долг), len(долг_о), len(исключения) + len(искл_о),
                     'только в носителях' if усеч else 'в этих стилях не встречено'))
    return 1 if красное else 0


def самопроверка():
    д = tempfile.mkdtemp(prefix='sostav-')
    случаи, провал = [], []

    def прогон(стили_текст, состав_текст, ждём, что, кусок=None):
        """⚠ Сверяется и КОД, и слова: два разных красных (чужой селектор и
        мёртвый носитель) дают одну единицу, и без куска текста самопроверка
        не отличила бы, какая половина сработала."""
        с = os.path.join(д, 'styles.css')
        о = os.path.join(д, 'sostav.md')
        io.open(с, 'w', encoding='utf-8').write(стили_текст)
        io.open(о, 'w', encoding='utf-8').write(состав_текст)
        прежний, sys.stdout = sys.stdout, io.StringIO()
        try:
            код = суд(с, о)
            вывод = sys.stdout.getvalue()
        finally:
            sys.stdout = прежний
        случаи.append(что)
        if код != ждём:
            провал.append('%s: код %d, ждали %d' % (что, код, ждём))
        if кусок and кусок not in вывод:
            провал.append('%s: в выводе нет %r' % (что, кусок))

    шкала = '<!-- ШКАЛА-РАДИУС: 0 9px 12px -->\n'
    долг = ('<!-- ДОЛГ-РАДИУС: .btn=11px -->\n'
            '<!-- НОСИТЕЛЬ-УСЕЧЕНИЯ: .clamp1=одна строка -->\n'
            '<!-- ШКАЛА-ОТСТУП: 0 4px 8px 12px -->\n')
    здоровые = '.card { border-radius: 12px }\n.btn { border-radius: 11px }\n'
    усеч1 = '.clamp1 { overflow: hidden; text-overflow: ellipsis }\n'

    прогон(здоровые, шкала + долг, 0, 'здоровое: шкала плюс объявленный долг')
    # ПОДЛОГ 1 — значение вне шкалы и вне долга
    прогон(здоровые + '.chip { border-radius: 8px }\n', шкала + долг, 1,
           'подлог «радиус вне шкалы» краснеет')
    # ПОДЛОГ 2 — долг умер: строка есть, значения в стилях нет
    прогон('.card { border-radius: 12px }\n', шкала + долг, 1,
           'подлог «мёртвая строка долга» краснеет')
    искл = '<!-- ИСКЛЮЧЕНИЕ-РАДИУС: .pass=18px -->\n'
    прогон(здоровые + '.pass { border-radius: 18px }\n', шкала + долг + искл, 0,
           'исключение с причиной проходит')
    # ПОДЛОГ 3 — мёртвое исключение: уходить не обязано, но живым быть обязано
    прогон(здоровые, шкала + долг + искл, 1,
           'подлог «мёртвая строка исключения» краснеет')
    # ПОДЛОГ 4 — нет пометки шкалы: НЕ ВЫПОЛНЕНО, а не зелёное
    прогон(здоровые, долг, 2, 'состав без шкалы — не выполнено, не зелёное')
    # ПОДЛОГ 5 — стили без радиусов вовсе: прибор слеп, а не стили чисты
    прогон('.card { color: red }\n', шкала + долг, 2,
           'стили без радиусов — не выполнено')
    # ── усечение ────────────────────────────────────────────────────────
    прогон(здоровые + усеч1, шкала + долг, 0,
           'усечение в объявленном носителе проходит', 'усечений 1 · носителей 1')
    # ПОДЛОГ 6 — усечение у чужого селектора
    прогон(здоровые + '.listitem b { text-overflow: ellipsis }\n', шкала + долг, 1,
           'подлог «усечение вне носителя» краснеет', 'вне носителей усечения')
    # ПОДЛОГ 7 — носитель назван, в стилях его нет, а усечение живо у другого
    прогон(здоровые + усеч1, шкала + долг.replace(
               '.clamp1=одна строка', '.clamp1=одна строка | .clamp2=две строки'),
           1, 'подлог «мёртвый носитель» краснеет', 'МЁРТВ')
    # ⚠ Третий исход — ФАКТ, а не приговор: усечения в дереве нет вовсе,
    #    носители приходят сборкой. Без этого случая прощение неотличимо
    #    от различения.
    прогон(здоровые, шкала + долг, 0, 'дерева без усечения прибор не судит',
           'состав впереди дерева')
    # ПОДЛОГ 8 — состав без пометки носителей: НЕ ВЫПОЛНЕНО, а не зелёное
    прогон(здоровые + усеч1, шкала + '<!-- ДОЛГ-РАДИУС: .btn=11px -->\n', 2,
           'состав без носителей — не выполнено', 'НОСИТЕЛЬ-УСЕЧЕНИЯ')
    # ── отступ ──────────────────────────────────────────────────────────
    прогон(здоровые + '.note { padding: 12px 8px }\n', шкала + долг, 0,
           'отступ из шкалы проходит', 'отступов в стилях 1')
    # ПОДЛОГ 9 — одна длина вне шкалы: судится ДЛИНА, а не строка целиком
    прогон(здоровые + '.note { padding: 13px 8px }\n', шкала + долг, 1,
           'подлог «длина отступа вне шкалы» краснеет', 'длины 13px вне шкалы')
    долг_о = '<!-- ДОЛГ-ОТСТУП: .note=13px 8px -->\n'
    прогон(здоровые + '.note { padding: 13px 8px }\n', шкала + долг + долг_о,
           0, 'объявленный долг отступа проходит')
    # ПОДЛОГ 10 — мёртвая строка долга отступа: разрешающий список обязан
    #             краснеть и на пустом месте
    прогон(здоровые, шкала + долг + долг_о, 1,
           'подлог «мёртвый долг отступа» краснеет', 'отступ долг')
    # ПОДЛОГ 11 — состав без шкалы отступа: НЕ ВЫПОЛНЕНО, а не зелёное
    прогон(здоровые + '.note { padding: 12px }\n',
           шкала + '<!-- ДОЛГ-РАДИУС: .btn=11px -->\n'
                   '<!-- НОСИТЕЛЬ-УСЕЧЕНИЯ: .clamp1=одна строка -->\n', 2,
           'состав без шкалы отступа — не выполнено', 'ШКАЛА-ОТСТУП')
    # ⚠ РАЗЛИЧЕНИЕ: `padding-top` это не `padding`, и значение вне шкалы в
    #    нём законно — прибор судит само свойство. Держит это ДЕФИС, а не
    #    якорь: подлог со снятым якорем оставляет случай зелёным (прогнано),
    #    и первая редакция этого комментария обещала обратное.
    прогон(здоровые + '.note { padding-top: 13px }\n', шкала + долг, 0,
           'padding-top не судится шкалой отступа', 'отступов в стилях 0')

    for ф in os.listdir(д):
        os.unlink(os.path.join(д, ф))
    os.rmdir(д)
    for с in случаи:
        print('  %s %s' % (с, 'ПРОВАЛ' if any(с in п for п in провал) else 'ок'))
    if провал:
        print('САМОПРОВЕРКА ПРОВАЛЕНА:')
        for п in провал:
            print('  %s' % п)
        return 1
    print('самопроверка: всё как ждали (случаев %d)' % len(случаи))
    return 0


# ── вторая половина: ПРЕДЕЛ РАЗМЕРА РЕЦЕПТА ─────────────────────────────────
# Предел 20 КиБ объявлен владельцем порядка работы (слово координатора
# 07.11.2026) и для блоков правил, и для рецептов. Признак был только у блоков:
# его прибор смотрит `Cafe13KPG/_docs/rules-*.md` и в каталог рецептов клиента
# не заглядывает ПО ПОСТРОЕНИЮ. Пока признака здесь не было, предел держался
# вниманием — и не удержал: `bar/sostav.md` жил на 21 925 Б, пока его не нашёл
# числом архитектор.
#
# ⚠ ЧИСЛО ПРЕДЕЛА — РЕШЕНИЕ, А НЕ ЗАМЕР, поэтому оно константой. Размер В
# СТВОЛЕ — наоборот замер, и он спрашивается у git КАЖДЫЙ раз: число ствола,
# записанное в прибор, стареет молча (довод координатора).
ПРЕДЕЛ_РЕЦЕПТА = 20 * 1024
РЕЦЕПТЫ = os.path.join(КОРЕНЬ, '_docs', 'recept')
СТВОЛ = 'origin/main'
# ⚠ Временное — в `~/.cache`, а не в `/tmp`: на агентском хосте `/tmp` общая
#   tmpfs на все сессии парка.
РАБОЧЕЕ = os.path.join(os.path.expanduser('~'), '.cache', 'check-sostav')


def размеры_рецептов(корень):
    """{путь от корня репозитория: размер в БАЙТАХ} по всем `.md` рецептов.

    ⚠ БАЙТЫ, а не знаки: текст кириллический, и в UTF-8 на знак приходится два
    байта. Счёт знаками показал бы 9 400 там, где файл весит 17 867, то есть
    прощал бы вдвое — предел объявлен в килобайтах, значит и мерить байтами."""
    из = {}
    for корневой, _, файлы in os.walk(корень):
        for имя in файлы:
            if имя.endswith('.md'):
                пп = os.path.join(корневой, имя)
                with open(пп, 'rb') as ф:
                    из[os.path.relpath(пп, КОРЕНЬ)] = len(ф.read())
    return из


def размер_в_стволе(путь, ствол=СТВОЛ):
    """Размер файла в стволе или None, если его там нет (файл НОВЫЙ)."""
    р = subprocess.run(['git', 'show', '%s:%s' % (ствол, путь)],
                       cwd=КОРЕНЬ, capture_output=True)
    return len(р.stdout) if р.returncode == 0 else None


def судить_размер(размеры, в_стволе, печать=True):
    """(код, строки). `в_стволе` — ШОВ: {путь: размер|None}, у случаев готовый.

    Исходы ТРИ, и средний куплен доводом координатора: жёсткий предел покраснел
    бы на принятом, а прибор, красный с рождения, выключают через сутки.
      · сверх предела и НОВЫЙ               → КРАСНОЕ: предел знали заранее;
      · сверх предела, но НЕ ВЫРОС          → зелёное с названным долгом;
      · сверх предела и ВЫРОС против ствола → КРАСНОЕ: долг растёт."""
    строки, беды = [], 0
    if not размеры:
        return 2, ['рецептов не найдено вовсе — мерить было нечего, '
                   'и ноль нарушений тут ничего не значит']
    сверх = {пп: р for пп, р in размеры.items() if р > ПРЕДЕЛ_РЕЦЕПТА}
    for пп in sorted(сверх):
        было = в_стволе.get(пп)
        if было is None:
            строки.append('КРАСНОЕ: новый рецепт %s — %d Б при пределе %d; '
                          'предел знали до того, как писать'
                          % (пп, сверх[пп], ПРЕДЕЛ_РЕЦЕПТА))
            беды += 1
        elif сверх[пп] > было:
            строки.append('КРАСНОЕ: %s сверх предела И ВЫРОС — %d Б против %d в '
                          'стволе (предел %d)'
                          % (пп, сверх[пп], было, ПРЕДЕЛ_РЕЦЕПТА))
            беды += 1
        else:
            строки.append('долг: %s — %d Б сверх предела %d, но не вырос '
                          '(в стволе %d)' % (пп, сверх[пп], ПРЕДЕЛ_РЕЦЕПТА, было))
    строки.append('размеры рецептов: файлов %d, сверх предела %d КиБ — %d'
                  % (len(размеры), ПРЕДЕЛ_РЕЦЕПТА // 1024, len(сверх)))
    if печать:
        for с in строки:
            print(с)
    return (1 if беды else 0), строки


def самопроверка_размера():
    """Случаи и подлоги второй половины. Шов — готовый `в_стволе`."""
    П = ПРЕДЕЛ_РЕЦЕПТА
    случаи = [
        ('под пределом — зелёное', {'a.md': П - 1}, {'a.md': П - 1}, 0, 'КиБ — 0'),
        ('новый сверх предела — красное', {'a.md': П + 1}, {}, 1, 'новый рецепт'),
        ('сверх предела, не вырос — долг', {'a.md': П + 9}, {'a.md': П + 9}, 0, 'не вырос'),
        ('сверх предела, УБЫЛ — долг', {'a.md': П + 5}, {'a.md': П + 9}, 0, 'не вырос'),
        ('сверх предела и вырос — красное', {'a.md': П + 10}, {'a.md': П + 9}, 1, 'ВЫРОС'),
        ('ровно предел — зелёное', {'a.md': П}, {'a.md': П}, 0, 'КиБ — 0'),
        ('пустой перечень — не выполнено', {}, {}, 2, 'мерить было нечего'),
    ]
    беды = 0
    print('— размер рецепта: случаи —')
    for имя, размеры, ствол, ждём_код, ждём_слово in случаи:
        код, строки = судить_размер(размеры, ствол, печать=False)
        текст = ' '.join(строки)
        ок = (код == ждём_код and ждём_слово in текст)
        беды += 0 if ок else 1
        print('  %-34s %s (код %d, ждали %d)'
              % (имя, 'ок' if ок else 'БЕДА', код, ждём_код))
    # ⚠ ПОДЛОГ НА БАЙТЫ ПРОТИВ ЗНАКОВ — на НАСТОЯЩЕМ файле, и наполнитель обязан
    #   оставлять файл ЧИТАЕМЫМ: наполнитель в один байт на знак даёт битый
    #   UTF-8, и прибор на таком ПАДАЕТ, а не краснеет — предупредил координатор
    #   своим же прогоном, дважды приняв падение за приговор.
    print('— размер рецепта: подлог «считать знаки вместо байтов» —')
    os.makedirs(РАБОЧЕЕ, exist_ok=True)
    д = tempfile.mkdtemp(prefix='razmer-', dir=РАБОЧЕЕ)
    ф = os.path.join(д, 'bolshoy.md')
    with open(ф, 'w', encoding='utf-8') as вых:
        вых.write('я' * (П // 2 + 100))          # валидный UTF-8, два байта на знак
    with open(ф, 'rb') as вх:
        байт = len(вх.read())
    with open(ф, encoding='utf-8') as вх:
        знаков = len(вх.read())
    ок = байт > П >= знаков
    беды += 0 if ок else 1
    print('  %-34s %s (байт %d, знаков %d, предел %d)'
          % ('байты судят, знаки прощают', 'ок' if ок else 'БЕДА', байт, знаков, П))
    код, _ = судить_размер({'bolshoy.md': байт}, {}, печать=False)
    беды += 0 if код == 1 else 1
    print('  %-34s %s' % ('тот же файл байтами — красное',
                          'ок' if код == 1 else 'БЕДА'))
    os.unlink(ф)
    os.rmdir(д)
    print('размер рецепта: бед %d' % беды)
    return 1 if беды else 0


def main(args):
    if args == ['--самопроверка']:
        return самопроверка() or самопроверка_размера()
    стили, состав, о = СТИЛИ, СОСТАВ, 0
    while о < len(args):
        if args[о] == '--стили':
            о += 1
            стили = args[о]
        elif args[о] == '--состав':
            о += 1
            состав = args[о]
        else:
            print('не знаю довода: %s' % args[о])
            return 2
        о += 1
    код = суд(стили, состав)
    размеры = размеры_рецептов(РЕЦЕПТЫ)
    ствол = {пп: размер_в_стволе(пп) for пп in размеры}
    код2, _ = судить_размер(размеры, ствол)
    return код or код2


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
