#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Сколько раз образец встречается В ОБЛАСТИ ОДНОГО ЭКРАНА, а не в файле.

  python3 -I tools/v-oblasti.py js/16-ekrany-bar.js drink 'Меню не загрузилось'
  python3 -I tools/v-oblasti.py --самопроверка

На stdout — ОДНО ЧИСЛО (как у `rg -c`), на stderr — адреса находок и путь, по
которому экран до них достаёт. Коды: 0 — замер напечатан · 2 — НЕ ВЫПОЛНЕНО
(нет файла, нет такого ключа, образец не читается регуляркой).

⚠ СВОЕГО ПРИГОВОРА У ПРИБОРА НЕТ, и это нарочно: цель («обязано стать N») живёт
в рецепте, судит её прибор сверки. Прибор, который сам решает «сошлось», стал бы
второй реализацией того, что проверяет.

ЗАЧЕМ ОН ЕСТЬ. 07.11.2026 сборщик привёз витрину бара одним PR (#273), и пять
экранов семьи оказались в ОДНОМ файле `js/16-ekrany-bar.js`. Признаки рецептов
считали `rg -c` ПО ФАЙЛУ — то есть считали заодно работу соседей. Замер по
сданной сборке:

  · `barCart` ждал `clamp1` = 1, в файле 2: своя строка состава и ЗАКОННАЯ
    строка `barOrder` («Что заказано»). Ложное КРАСНОЕ на верной сборке —
    единственный случай, который заметил сборщик;
  · `drink` ждал «Меню не загрузилось» = 2 и ПОЛУЧИЛ 2 — но ни одной в своём
    теле: одна в помощнике `menuGate` (:9), другая у соседа `bar` (:39). Не
    позови сборщик помощника из `drink`, признак сказал бы то же самое.
    Ложное ЗЕЛЁНОЕ, и его не заметил никто;
  · `barOrder` ждал «Заказ не загрузился» = 1 и получил 1 — находка в помощнике
    `mineFail` (:20), в теле экрана фразы нет вовсе. Тоже ложное зелёное;
  · развилка `.steps` объявляла исходы «4 или 0», а в файле `class="steps"`
    стоит дважды — у `barOrder` и у `barShot`, то есть у ЧУЖОГО экрана. Верные
    исходы 3 и 1: я записала соседнюю лестницу в свой замер.

Ложное красное ловит сборщик в тот же день — ему возвращают работу, и он
смотрит. Ложное зелёное не ловит никто: признак молчит ровно так же, как на
исполненном требовании.

ОБЛАСТЬ ЭКРАНА — НЕ ЕГО ТЕЛО. Тела мало, и это замер, а не вкус: правильная
сборка семьи держит общее состояние ОДНИМ приёмом на семью (решение
координатора), поэтому слова «Меню не загрузилось» в теле `drink` нет и быть
не должно — оно в помощнике, которого тело ЗОВЁТ. Признак по телу дал бы 0 и до
сборки, и после неё, то есть не отличал бы исполненное требование от неначатого.
Поэтому область = тело экрана ПЛЮС тела тех функций этого файла, до которых
экран достаёт по вызовам.

⚠ НАЗВАННЫЙ ПРЕДЕЛ: обход идёт ТОЛЬКО по этому файлу. Помощник из другого файла
(`tile`, `buyBtn`, `stepper` живут в `js/21-navigaciya.js`) в область не входит,
и признак на слово, уехавшее в чужой файл, покраснеет ложно. Предел выбран в
сторону строгости: лучше красное с адресом, чем зелёное без него.
"""
import io, os, re, subprocess, sys, tempfile

ПОДПИСЬ_ПРИБОРА = 'v-oblasti:'

# Слова, за которыми скобка стоит не потому, что это вызов функции.
НЕ_ВЫЗОВ = frozenset((
    'if', 'for', 'while', 'switch', 'catch', 'function', 'return', 'typeof',
    'new', 'delete', 'void', 'in', 'of', 'do', 'else', 'var', 'let', 'const'))

ОБЪЯВЛЕНИЕ_ЭКРАНА = re.compile(r'^  ([A-Za-z_$][A-Za-z0-9_$]*)\s*:\s*function')
ОБЪЯВЛЕНИЕ_ПОМОЩНИКА = re.compile(r'^function\s+([A-Za-z_$][A-Za-z0-9_$]*)\s*\(')
КОНЕЦ_ПОМОЩНИКА = re.compile(r'^\}')
КОНЕЦ_СКЛАДКИ = re.compile(r'^\}\)')
ВЫЗОВ = re.compile(r'\b([A-Za-z_$][A-Za-z0-9_$]*)\s*\(')


class НеВыполнено(Exception):
    pass


def области(строки):
    """{имя: (первая, последняя)} по 1-based строкам: экраны и помощники файла.

    ⚠ Экран закрывается СЛЕДУЮЩИМ объявлением или концом складки `});`, а не
    концом файла. Без этого область последнего экрана съедала бы хвост файла —
    ровно та ошибка области, против которой прибор и писан."""
    из, открыт = {}, None
    for н, с in enumerate(строки, 1):
        м = ОБЪЯВЛЕНИЕ_ЭКРАНА.match(с)
        if м:
            if открыт:
                из[открыт[0]] = (открыт[1], н - 1)
            открыт = (м.group(1), н)
            continue
        if открыт and КОНЕЦ_СКЛАДКИ.match(с):
            из[открыт[0]] = (открыт[1], н - 1)
            открыт = None
            continue
        м = ОБЪЯВЛЕНИЕ_ПОМОЩНИКА.match(с)
        if м:
            if открыт:
                из[открыт[0]] = (открыт[1], н - 1)
                открыт = None
            имя, конец = м.group(1), None
            for н2 in range(н + 1, len(строки) + 1):
                if КОНЕЦ_ПОМОЩНИКА.match(строки[н2 - 1]):
                    конец = н2
                    break
            из[имя] = (н, конец or len(строки))
    if открыт:
        из[открыт[0]] = (открыт[1], len(строки))
    return из


def достижимые(имя, обл, строки):
    """[(имя, кем позван)] — область экрана: он сам и функции файла по вызовам."""
    путь, видены, очередь = [], set(), [(имя, None)]
    while очередь:
        кто, кем = очередь.pop(0)
        if кто in видены:
            continue
        видены.add(кто)
        путь.append((кто, кем))
        а, б = обл[кто]
        for с in строки[а - 1:б]:
            for позван in ВЫЗОВ.findall(с):
                if позван in обл and позван not in видены and позван not in НЕ_ВЫЗОВ:
                    очередь.append((позван, кто))
    return путь


def замер(путь_файла, ключ, образец):
    """(число, [пояснение…]). Беда — НеВыполнено со словом о причине."""
    if not os.path.exists(путь_файла):
        raise НеВыполнено('файла нет: %s' % путь_файла)
    строки = io.open(путь_файла, encoding='utf-8').read().splitlines()
    обл = области(строки)
    if ключ not in обл:
        raise НеВыполнено(
            'в %s нет области `%s` (есть: %s)'
            % (путь_файла, ключ, ' '.join(sorted(обл)) or '—'))
    try:
        р = re.compile(образец)
    except re.error as e:
        raise НеВыполнено('образец не читается регуляркой: %s' % e)
    всего, слова = 0, []
    for кто, кем in достижимые(ключ, обл, строки):
        а, б = обл[кто]
        свои = []
        for н in range(а, б + 1):
            к = len(р.findall(строки[н - 1]))
            if к:
                всего += к
                свои.append('%s:%d%s' % (os.path.basename(путь_файла), н,
                                         '' if к == 1 else ' ×%d' % к))
        if свои:
            слова.append('  %s%s — %s'
                         % (кто, '' if кем is None else ' (зовёт %s)' % кем,
                            ' '.join(свои)))
    return всего, слова


