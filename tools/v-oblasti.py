# Слова, за которыми скобка стоит не потому, что это вызов функции.
НЕ_ВЫЗОВ = frozenset((
    'if', 'for', 'while', 'switch', 'catch', 'function', 'return', 'typeof',
    'new', 'delete', 'void', 'in', 'of', 'do', 'else', 'var', 'let', 'const'))

# ⚠ ЭКРАН СЧИТАЕТСЯ ТОЛЬКО ВНУТРИ СКЛАДКИ `Object.assign(SCREENS, {`, и это
#   куплено прогоном по живому клиенту, а не осторожностью. Первая редакция
#   брала любую строку `^  имя: function` — и на паре
#   `js/16-ekrany-bar.js,js/21-navigaciya.js` отказала: «имя `barCards`
#   объявлено в обоих». В `21-navigaciya.js:324` это запись КАРТЫ ВОЗВРАТА
#   (`barCards: function () { return CARDS.from || homeOf(); }`), а не экран, и
#   лежит она на том же отступе. Отказ был честный, но предмет не тот: ключ
#   экрана и имя в чужом объекте — разные вещи. Складка в клиенте ровно одна на
#   файл (замер: девять файлов экранов, в каждом один `Object.assign(SCREENS`).
НАЧАЛО_СКЛАДКИ = re.compile(r'^Object\.assign\(SCREENS\s*,')
ОБЪЯВЛЕНИЕ_ЭКРАНА = re.compile(r'^  ([A-Za-z_$][A-Za-z0-9_$]*)\s*:\s*function')
ОБЪЯВЛЕНИЕ_ПОМОЩНИКА = re.compile(r'^function\s+([A-Za-z_$][A-Za-z0-9_$]*)\s*\(')
КОНЕЦ_ПОМОЩНИКА = re.compile(r'^\}')
КОНЕЦ_СКЛАДКИ = re.compile(r'^\}\)')
ВЫЗОВ = re.compile(r'\b([A-Za-z_$][A-Za-z0-9_$]*)\s*\(')
# ⚠ ПОМОЩНИК БЫВАЕТ ПЕРЕДАН ЗНАЧЕНИЕМ, БЕЗ СКОБОК, и без этой формы обход его не
#   видит. Снято замером на живом клиенте 07.11.2026: усечение строки меню лежит
#   в `barRow` (`js/21-navigaciya.js:154`), а `bar` зовёт его
#   `g.items.map(barRow)` — имя стоит АРГУМЕНТОМ. Прибор печатал 0 там, где
#   требование исполнено, то есть ровно то ложное красное, против которого писан.
#   Таких форм в файле бара пять: `map(barRow)` ×2, `map(liveCard)`,
#   `map(queueCard)`, `map(cardRow)`.
#
# ⚠ И ПОЧЕМУ НЕ ЛЮБОЕ УПОМИНАНИЕ ИМЕНИ: потому что это переохват, и он измерен.
#   Помощник в клиенте зовётся `go` (`js/21-navigaciya.js:530`), а разметка полна
#   `data-go="bar"` — 21 строковый литерал файла бара несёт имя помощника внутри
#   себя. Пойди обход по любому упоминанию, область КАЖДОГО экрана втянула бы
#   `go` и всё, до чего достаёт он. То же с прозой: головной комментарий файла
#   законно называет `drink` и `barRecipe`. Поэтому берётся только имя, стоящее
#   ЦЕЛЫМ АРГУМЕНТОМ, — такой формы ни в разметке, ни в прозе не бывает.
АРГУМЕНТ = re.compile(r'[(,]\s*([A-Za-z_$][A-Za-z0-9_$]*)\s*(?=[),])')


class НеВыполнено(Exception):
    pass


def области_файла(строки):
    """{имя: (первая, последняя)} по 1-based строкам: экраны и помощники файла.

    ⚠ Экран закрывается СЛЕДУЮЩИМ объявлением или концом складки `});`, а не
    концом файла. Без этого область последнего экрана съедала бы хвост файла —
    ровно та ошибка области, против которой прибор и писан."""
    из, открыт, в_складке = {}, None, False
    for н, с in enumerate(строки, 1):
        if НАЧАЛО_СКЛАДКИ.match(с):
            в_складке = True
            continue
        м = ОБЪЯВЛЕНИЕ_ЭКРАНА.match(с) if в_складке else None
        if м:
            if открыт:
                из[открыт[0]] = (открыт[1], н - 1)
            открыт = (м.group(1), н)
            continue
        if в_складке and КОНЕЦ_СКЛАДКИ.match(с):
            if открыт:
                из[открыт[0]] = (открыт[1], н - 1)
                открыт = None
            в_складке = False
            continue
        м = ОБЪЯВЛЕНИЕ_ПОМОЩНИКА.match(с)
        if м:
            if открыт:
                из[открыт[0]] = (открыт[1], н - 1)
                открыт = None
            имя, конец = м.group(1), None
            for н2 in range(н + 1, len(строки) + 1):
                if КОНЕЦ_ПОМОЩНИКА.match(строки[н2 - 1]):
                    конец = н2
                    break
            из[имя] = (н, конец or len(строки))
    if открыт:
        из[открыт[0]] = (открыт[1], len(строки))
    return из


def области(пути):
    """{имя: (путь, строки, первая, последняя)} по ВСЕМ названным файлам.

    ⚠ Имя, объявленное в двух названных файлах, — беда: выбрав молча одно, прибор
    собрал бы область из чужого тела и напечатал правдоподобное число."""
    карта = {}
    for п in пути:
        if not os.path.exists(п):
            raise НеВыполнено('файла нет: %s' % п)
        строки = io.open(п, encoding='utf-8').read().splitlines()
        for имя, (а, б) in области_файла(строки).items():
            if имя in карта:
                raise НеВыполнено(
                    'имя `%s` объявлено и в %s, и в %s — какое тело область, '
                    'прибор не решает' % (имя, карта[имя][0], п))
            карта[имя] = (п, строки, а, б)
    return карта


def достижимые(имя, обл):
    """[(имя, кем позван)] — область экрана: он сам и функции по вызовам."""
    путь, видены, очередь = [], set(), [(имя, None)]
    while очередь:
        кто, кем = очередь.pop(0)
        if кто in видены:
            continue
        видены.add(кто)
        путь.append((кто, кем))
        _, строки, а, б = обл[кто]
        for с in строки[а - 1:б]:
            for позван in ВЫЗОВ.findall(с) + АРГУМЕНТ.findall(с):
                if позван in обл and позван not in видены and позван not in НЕ_ВЫЗОВ:
                    очередь.append((позван, кто))
    return путь


def замер(файлы, ключ, образец):
    """(число, [пояснение…]). Беда — НеВыполнено со словом о причине.

    `файлы` — строка с путями через запятую либо список путей."""
    пути = файлы.split(',') if isinstance(файлы, str) else list(файлы)
    пути = [п.strip() for п in пути if п.strip()]
    if not пути:
        raise НеВыполнено('файлы не названы')
    обл = области(пути)
    if ключ not in обл:
        raise НеВыполнено(
            'в %s нет области `%s` (есть: %s)'
            % (', '.join(пути), ключ, ' '.join(sorted(обл)) or '—'))
    try:
        р = re.compile(образец)
    except re.error as e:
        raise НеВыполнено('образец не читается регуляркой: %s' % e)
    всего, слова = 0, []
    for кто, кем in достижимые(ключ, обл):
        п, строки, а, б = обл[кто]
        свои = []
        for н in range(а, б + 1):
            к = len(р.findall(строки[н - 1]))
            if к:
                всего += к
                свои.append('%s:%d%s' % (os.path.basename(п), н,
                                         '' if к == 1 else ' ×%d' % к))
        if свои:
            слова.append('  %s%s — %s'
                         % (кто, '' if кем is None else ' (зовёт %s)' % кем,
                            ' '.join(свои)))
    return всего, слова


