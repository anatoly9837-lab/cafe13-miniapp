СЛУЧАИ = [
    ('слово в своём теле',            'barCart', 'clamp1',              1),
    ('слово в позванном помощнике',   'drink',   'Меню не загрузилось', 1),
    ('помощник НЕ позван — не моё',   'barCart', 'Меню не загрузилось', 0),
    ('слово у соседа по файлу',       'drink',   'clamp1',              0),
    ('голова файла вне областей',     'drink',   'ВНЕ-ОБЛАСТЕЙ',        0),
    ('хвост за складкой не мой',      'barCart', 'за складкой',         0),
    # ⚠ Ждали 3, вышло 4, и права была МАШИНА: образец `Меню|не загрузилось`
    # даёт ДВА вхождения в строке, а таких строк в теле `bar` две. Считаем по
    # вхождениям, как `re.findall` у прибора сверки, а не по строкам, как `rg -c`.
    ('вхождения, а не строки',        'bar',     'Меню|не загрузилось', 4),
    ('комментарий тела считается',    'bar',     'слово в комментарии', 1),
    ('обход транзитивный',            'bar',     'глубокое слово',      1),
    ('одинокий помощник не достижим', 'bar',     'lonely',              0),
    ('своё тело у соседа тоже видно', 'drink',   'clamp2',              1),
]

ПОДЛОГИ = [
    ('область экрана до конца файла',
     ("            из[открыт[0]] = (открыт[1], н - 1)\n"
      "            открыт = (м.group(1), н)",
      "            открыт = (м.group(1), н)")),
    # ⚠ ЯКОРЬ ПОДЛОГА ДВУХСТРОЧНЫЙ НАРОЧНО. Прежняя редакция брала одну строку
    #   `while очередь:` — и сторож «место подлога найдено ровно один раз» сказал
    #   БЕДУ: строка встречается дважды, в коде и в ЭТОЙ ЖЕ таблице. Двухстрочный
    #   якорь в тексте файла лежит с `\n` внутри литерала и себе не равен.
    ('не ходить по вызовам',
     ("                if позван in обл and позван not in видены and позван not in НЕ_ВЫЗОВ:\n"
      "                    очередь.append((позван, кто))",
      "                if False:\n"
      "                    очередь.append((позван, кто))")),
    ('считать по всему файлу',
     ("        а, б = обл[кто]\n        свои = []",
      "        а, б = (1, len(строки))\n        свои = []")),
]


def самопроверка():
    беды = 0
    база = os.environ.get('V_OBLASTI_WORK') or os.path.join(
        os.path.expanduser('~'), '.cache', 'v-oblasti')
    os.makedirs(база, exist_ok=True)
    кат = tempfile.mkdtemp(prefix='samo-', dir=база)
    ф = os.path.join(кат, 'obrazec.js')
    io.open(ф, 'w', encoding='utf-8').write(ОБРАЗЕЦ_ФАЙЛА)
    print('— случаи —')
    for имя, ключ, обр, ждём in СЛУЧАИ:
        try:
            было, _ = замер(ф, ключ, обр)
        except НеВыполнено as e:
            было = 'беда: %s' % e
        ок = (было == ждём)
        беды += 0 if ок else 1
        print('  %-32s %s (ждали %s, вышло %s)'
              % (имя, 'ок' if ок else 'БЕДА', ждём, было))
    print('— беды входа —')
    for имя, ключ, обр, путь in (
            ('нет файла',        'drink', 'x', os.path.join(кат, 'НЕТУ.js')),
            ('нет такого ключа', 'НЕТУ',  'x', ф),
            ('образец не регулярка', 'drink', '[', ф)):
        try:
            замер(путь, ключ, обр)
            print('  %-32s БЕДА (прошло молча)' % имя)
            беды += 1
        except НеВыполнено as e:
            print('  %-32s ок — %s' % (имя, str(e)[:60]))
    print('— подлоги против прибора —')
    свой = io.open(os.path.abspath(__file__), encoding='utf-8').read()
    for имя, (что, на) in ПОДЛОГИ:
        if свой.count(что) != 1:
            print('  %-32s БЕДА: место подлога не найдено ровно один раз' % имя)
            беды += 1
            continue
        п = os.path.join(кат, 'podlog.py')
        io.open(п, 'w', encoding='utf-8').write(свой.replace(что, на))
        р = subprocess.run([sys.executable, '-I', п, '--самопроверка'],
                           capture_output=True, text=True)
        покраснел = 'БЕДА' in р.stdout and р.returncode != 0
        беды += 0 if покраснел else 1
        print('  %-32s %s' % (имя, 'ок — подлог краснеет' if покраснел
                              else 'БЕДА: подлог прошёл ЗЕЛЁНЫМ'))
    print('%s самопроверка — бед %d' % (ПОДПИСЬ_ПРИБОРА, беды))
    shutil_rmtree(кат)
    return 1 if беды else 0


def shutil_rmtree(путь):
    import shutil
    shutil.rmtree(путь, ignore_errors=True)


def main(аргв):
    if '--самопроверка' in аргв:
        return самопроверка()
    if len(аргв) != 3:
        sys.stderr.write(__doc__.split('\n\n')[0] + '\n')
        return 2
    путь_файла, ключ, образец = аргв
    try:
        число, слова = замер(путь_файла, ключ, образец)
    except НеВыполнено as e:
        sys.stderr.write('%s НЕ ВЫПОЛНЕНО — %s\n' % (ПОДПИСЬ_ПРИБОРА, e))
        return 2
    sys.stdout.write('%d\n' % число)
    sys.stderr.write('%s `%s` в области `%s` (%s): %d\n'
                     % (ПОДПИСЬ_ПРИБОРА, образец, ключ,
                        os.path.basename(путь_файла), число))
    for с in слова:
        sys.stderr.write(с + '\n')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
