"""Проверка записана в прозе, а зовёт её НИКТО. Приговор по приборам.

    tools/bez-zova.py <файл.py|.sh|.cjs> [ещё файлы…]
    tools/bez-zova.py --самопроверка

Коды: 0 — чисто; 1 — КРАСНОЕ; 2 — ПРОВЕРКА НЕ ВЫПОЛНЕНА.

ЧТО ЗА ДЕФЕКТ, и он о нас, а не об инструментах. Правило или признак,
записанный РЯДОМ с прибором, но не включённый в приговор, держит ноль и при
этом выглядит сделанным. Случай, купивший этот прибор (журнал `Cafe13KPG`,
06.11.2026): признак на кириллицу в именах переменных жил четырьмя ветвями
`grep` в КОММЕНТАРИИ `tools/pered-mergem.sh:35`. У него была история — четвёртая
ветвь дописана по возврату ревьюера, в прозе рядом стояло, что комментарии из
признака вычтены, «иначе он находит сам себя». Отлажен, отревьюирован, правлен —
и за всё время не вызван ни разу: класс ловила привычка ставить контроль
различения рядом со сравнением, а не он. Настоящих случаев того класса в
корпусе 7617 команд — 34.

ПРИЗНАК, три условия вместе:
  1. строка прозы или комментария содержит команду поиска И КАВЫЧНЫЙ ОБРАЗЕЦ.
     Образец отделяет ПРОВЕРКУ от строки ЗАПУСКА прибора: у той подстановки
     «<каталог>», «<файл.js>», а не образцы. Без этого условия в корпусе 113
     законных строк запуска, и каждая была бы ложным приговором;
  2. в окне ±8 строк стоит ОЖИДАНИЕ: «ждём 0», «даёт 3», `rc=1`, «# 1 —».
     ⚠ Окно, а не строка, куплено тем же случаем: у признака из `pered-mergem`
     ожидание («ждём 0… он даёт 3») стояло СЕМЬЮ строками ниже рецепта, и
     построчный образец давал ложный ноль. Это был мой первый замер;
  3. кавычный кусок рецепта НЕ встречается в исполняемых строках того же файла.
     Встречается — значит проверку зовут, и она не предмет этого прибора.

ПРОЗУ ПИТОНА ЧИТАЕТ `ast`, а не поиск по «#». Второй ложный ноль того же
вечера: первая редакция искала только `#`-комментарии, а у наших приборов проза
живёт в docstring — по 81 файлу вышло 0 рецептов. После разбора `ast` их видно
113. Признак, не способный увидеть предмет, даёт ноль, неотличимый от чистоты.

ЧТО ОН СТОРОЖИТ ЧИСЛОМ, и зелёное читать как «класс закрыт» нельзя:
приборов в этом дереве **23**, всего в двух репозиториях **82** (считая этот —
он тоже прибор, и себя он судит). Остальные **59** лежат в `Cafe13KPG`, где
ворот и CI нет (замер 06.11.2026 по `origin/dev` `9666454`), и там признак
гоняется руками:

    python3 -I <чекаут cafe13-miniapp>/tools/bez-zova.py <файл.py> […]

Меньшая часть — но зов настоящий, а прибор без зова воспроизвёл бы ровно тот
дефект, о котором писан. Решение о шаге 9 — `cafe13kpg-coordinator`, 06.11.2026,
с доводом: признак ловит дефект при РОЖДЕНИИ прибора, а рождаются приборы с PR,
то есть там, где ворота уже стоят.

⚠ ГРАНИЦА КОРПУСА: БЛОКИ ПРАВИЛ И ДОКУМЕНТЫ СЮДА НЕ ВХОДЯТ, и это не
забывчивость. В `_docs/rules-*.md`, `AGENTS.md`, `CLAUDE.md` рецепт с образцом и
ожиданием — ЗАКОННАЯ форма: его зовёт человек по поводу, и «никто не зовёт из
кода» там не дефект, а норма жанра. Замер 06.11.2026: направленный на документы
прибор дал бы **5** ложных приговоров, и все пять — здоровые правила:
`CLAUDE.md:13-14` (проверка канона с контролем различения),
`_docs/rules-journal.md:1600-1601` (свидетельство числом в записи),
`_docs/rules-obolochka.md:103` (поиск по своим скиллам). Поэтому `.md` прибор не
судит вовсе — отказывает кодом 2, назвав причину.
"""
import ast
import glob
import io
import os
import re
import sys
from contextlib import redirect_stderr, redirect_stdout

ИНСТР = r"(?:grep|rg|awk|sed|test)"
РЕЦЕПТ = re.compile(rf"(?:^\s*#\s{{2,}}|^\s{{4,}})({ИНСТР}\b.*)$")
ОЖИДАНИЕ = re.compile(r"ждём\s*\d|ждем\s*\d|даёт\s+\d|даст\s+\d|→\s*\d|rc=\d|#\s*\d+\s*—")
КАВЫЧКА = re.compile(r"'([^']{6,})'|\"([^\"]{6,})\"")
ОКНО = 8
ПРЕДМЕТ = (".py", ".sh", ".bash", ".cjs", ".js")


def _проза_питона(текст):
    """Строки всех документирующих строк модуля, с номером в файле."""
    try:
        дер = ast.parse(текст)
    except SyntaxError as е:
        raise ValueError(f"питон не разобрался ({е.lineno}: {е.msg}) — "
                         f"проза не прочитана, приговору верить нельзя")
    вышло = []
    for у in ast.walk(дер):
        if not isinstance(у, (ast.Module, ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            continue
        д = ast.get_docstring(у, clean=False)
        if not д:
            continue
        нач = у.body[0].lineno if isinstance(у, ast.Module) else у.body[0].lineno
        for i, с in enumerate(д.split("\n")):
            вышло.append((нач + i, с))
    return вышло


def находки(путь, текст):
    строки = текст.split("\n")
    испол = [с for с in строки
             if not с.lstrip().startswith("#") and not РЕЦЕПТ.match(с)]
    испол_текст = "\n".join(испол)
    места = [(n, с) for n, с in enumerate(строки, 1) if с.lstrip().startswith("#")]
    if путь.endswith(".py"):
        места += _проза_питона(текст)
    вышло = []
    for n, с in места:
        m = РЕЦЕПТ.match(с)
        if not m:
            continue
        куски = [a or b for a, b in КАВЫЧКА.findall(m.group(1))]
        if not куски:
            continue                                  # строка запуска, не проверка
        окно = "\n".join(строки[max(0, n - 1 - ОКНО):n + ОКНО])
        if not ОЖИДАНИЕ.search(окно):
            continue                                  # пример, не проверка
        if any(к in испол_текст for к in куски):
            continue                                  # зовут — не предмет
        вышло.append((n, m.group(1).strip()))
    return вышло


def не_выполнено(что):
    print(f"ПРОВЕРКА НЕ ВЫПОЛНЕНА: {что}", file=sys.stderr)
    sys.exit(2)


def проверить(пути):
    красное, строк = [], 0
    for п in пути:
        if п.endswith((".md", ".txt", ".tsv", ".html")):
            не_выполнено(f"«{п}» — документ, а не прибор: там рецепт с образцом и "
                         f"ожиданием ЗАКОННАЯ форма (его зовёт человек по поводу), "
                         f"и приговор был бы ложным — см. прозу о границе корпуса")
        if not п.endswith(ПРЕДМЕТ):
            не_выполнено(f"«{п}» не прибор ({' '.join(ПРЕДМЕТ)}) — предмет не тот")
        try:
            т = io.open(п, encoding="utf-8").read()
        except OSError as е:
            не_выполнено(f"файл «{п}» не прочитан: {е}")
        if not т.strip():
            не_выполнено(f"файл «{п}» пуст — на пустом входе приговор был бы зелёным")
        try:
            н = находки(п, т)
        except ValueError as е:
            не_выполнено(f"{п}: {е}")
        строк += т.count("\n") + 1
        for n, команда in н:
            красное.append(f"  {п}:{n}: {команда[:100]}")
    if строк < len(пути):
        не_выполнено("прочитано меньше строк, чем файлов — вход не тот")
    if красное:
        print("КРАСНОЕ: проверка записана в прозе, а из кода её никто не зовёт")
        print("\n".join(красное))
        print("\nпроверка становится прибором тогда, когда её зовёт приговор; "
              "иначе она держит ноль и выглядит сделанной")
        return 1
    print(f"зелёное: проверок без зова нет в {len(пути)} приборах "
          f"({строк} строк прочитано)")
    return 0


# ── самопроверка ────────────────────────────────────────────────────────────
РЕЦЕПТ_ТЕКСТ = "grep -c 'Коммит агента не несёт трейлера' AGENTS.md"

СЛУЧАИ = (
    ("дефект: рецепт с ожиданием, зова нет",
     f'"""Проза.\n\n    {РЕЦЕПТ_ТЕКСТ}\n\n    ждём 1\n"""\nx = 1\n', True),
    ("ожидание В ОКНЕ, семью строками ниже (как в настоящем случае)",
     f'"""Проза.\n\n    {РЕЦЕПТ_ТЕКСТ}\n\nстрока\nстрока\nстрока\nстрока\n'
     f'строка\nждём 0 — и это ожидание\n"""\nx = 1\n', True),
    ("контроль: ожидание ВНЕ окна (девять строк)",
     f'"""Проза.\n\n    {РЕЦЕПТ_ТЕКСТ}\n\n1\n2\n3\n4\n5\n6\n7\n8\n9\nждём 0\n"""\nx = 1\n', False),
    ("контроль: рецепт зовут из кода",
     f'"""Проза.\n\n    {РЕЦЕПТ_ТЕКСТ}\n\n    ждём 1\n"""\n'
     f'if "Коммит агента не несёт трейлера" in текст:\n    pass\n', False),
    ("контроль: строка ЗАПУСКА прибора (нет образца)",
     '"""Проза.\n\n    python3 -I tools/check.py <каталог>   — ждём 0\n"""\nx = 1\n', False),
    ("контроль: рецепт без ожидания",
     f'"""Проза.\n\n    {РЕЦЕПТ_ТЕКСТ}\n\nпросто пример.\n"""\nx = 1\n', False),
    ("контроль: проза без рецептов вовсе",
     '"""Проза о предмете, замерах и границах.\n\nБез команд.\n"""\nx = 1\n', False),
)


def самопроверка():
    беда = 0
    for имя, текст, ждём in СЛУЧАИ:
        try:
            н = находки("<случай>.py", текст)
        except ValueError as е:
            print(f"КРАСНОЕ самопроверки: случай «{имя}» отказал: {е}")
            беда = 1
            continue
        if bool(н) != ждём:
            print(f"КРАСНОЕ самопроверки: случай «{имя}» дал "
                  f"{'красное' if н else 'зелёное'}, ждали "
                  f"{'красное' if ждём else 'зелёное'}; находки: {н}")
            беда = 1
            continue
        print(f"  {'краснеет' if ждём else 'молчит  '}  {имя}")

    # сторож ПРОЗЫ ПИТОНА: рецепт в docstring обязан быть виден (первый ложный ноль)
    только_проза = f'"""Проза.\n\n    {РЕЦЕПТ_ТЕКСТ}\n\n    ждём 1\n"""\nx = 1\n'
    if not находки("<случай>.py", только_проза):
        print("КРАСНОЕ самопроверки: рецепт в docstring не виден — "
              "ровно тот ложный ноль, из-за которого прибор читает ast")
        беда = 1
    else:
        print("  видит     рецепт в docstring, а не только в «#»")

    # сторож ГРАНИЦЫ КОРПУСА: документ прибор судить не смеет
    import tempfile
    for имя, ждём_отказ in (("правила.md", True), ("прибор.py", False)):
        д = tempfile.mkdtemp()
        путь = os.path.join(д, имя)
        io.open(путь, "w", encoding="utf-8").write('"""Проза."""\nx = 1\n')
        тихо = io.StringIO()
        try:
            with redirect_stdout(тихо), redirect_stderr(тихо):
                проверить([путь])
            отказал = False
        except SystemExit as е:
            отказал = (е.code == 2)
        if отказал != ждём_отказ:
            print(f"КРАСНОЕ самопроверки: на «{имя}» прибор "
                  f"{'отказал' if отказал else 'вынес приговор'}, ждали "
                  f"{'отказа' if ждём_отказ else 'приговора'}")
            беда = 1
        else:
            print(f"  {'отказ   ' if ждём_отказ else 'судит   '}  предмет «{имя}»")

    # сторож числа случаев и покрытия условий признака
    if len(СЛУЧАИ) < 6:
        print(f"КРАСНОЕ самопроверки: случаев {len(СЛУЧАИ)} — набор обрезан")
        беда = 1
    положительных = sum(1 for _, _, ж in СЛУЧАИ if ж)
    отрицательных = len(СЛУЧАИ) - положительных
    if положительных < 2 or отрицательных < 4:
        print(f"КРАСНОЕ самопроверки: перекос набора "
              f"({положительных} краснеющих, {отрицательных} молчащих): "
              f"у каждого из трёх условий признака обязан быть свой отрицательный")
        беда = 1

    print("самопроверка: красное выше" if беда
          else f"зелёное: самопроверка прошла, случаев {len(СЛУЧАИ)} "
               f"+ сторож прозы питона + сторож границы корпуса + сторож набора")
    return беда


def main():
    арг = sys.argv[1:]
    if "--самопроверка" in арг:
        return самопроверка()
    if not арг:
        не_выполнено("не названо, что проверять: tools/bez-zova.py <файл.py> […]")
    return проверить(арг)


if __name__ == "__main__":
    sys.exit(main())
