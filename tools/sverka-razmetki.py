"""Сверка СЛЕПКА отрисованных классов: свежий съём против описи дерева.

  python3 -I tools/sverka-razmetki.py <свежий razmetka.json> <razmetka.json описи>
  python3 -I tools/sverka-razmetki.py --состав <дерево>
  python3 -I tools/sverka-razmetki.py --самопроверка

Зачем он есть. До 19.11.2026 «что изменилось на экранах» судила БАЙТОВАЯ сверка
снимков (шаг 2 ворот). Она умерла: замер `frontend-events-9d` 18.11.2026 —
два прогона ОДНОГО дерева, один образ, один хост, дали 31 расхождение из 32,
и это сглаживание текста (0,08 % пикселей по краям глифов), а не содержание.
Порог по доле пикселей тоже мёртв по построению: шум доходил до 0,245 %, а
НАСТОЯЩАЯ смена номера версии на экране дала 0,237 % — полосы перекрываются.
Карточка `Cafe13KPG#934`.

А слепок классов воспроизводим, и это тот же замер: `razmetka.json` без поля
`снято` совпал ЦЕЛИКОМ у четырёх прогонов (двух последовательных и двух
одновременных). Поэтому судит он, а снимок остаётся изделием для глаза.

⚠ ЧЕГО ЭТОТ ПРИБОР НЕ ВИДИТ, и это предел по существу, а не недоделка: он
сверяет СОСТАВ отрисованных классов. Цвет, радиус, отступ, шрифт, съехавшая
на 3 пиксела кнопка — всё это для него одно и то же. Облик судят
`tools/check-sostav.py` (по стилям) и человеческий глаз по снимку. Поэтому
снимки из ворот не убраны: они справка, и справка нужная.

⚠ И САМОЕ ОСТРОЕ из невидимого — ТЕКСТ. Замер при сдаче прибора: сличение
съёма v159 с описью v158 дало РОВНО четыре расхождения — четыре новых вида, —
а смена номера версии на экране `29-demo` («v158» → «v159») слепку не видна
вовсе, хотя пиксельная сверка её ловила (0,237 % пикселей). Слова на экранах
судят случаи `tools/live.cjs` (тестирование 1) и признаки рецептов в
`tools/sverka-recepta.py`; переезд на слепок эту потерю НЕ закрывает, и
называть её обязан тот, кто ссылается на зелёный слепок.

Исходы: 0 — слепок тот же; 1 — РАСХОЖДЕНИЕ (назван каждый вид); 2 — ПРОВЕРКА
НЕ ВЫПОЛНЕНА (файла нет, не читается, нет карты `экраны`). Двойку читать как
«мерить было нечем», а не как зелёное.
"""
import importlib.util
import io
import json
import os
import re
import sys

ПОЛЯ_ВИДА = ('экран', 'довод', 'роль', 'тема')


class НечемМерить(Exception):
    pass


def карта(путь):
    """{имя вида: вид} из файла съёма. Поле `снято` не читается нарочно."""
    if not os.path.exists(путь):
        raise НечемМерить('нет файла съёма: %s' % путь)
    try:
        д = json.load(io.open(путь, encoding='utf-8'))
    except (ValueError, OSError) as е:
        raise НечемМерить('файл съёма не читается (%s): %s' % (е, путь))
    if not isinstance(д, dict) or not isinstance(д.get('экраны'), dict):
        raise НечемМерить('в %s нет карты `экраны` — это не съём разметки' % путь)
    return д['экраны']


def сверить(свежий, описи):
    """[(имя, что разошлось)…] — по видам, в порядке свежего съёма."""
    расхождения = []
    for имя in list(свежий) + [и for и in описи if и not in свежий]:
        если_нет = имя not in свежий or имя not in описи
        if если_нет:
            расхождения.append((имя, 'вида нет в описи дерева' if имя in свежий
                                else 'вид есть в описи, а съём его не снял'))
            continue
        а, б = свежий[имя], описи[имя]
        слова = []
        for поле in ПОЛЯ_ВИДА:
            if а.get(поле) != б.get(поле):
                слова.append('%s: %r было %r' % (поле, а.get(поле), б.get(поле)))
        ка, кб = а.get('классы') or {}, б.get('классы') or {}
        # ⚠ Классы сверяются ПОИМЁННО, а не числом: «классов стало столько же»
        #   истинно при замене одного другим, то есть молчало бы о правке.
        пришли = sorted(set(ка) - set(кб))
        ушли = sorted(set(кб) - set(ка))
        сменились = sorted(к for к in set(ка) & set(кб) if ка[к] != кб[к])
        if пришли:
            слова.append('классы пришли: ' + ' '.join('.' + к for к in пришли))
        if ушли:
            слова.append('классы ушли: ' + ' '.join('.' + к for к in ушли))
        for к in сменились:
            слова.append('.%s: %s было %s'
                         % (к, json.dumps(ка[к], ensure_ascii=False, sort_keys=True),
                            json.dumps(кб[к], ensure_ascii=False, sort_keys=True)))
        if слова:
            расхождения.append((имя, '; '.join(слова)))
    return расхождения


def шрифты(путь):
    """{адрес: запись} из карты `шрифты` съёма. Нет карты — «нечем мерить».

    ⚠ Карта появилась 19.11.2026 и у съёма ПРЕЖНЕЙ описи её может не быть —
    это «нечем», а не «совпали»: иначе первый же старый файл дал бы пиксельному
    расхождению приговор, не имея на то свидетельства."""
    if not os.path.exists(путь):
        raise НечемМерить('нет файла съёма: %s' % путь)
    try:
        д = json.load(io.open(путь, encoding='utf-8'))
    except (ValueError, OSError) as е:
        raise НечемМерить('файл съёма не читается (%s): %s' % (е, путь))
    к = д.get('шрифты')
    if not isinstance(к, dict) or not к:
        raise НечемМерить('в %s нет карты `шрифты` — съём снят прибором до '
                          '19.11.2026, и условие для пиксельного приговора '
                          'спросить нечем' % путь)
    return к


# ⚠ ФОРМ ОТДАЧИ ДВЕ, И ОДНОГО ЗАМЕРА ДОВОЛЬНО, ЧТОБЫ ИХ РАЗЛИЧИТЬ (Cafe13KPG#966).
#   Форма A — `fonts.gstatic.com/s/<семейство>/vN/*.woff2`, форма B —
#   `fonts.gstatic.com/l/font?kit=…`. Пара прогонов форму не различает по
#   построению: оба могут лечь на одну сторону. А адрес ресурса называет форму
#   в ОДНОМ съёме, без второго.
#   ДЕЙСТВУЮЩАЯ — A, и это замер, а не вкус: на ней снята опись ствола `c5aa42f`
#   (отпечатки `npjeeacl jkgjnakk bhnaeimk ddjcnofk blifkimh`); на ней же все
#   воротные прогоны карточки (#327, #331) и шесть прогонов образа ворот подряд
#   25.11.2026 (`tools/shots.cjs`, тот же образ, ни одного `/l/`). B вытягивали
#   только прямые прогоны 19.11; причина (жребий сети или зов) НЕ установлена,
#   и прибор её не угадывает — он называет форму и не пускает B в опись.
ДЕЙСТВУЮЩАЯ_ФОРМА = 'A'


def форма_отдачи(карта):
    """'A', 'B' или None (адресов gstatic нет или вид их не назван)."""
    адреса = [у for у in карта if 'fonts.gstatic.com/' in у]
    if any('fonts.gstatic.com/l/font' in у for у in адреса):
        return 'B'
    if адреса and all('fonts.gstatic.com/s/' in у for у in адреса):
        return 'A'
    return None


def сверить_шрифты(аргв):
    """0 — выпуск тот же; 1 — РАЗОШЛИСЬ; 2 — мерить нечем.

    ⚠ Зачем этот режим: причина `Cafe13KPG#934` — сеть отдаёт ДВА выпуска
    `Golos Text`, и при смене выпуска сдвигаются почти все снимки (сглаживание
    глифов, 0,08 % пикселей). Поэтому пиксельное расхождение — приговор ТОГДА И
    ТОЛЬКО ТОГДА, когда выпуск шрифтов тот же; разошёлся выпуск — расхождение
    остаётся справкой. Решение координатора 19.11.2026, и оно сильнее локальной
    копии шрифтов: пикселю возвращается то, чего слепок не умеет (съехавшая
    вёрстка, пропавший блок, смена слов), и при этом опись не начинает
    показывать шрифт из репозитория вместо того, что видит человек."""
    if len(аргв) != 2:
        print('ПРОВЕРКА НЕ ВЫПОЛНЕНА: нужны два пути — свежий съём и съём описи')
        return 2
    try:
        а, б = шрифты(аргв[0]), шрифты(аргв[1])
    except НечемМерить as е:
        print('ПРОВЕРКА НЕ ВЫПОЛНЕНА: %s' % е)
        return 2
    разошлись = [у for у in sorted(set(а) | set(б)) if а.get(у) != б.get(у)]
    print('шрифты: ресурсов свежих %d, в описи %d' % (len(а), len(б)))
    фа, фб = форма_отдачи(а), форма_отдачи(б)
    print('форма отдачи: свежий %s · опись %s (действующая %s, Cafe13KPG#966)'
          % (фа or 'не названа', фб or 'не названа', ДЕЙСТВУЮЩАЯ_ФОРМА))
    if not разошлись:
        print('выпуск шрифтов ТОТ ЖЕ — пиксельное расхождение о клиенте, а не о сети')
        return 0
    for у in разошлись:
        print('  ≠ %s\n      свежий %s · опись %s'
              % (у, (а.get(у) or {}).get('слепок', '—'), (б.get(у) or {}).get('слепок', '—')))
    print('ВЫПУСК ШРИФТОВ РАЗОШЁЛСЯ: ресурсов %d из %d — пиксельные расхождения '
          'сегодня о СЕТИ, приговором быть не могут (Cafe13KPG#934)'
          % (len(разошлись), max(len(а), len(б))))
    if фа and фб and фа != фб:
        print('ФОРМЫ ОТДАЧИ РАЗНЫЕ (свежий %s, опись %s): это не смена выпуска '
              '(Cafe13KPG#934), а другая форма (Cafe13KPG#966)' % (фа, фб))
    return 1


def снимки(каталог):
    """{имя: путь} PNG каталога. Нет каталога — «нечем мерить»."""
    if not os.path.isdir(каталог):
        raise НечемМерить('нет каталога снимков: %s' % каталог)
    из = {и: os.path.join(каталог, и) for и in sorted(os.listdir(каталог))
          if и.endswith('.png')}
    if not из:
        raise НечемМерить('в %s нет ни одного .png — сличать нечего' % каталог)
    return из


def сверить_снимки(аргв):
    """Приговор ПЕРЕСБОРКИ описи: 0 — опись под это дерево; 1 — ОТСТАЛА; 2 — нечем.

    ⚠ ЗДЕСЬ ПРИГОВОР НА МЕСТЕ, А В ВОРОТАХ МЕРДЖА — НЕТ, и это не вкус.
    Условие «выпуск шрифтов тот же» отсекает ШУМ СЕТИ (две сборки `Golos Text`,
    `Cafe13KPG#934`), но НЕ отсекает законную правку экрана. В воротах мерджа
    клиентский PR экран и ДОЛЖЕН менять, а опись пересобирается ПОСЛЕ мерджа —
    приговор там краснел бы на каждой фиче. А при ПЕРЕСБОРКЕ описи предмет
    ровно обратный: расхождение значит «опись отстала от дерева», и это
    приговор о моём предмете. Разделение — решение координатора 19.11.2026
    после замера архитектора по диффу.

    Зовётся с каталогом СВЕЖЕГО съёма и каталогом описи дерева; у каждого рядом
    свой `razmetka.json`, из которого берётся выпуск шрифтов."""
    if len(аргв) != 2:
        print('ПРОВЕРКА НЕ ВЫПОЛНЕНА: нужны два каталога — свежий съём и опись дерева')
        return 2
    свежий_кат, описи_кат = аргв
    try:
        свежие, лежат = снимки(свежий_кат), снимки(описи_кат)
        а = шрифты(os.path.join(свежий_кат, 'razmetka.json'))
        б = шрифты(os.path.join(описи_кат, 'razmetka.json'))
    except НечемМерить as е:
        print('ПРОВЕРКА НЕ ВЫПОЛНЕНА: %s' % е)
        return 2
    выпуск_тот_же = not [у for у in sorted(set(а) | set(б)) if а.get(у) != б.get(у)]
    разошлись, нет_в_описи = [], []
    for имя, путь in свежие.items():
        if имя not in лежат:
            нет_в_описи.append(имя)
        elif io.open(путь, 'rb').read() != io.open(лежат[имя], 'rb').read():
            разошлись.append(имя)
    print('снимки: свежих %d, в описи %d · разошлись %d · нет в описи %d · '
          'выпуск шрифтов %s'
          % (len(свежие), len(лежат), len(разошлись), len(нет_в_описи),
             'ТОТ ЖЕ' if выпуск_тот_же else 'РАЗОШЁЛСЯ'))
    for имя in разошлись:
        print('  ≠ %s' % имя)
    for имя in нет_в_описи:
        print('  + %s' % имя)
    if not (разошлись or нет_в_описи):
        print('опись под это дерево СОБРАНА — снимки те же')
        return 0
    # ⚠ СЕТЬ ФАЙЛА НЕ СОЗДАЁТ, и первая редакция этого места об этом не знала
    #   (нашёл `arhitector-47` стендом после мерджа `#310`): условие по выпуску
    #   шрифтов стояло ПЕРЕД разбором, и «снимок есть у съёма, а в описи его
    #   НЕТ» при ином выпуске уходило в «ПРИГОВОРА НЕТ» с кодом 0. Выпуск
    #   шрифтов объясняет РАСХОЖДЕНИЕ пикселей (сглаживание глифов), но нового
    #   файла он не делает: отсутствие снимка в описи — долг описи при ЛЮБОМ
    #   выпуске. Это тот же класс, что я в тот же день писал правилом: предмет
    #   УСЛОВИЯ обязан совпадать с предметом приговора, а здесь условие было о
    #   шуме сети, а приговор — о составе описи.
    if нет_в_описи:
        print('ОПИСЬ ОТСТАЛА от дерева: снимков нет в описи %d — сеть файла не '
              'создаёт, и выпуск шрифтов (%s) тут не оправдание; разошедшихся '
              'снимков %d — пересобрать (tools/shots.cjs, затем tools/catalog.py)'
              % (len(нет_в_описи), 'тот же' if выпуск_тот_же else 'разошёлся',
                 len(разошлись)))
        return 1
    # ⚠ ОПИСЬ ЖИВЁТ НА ДЕЙСТВУЮЩЕЙ ФОРМЕ, в обе стороны (Cafe13KPG#966): съём на
    #   иной форме — не повод пересобирать (31 снимок из 32 перетряхнётся и
    #   вернётся следующим прогоном), а опись, снятая на иной форме, — отстала.
    фс, фо = форма_отдачи(а), форма_отдачи(б)
    if фс and фс != ДЕЙСТВУЮЩАЯ_ФОРМА:
        print('ПРОВЕРКА НЕ ВЫПОЛНЕНА: свежий съём снят на НЕдействующей форме '
              'отдачи шрифтов %s (действующая %s, Cafe13KPG#966) — опись с него '
              'не пересобирается; переснять' % (фс, ДЕЙСТВУЮЩАЯ_ФОРМА))
        return 2
    # ⚠ Без `and разошлись`: сюда доходит только непустое `разошлись` (снимки
    #   те же → «СОБРАНА» выше, `нет_в_описи` → «ОТСТАЛА» выше). Мутант
    #   `arhitector-f5` m1 по #414 был равносильным; ветку «опись на B, снимки
    #   те же» держит случай самопроверки у «СОБРАНА».
    if фо and фо != ДЕЙСТВУЮЩАЯ_ФОРМА:
        print('ОПИСЬ ОТСТАЛА: она снята на НЕдействующей форме отдачи шрифтов %s '
              '(действующая %s, Cafe13KPG#966), разошедшихся снимков %d — '
              'пересобрать со свежего съёма' % (фо, ДЕЙСТВУЮЩАЯ_ФОРМА, len(разошлись)))
        return 1
    if not выпуск_тот_же:
        # ⚠ Не «сошлось», а «приговора нет»: расхождение объяснено сетью, и
        #   спрашивать его как долг описи нечем. Строка об этом печатается.
        print('ПРИГОВОРА НЕТ: выпуск шрифтов разошёлся, расхождение объяснено '
              'СЕТЬЮ (Cafe13KPG#934) — пересобирать опись этим расхождением '
              'нельзя: оно вернётся с другим выпуском')
        return 0
    print('ОПИСЬ ОТСТАЛА от дерева: при ТОМ ЖЕ выпуске шрифтов разошедшихся '
          'снимков %d, нет в описи 0 — пересобрать (tools/shots.cjs, затем '
          'tools/catalog.py)' % len(разошлись))
    return 1


