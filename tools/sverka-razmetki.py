def _без_прозы(текст, рядом):
    """Код без комментариев — снималкой СОСЕДА (`tools/check-stages.py`).

    ⚠ Зачем вообще снимать комментарии: объявление вида, приведённое в
    КОММЕНТАРИИ, иначе прочиталось бы объявлением — а `tools/shots.cjs` прозу
    пишет обильно и цитирует в ней собственные записи. Тогда долг описи
    покупался бы цитатой, и это ровно тот класс, что уже записан у соседа:
    «комментарий покупает признак».

    ⚠ Второй снималки тут НЕТ НАРОЧНО: она у соседа падающая (три возврата
    архитектора, включая шаблонные строки), и своя копия разошлась бы с ней
    молча. Нет соседа — «мерить нечем», а не «обошлось»."""
    if not os.path.exists(рядом):
        raise НечемМерить('рядом нет %s — снять комментарии нечем, а своей '
                          'снималки у прибора нет нарочно' % рядом)
    сп = importlib.util.spec_from_file_location('_snyat_kommentarii', рядом)
    if сп is None or сп.loader is None:
        raise НечемМерить('%s не грузится модулем — снять комментарии нечем'
                          % рядом)
    мод = importlib.util.module_from_spec(сп)
    сп.loader.exec_module(мод)
    return мод.снять_комментарии(текст)


def _виды_списка(код, н, имя_списка, путь):
    """Имена видов — ПЕРВЫЕ строки записей ВЕРХНЕГО уровня списка с `н`.

    ⚠ Глубина, а не образец (Cafe13KPG#943, 25.11.2026): записи `LIVE_SHOTS`
    несут ВЛОЖЕННЫЕ списки — роли `['head', 'admin', 'god_mentor']`,
    фикстуры. Образец «`['имя',`» по куску назвал бы `head.png` видом,
    объявленным съёмкой, — ложное КРАСНОЕ, тот же класс, что `Prata.png`
    выше. Вид — только запись глубины 1, её первая строка.

    ⚠ Строки обходятся целиком (`'`, `"`, `` ` ``, с `\\`): скобка в подписи
    вида — не скобка списка. Конец списка — его ПАРНАЯ скобка; её нет —
    «мерить нечем», а не обрезанный перечень."""
    i = код.index('[', н)
    глубина, имена, ждём_имя = 0, [], False
    while i < len(код):
        с = код[i]
        if с in '\'"`':
            j = i + 1
            while j < len(код) and код[j] != с:
                j += 2 if код[j] == '\\' else 1
            if ждём_имя:
                имена.append(код[i + 1:j])
                ждём_имя = False
            i = j + 1
            continue
        if с == '[':
            глубина += 1
            ждём_имя = глубина == 2
        elif с == ']':
            глубина -= 1
            ждём_имя = False
            if глубина == 0:
                return имена
        elif not с.isspace():
            ждём_имя = False
        i += 1
    raise НечемМерить('в %s у списка `%s` нет парной скобки — объявление '
                      'видов читать нечем' % (путь, имя_списка))


def объявленные_виды(путь_съёмки, путь_снималки):
    """{имя файла снимка} по спискам `SHOTS`, `LIVE_SHOTS` и `DARK` съёмки.

    ⚠ ОБЛАСТЬ СЧЁТА — СПИСОК, а не файл, и это замер, а не осторожность:
    по всему `tools/shots.cjs` образец объявления даёт 33 вхождения при 32
    видах, и лишнее — живая строка `const ждём = ['Prata', 'Golos Text'];`
    (проверка шрифтов). Считая файлом, прибор назвал бы `Prata.png` видом,
    объявленным съёмкой и потерянным описью, — ложное КРАСНОЕ на каждом
    прогоне. Моё же правило: область счёта обязана совпадать с областью
    утверждения, а утверждение здесь про СПИСКИ видов.

    ⚠ Конец списка — его ПАРНАЯ скобка, а вид — запись глубины 1
    (`_виды_списка`). До 25.11.2026 концом было первое `];`, а видом — любой
    образец «`['имя',`» в куске; на `LIVE_SHOTS` это назвало бы видом роль
    `head` из вложенного списка. `DARK` объявлен одной строкой — случай на
    него стоит отдельный, как и на `LIVE_SHOTS`."""
    if not os.path.exists(путь_съёмки):
        raise НечемМерить('нет файла съёмки: %s' % путь_съёмки)
    код = _без_прозы(io.open(путь_съёмки, encoding='utf-8').read(), путь_снималки)
    из = set()
    for имя_списка in СПИСКИ_ВИДОВ:
        н = код.find('const %s = [' % имя_списка)
        if н < 0:
            raise НечемМерить('в %s нет списка `const %s = [` — объявление '
                              'видов читать нечем' % (путь_съёмки, имя_списка))
        из.update(и + '.png' for и in _виды_списка(код, н, имя_списка, путь_съёмки))
    if not из:
        raise НечемМерить('в %s не прочитано ни одного объявления вида'
                          % путь_съёмки)
    return из


def сверить_состав(аргв):
    """0 — состав сошёлся; 1 — ДОЛГ описи; 2 — мерить нечем.

    ⚠ Предмет — ОБЪЯВЛЕНИЕ, а не байты: «вид съёмкой объявлен, а в описи
    его нет» и обратное. Съёма прибор не требует вовсе, и ровно поэтому его
    может звать ночной проход описи (`Cafe13KPG#943`), у которого ни docker,
    ни пересъёмки нет. Байтовый приговор там невозможен — он требует свежего
    съёма, а это docker и 32 запуска браузера.

    ⚠ Чего он НЕ ловит, и это предел по существу: УСТАРЕВШИЙ снимок. Вид
    объявлен, файл лежит — состав сошёлся, хотя экран давно другой. Это судит
    `--снимки` при пересборке (в живой сессии, с docker), а пиксель из
    приговоров ворот убран нарочно (`Cafe13KPG#934`).

    ⚠ Итог печатается СТРОКОЙ в любом случае, включая «сошлось»: у ночного
    прохода молчание неотличимо от смерти запуска."""
    if len(аргв) != 1:
        print('ПРОВЕРКА НЕ ВЫПОЛНЕНА: нужен один довод — каталог дерева')
        return 2
    дерево = аргв[0]
    try:
        объявлено = объявленные_виды(
            os.path.join(дерево, 'tools', 'shots.cjs'),
            os.path.join(дерево, 'tools', 'check-stages.py'))
        путь_м = os.path.join(дерево, 'screens', 'manifest.json')
        if not os.path.exists(путь_м):
            raise НечемМерить('нет манифеста описи: %s' % путь_м)
        манифест = json.load(io.open(путь_м, encoding='utf-8'))
        if not isinstance(манифест, list):
            raise НечемМерить('%s не список записей — это не манифест описи'
                              % путь_м)
    except НечемМерить as е:
        print('ПРОВЕРКА НЕ ВЫПОЛНЕНА: %s' % е)
        return 2
    except (ValueError, OSError) as е:
        print('ПРОВЕРКА НЕ ВЫПОЛНЕНА: манифест не читается (%s)' % е)
        return 2
    в_описи = {з.get('file') for з in манифест if isinstance(з, dict)}
    не_собрано = sorted(объявлено - в_описи)
    не_объявлено = sorted(в_описи - объявлено)
    print('состав описи: объявлено съёмкой %d, в описи %d'
          % (len(объявлено), len(в_описи)))
    for и in не_собрано:
        print('  + объявлен съёмкой, а в описи его НЕТ: %s' % и)
    for и in не_объявлено:
        print('  - лежит в описи, а съёмка его НЕ ОБЪЯВЛЯЕТ: %s' % и)
    if не_собрано or не_объявлено:
        print('ДОЛГ ОПИСИ: не собрано %d, лишних %d — пересобрать опись '
              '(tools/shots.cjs, затем tools/catalog.py --строго)'
              % (len(не_собрано), len(не_объявлено)))
        return 1
    print('состав СОШЁЛСЯ: каждый объявленный вид лежит в описи, лишних нет')
    return 0


