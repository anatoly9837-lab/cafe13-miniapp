def итог_самопроверки(код):
    """Контракт шага 18 ворот (Cafe13KPG#1118): ПОСЛЕДНЯЯ строка самопроверки —
    её приговор, из ТОГО ЖЕ кода, каким прибор выходит. Грамматика:
        самопроверка <файл>: сошлась | РАЗОШЛАСЬ — код 1 | НЕ ВЫПОЛНЕНА — код N
    Строка не по грамматике → шаг «НЕ ИЗМЕРЕН»; код 0 при не-«сошлась» → КРАСНОЕ
    «код съеден». Печатать после неё нельзя: она обязана быть последней."""
    print('самопроверка %s: %s' % (__file__.replace('\\', '/').rsplit('/', 1)[-1],
          'сошлась' if код == 0 else 'РАЗОШЛАСЬ — код 1' if код == 1
          else 'НЕ ВЫПОЛНЕНА — код %s' % код), flush=True)
    return код


