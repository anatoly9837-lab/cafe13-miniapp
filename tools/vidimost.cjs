(async () => {
  const b = await chromium.launch({ args: ['--no-sandbox'] });
  const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, locale: 'ru-RU' });
  /* ⚠ Часы приколоты теми же, что у съёмки (Cafe13KPG#727). Без этого обход
     течёт КАЛЕНДАРЁМ, и течёт числом, а не картинкой: `длины.events` — длина
     текста экрана афиши, а афиша печатает недельную сетку и день («Чт,
     30 октября» → «Вс, 1 ноября», ровно −2 знака). Замер 01.11.2026: на
     дереве 9c8683a — клиент байт в байт тот, с которого снята опись v121 —
     без часов выходит 245/209, с часами 247/211, и 247/211 воспроизводимо.
     ⚠ Записанное число устойчивости НЕ доказывает: в описи v121 стояло то же
     247/211, снятое БЕЗ часов, — только потому, что «Вт, 27 октября» и
     «Чт, 30 октября» равной длины. Совпало, а не держалось. */
  await ctx.clock.setFixedTime(new Date(FIXED_NOW));
  const p = await ctx.newPage();
  await p.goto('file:///app/index.html', { waitUntil: 'networkidle' });

  const есть = await p.evaluate((пр) => {
    const нет = пр.filter((и) => typeof window[и] !== 'function');
    if (typeof tabList !== 'function') нет.push('tabList');
    return нет;
  }, ПРАВА);
  if (есть.length) не_выполнено('в клиенте нет функций: ' + есть.join(', ') +
    ' — спрашивать нечем, и это НЕ «прав нет»');

  const спросить = (человек, уровень) => p.evaluate(([ч, у]) => {
    LIVE = true;
    DATA.role = у || 'guest';
    DATA.grants = ч.роли.map((р) => ({ role: р, dir: null }));
    DATA.barSide = ч.роли.some((р) => р === 'admin' || р === 'bar' || р === 'curator');
    /* Сервера нет, а `go()`-загрузчики (loadCards, loadRoster) за ним ходят.
       Висящий обещанием fetch не даёт им затереть состояние ответом-отказом. */
    window.fetch = function () { return new Promise(function () {}); };

    const права = {};
    ['mayCards', 'mayBook', 'mayPeople', 'canTopup', 'mayTopups'].forEach((и) => { права[и] = !!window[и](); });

    /* ── ОБХОД ДВЕРЕЙ. Видимость — не право, а путь: право без входа никуда
       не ведёт. Вход берётся с ОТРИСОВАННОГО экрана (`data-go` внутри
       `#view`), а не из числа вхождений в исходнике: вход рисуется условно,
       и число в прозе устаревает в день чужого мерджа (поправка
       arhitector-47, 27.10.2026, miniapp#90 — вход «Карточки меню» стал
       вторым, на «Заказах»).
       Отрисовка идёт через `current`+`render()`, а не `go()`: `go()` ещё и
       правит «откуда» (CARDS.from, BOOK.from), а это память приложения,
       которую обход портить не должен. */
    const вкладки = tabList();
    const сбои = {};
    /* ⚠ ДЛИНА ТЕКСТА `#view` у каждого пройденного экрана — свидетельство того,
       что экран ОТРИСОВАЛСЯ. Без него «дверей нет» неотличимо от «экран не
       нарисовался»: оба дают ноль входов и ни одного исключения. Пустое
       состояние клиента всегда что-то говорит («Афиши нет», «Записей нет»),
       поэтому ноль длины — это поломка, а не законная пустота. */
    const длины = {};
    let всего_в_документе = 0, в_обзоре = 0;

    function обойти() {
      /* Хозяев у двери бывает несколько: после miniapp#90 вход в «Карточки
         меню» есть и на «Клубе», и на «Заказах». Запомнить только первого —
         значит сказать на странице «дверь на „Заказы“» там, где их две. */
      const двери = {};
      // закрытая вкладка (заморозка, Cafe13KPG#510) видна, но не ведёт никуда — пути через неё нет
      const открыты = вкладки.filter((т) => !(typeof closed === 'function' && closed(т[0])));
      открыты.forEach((т) => { двери[т[0]] = ['вкладка']; });
      const очередь = открыты.map((т) => т[0]);
      while (очередь.length) {
        const к = очередь.shift();
        let вышло;
        try {
          current = к; param = null; render();
          // погашенный вход — не дверь: `render()` гасит входы на закрытые экраны (Cafe13KPG#510)
          вышло = [].slice.call(document.querySelectorAll('#view [data-go]:not([disabled])'))
                    .map((э) => э.getAttribute('data-go'));
          всего_в_документе = Math.max(всего_в_документе,
            document.querySelectorAll('[data-go]').length);
          в_обзоре = Math.max(в_обзоре, вышло.length);
          const тело = document.querySelector('#view');
          длины[к] = Math.max(длины[к] || 0, ((тело && тело.textContent) || '').trim().length);
        } catch (e) {
          /* Экран, который без сервера или без параметра не рисуется, обход
             ПРОХОДИТ НАСКВОЗЬ: его двери не собраны, и всё, что за ним, может
             быть недосчитано. Поэтому сбой записывается, а не глотается. */
          сбои[к] = String((e && e.message) || e);
          continue;
        }
        вышло.forEach((н) => {
          if (typeof SCREENS[н] !== 'function') return;
          if (!(н in двери)) { двери[н] = [к]; очередь.push(н); }
          else if (двери[н].indexOf(к) === -1) двери[н].push(к);
        });
      }
      return двери;
    }

    /* ⚠ Длины отрисовки нужны ПО КАЖДОЙ ПРОБЕ отдельно: сравнение двух проб —
       единственное наблюдение, которое отличает «подача данных не сработала»
       от «сработала, но новых дверей не прибавила». Второе законно: дверь,
       которую афиша добавляла («Вся афиша» → `events`), на v118 стала ВКЛАДКОЙ
       и достижима без данных (замер мой, #192). */
    const снять_длины = () => { const к = {}; Object.keys(длины).forEach((и) => (к[и] = длины[и])); return к; };

    /* Две пробы, и разница между ними — не придирка, а целый класс дверей.
       ПУСТО: сервера нет, списки (`EVENTS`, `CARDS.list`, `QUEUE`) пусты, и
       вход, нарисованный ВНУТРИ списка, не появляется — дверь в афишу живёт
       в `afishaHome()` под `if (!EVENTS)`. Такой недосчёт читался бы как
       «пути нет», а это «нечем измерить».
       С АФИШЕЙ: в `EVENTS` кладётся ДЕМО-НАБОР САМОГО КЛИЕНТА (`DATA.events`)
       — тот, которым он рисует афишу вне живого режима, и через ту же
       функцию строки (`eventRow` зовут оба места). Это проба, а не выдумка:
       своих данных я не сочиняю. Для `CARDS.list` и `QUEUE` демо-набора у
       клиента НЕТ, поэтому их внутренние двери здесь не мерятся вовсе —
       форму живой строки пришлось бы выдумать. */
    const пусто = обойти();
    const длины_пусто = снять_длины();
    EVENTS = DATA.events;
    const с_афишей = обойти();
    const длины_с_афишей = снять_длины();
    EVENTS = null;
    // подача ПОДЕЙСТВОВАЛА, если хоть один экран напечатал другое число знаков
    const проба_подействовала = Object.keys(длины_с_афишей).some(
      (к) => длины_с_афишей[к] !== длины_пусто[к]);

    const при_данных = {};
    Object.keys(с_афишей).forEach((к) => { if (!(к in пусто)) при_данных[к] = с_афишей[к]; });
    /* Экран, достижимый и так, но получивший при данных НОВУЮ дверь: сам он
       не «только при данных», а вот этот вход — да. Хозяева просто
       дописываются; разницу страница не печатает, и обещать её незачем. */
    Object.keys(пусто).forEach((к) => (с_афишей[к] || []).forEach((х) => {
      if (пусто[к].indexOf(х) === -1) пусто[к].push(х);
    }));

    /* Вкладки, за которыми в живом режиме экрана нет: замороженные и не подключённые
       (`closed()`, Cafe13KPG#510). Их экраны рисуют одну плашку без входов, и у человека,
       чьи вкладки ВСЕ закрыты, дверей нет законно — сторож ниже обязан это различать. */
    const закрыты = typeof closed === 'function' ? вкладки.filter((т) => closed(т[0])).map((т) => т[0]) : [];
    return { вкладки: вкладки.map((т) => т[1]), закрыты, всего_вкладок: вкладки.length, права, barSide: DATA.barSide,
             достижимо: пусто, при_данных, сбои, длины, проба_подействовала,
             // двери, которые рисует афиша с данными, ведут на `event`; закрыт он — проба мерить нечего
             афиша_закрыта: typeof closed === 'function' && closed('event'),
             обзор: { всего_в_документе, в_обзоре } };
  }, [человек, уровень]);

  const вышло = [];
  for (const ч of ЛЮДИ) {
    const уровни = ч.членство && ч.членство.length ? ч.членство : [null];
    const виды = [];
    for (const у of уровни) виды.push({ уровень: у || 'guest', ...(await спросить(ч, у)) });
    вышло.push({ имя: ч.имя, роли: ч.роли, членство: ч.членство, примечание: ч.примечание || '', виды });
  }

  // ── контроли: прибор, не различающий людей, неотличим от отсутствующего
  const гость = вышло.find((ч) => ч.имя === 'гость без ролей').виды[0];
  if (гость.вкладки.join(' ') !== 'Услуги Ивенты')
    не_выполнено('человек без ролей и без членства получил вкладки «' +
      гость.вкладки.join(' ') + '», а не гостевые две — состояние не применяется');
  if (Object.values(гость.права).some(Boolean))
    не_выполнено('у человека без ролей истинно право — состояние не применяется');
  const наборы = new Set(вышло.map((ч) => ч.виды[0].вкладки.join('·')));
  if (наборы.size < 3)
    не_выполнено('у пяти ролей всего ' + наборы.size +
      ' разных набора вкладок — прибор роли не различает');

  // ── контроли ОБХОДА ДВЕРЕЙ
  /* ⚠ СБОРЩИК СУДИТСЯ ПО ВСЕМУ ПРОГОНУ, А ПУСТОТА — ПО ВИДУ, и это разные
     вопросы. Сломанный сборщик `data-go` (переехал селектор, сменилась
     разметка) кладёт ноль дверей У ВСЕХ; законно пустой вид — один среди
     прочих. Признак по РОЛИ тут не годится ни в одну сторону: «вкладки
     отрисовались, дверей нет» при сломанном селекторе выглядит точно так же,
     и сторож, послабленный по этому признаку, пропустил бы ровно то, против
     чего писан (поймано подлогом селектора, замер мой 30.10.2026). */
  const всего_дверей = вышло.reduce((с, ч) => с + ч.виды.reduce((т, в) =>
    т + Object.keys(в.достижимо).filter((к) => в.достижимо[к][0] !== 'вкладка').length, 0), 0);
  if (!всего_дверей)
    не_выполнено('во ВСЁМ прогоне обход не нашёл ни одной двери ни у одного вида — ' +
      'сборщик `#view [data-go]` сломан или разметка входов переехала. Это НЕ «дверей нет»');

  for (const ч of вышло) for (const в of ч.виды) {
    const за_дверью = Object.keys(в.достижимо).filter((к) => в.достижимо[к][0] !== 'вкладка');
    // ноль дверей законен ТОЛЬКО когда все вкладки закрыты (заморозка, Cafe13KPG#510): тогда
    // за ними одна плашка «временно недоступно». Хоть одна живая вкладка — ноль снова значит
    // сломанный сборщик или неотрисованный экран (возврат arhitector-47 на #124)
    const все_закрыты = в.всего_вкладок > 0 && в.закрыты.length === в.всего_вкладок;
    /* ⚠ ВТОРОЕ ЗАКОННОЕ СОСТОЯНИЕ, купленное v118 (#192): вкладки гостя стали
       «Услуги» и «Ивенты», афиша в фикстуре пуста — за вкладками нет НИ ОДНОЙ
       строки с входом, и дверей законно ноль. Отличается оно от поломки тремя
       наблюдениями разом: двери нашлись хоть у кого-то в прогоне (выше), у
       этого вида ни одного сбоя отрисовки, и КАЖДАЯ его открытая вкладка
       что-то напечатала (`длины`). Пустое состояние клиента всегда говорит
       словами, поэтому нулевая длина — поломка, а не пустота. */
    const сбоев = Object.keys(в.сбои || {}).length;
    const длины = в.длины || {};
    const нарисованы = Object.keys(длины).length > 0 && Object.keys(длины).every((к) => длины[к] > 0);
    const пусто_законно = !за_дверью.length && !все_закрыты && !сбоев && нарисованы;
    if (пусто_законно)
      console.log('  ⚠ у «' + ч.имя + '» (' + в.уровень + ') дверей нет ЗАКОННО: ' +
        'вкладок ' + в.всего_вкладок + ', все отрисовались (' +
        Object.keys(длины).length + ' экранов, минимум ' +
        Math.min.apply(null, Object.keys(длины).map((к) => длины[к])) + ' знаков), ' +
        'а строк с входом за ними нет — так выглядит пустая фикстура, не поломка');
    if (!за_дверью.length && !все_закрыты && !пусто_законно)
      не_выполнено('у «' + ч.имя + '» (' + в.уровень + ') обход не нашёл НИ ОДНОЙ двери, и это ' +
        'НЕ законная пустота: ' + (сбоев ? 'сбоев отрисовки ' + сбоев + ' (' +
        Object.keys(в.сбои).join(', ') + ')' : 'экраны без текста: ' +
        Object.keys(длины).filter((к) => !длины[к]).join(', ') || 'ни один экран не пройден') +
        ' — так выглядит сломанный сборщик `data-go` или экран, который не отрисовался');
    // тот же признак: у человека без единой открытой вкладки обходить нечего, и 0 против 0 законно
    if (!все_закрыты && в.обзор.всего_в_документе <= в.обзор.в_обзоре)
      не_выполнено('у «' + ч.имя + '» в документе ' + в.обзор.всего_в_документе +
        ' входов, в обзоре ' + в.обзор.в_обзоре + ' — полоса вкладок из обзора не ' +
        'исключается, и вкладки сойдут за двери экрана');
  }
  const новых_при_данных = вышло.reduce((н, ч) =>
    н + ч.виды.reduce((м, в) => м + Object.keys(в.при_данных).length, 0), 0);
  // заморозка (Cafe13KPG#510) закрыла `event` у всех — тогда пусто законно: это «мерить нечем», а не «подача сломана»
  const афиша_закрыта_у_всех = вышло.every((ч) => ч.виды.every((в) => в.афиша_закрыта));
  /* ⚠ ВТОРОЕ ЗАКОННОЕ СОСТОЯНИЕ И ЗДЕСЬ, и купил его тот же v118 (#192).
     Ноль новых дверей значит одно из двух, и это РАЗНЫЕ вещи:
       • подача данных не сработала (`DATA.events` пуст, `EVENTS` не применился)
         — тогда пометка «при непустых данных» на странице была бы ложной;
       • подача сработала, но новых ДОСТИЖИМЫХ экранов не прибавила, потому что
         дверь, которую афиша добавляла («Вся афиша» → `events`), стала ВКЛАДКОЙ
         и достижима без данных. Строки афиши дверьми не являются вовсе:
         `eventRow` не рисует ни одного `data-go` (замер мой 30.10.2026 по
         дереву 771cc95), и это названный предел обхода, а не новость.
     Различает их СРАВНЕНИЕ ПРОБ: подействовала ли подача на отрисовку. */
  const подача_подействовала = вышло.some((ч) => ч.виды.some((в) => в.проба_подействовала));
  if (!новых_при_данных && !афиша_закрыта_у_всех && !подача_подействовала)
    не_выполнено('вторая проба (с демо-афишей клиента) не нашла НИ ОДНОЙ новой двери ' +
      'ни у кого И не изменила отрисовку ни одного экрана — значит подача данных не ' +
      'сработала, и пометка «при непустых данных» на странице была бы ложной');
  if (!новых_при_данных && !афиша_закрыта_у_всех && подача_подействовала)
    console.log('  ⚠ вторая проба новых дверей не дала ЗАКОННО: подача подействовала ' +
      '(отрисовка менялась), а новых достижимых экранов нет — дверь афиши уже достижима ' +
      'без данных, строки афиши дверьми не являются (`eventRow` без `data-go`)');

  const о = вышло.find((ч) => ч.имя === 'гость без ролей').виды[0];
  const лишнее = ['barCards', 'people', 'staff', 'barMoney'].filter((к) => к in о.достижимо);
  if (лишнее.length)
    не_выполнено('человек без ролей доходит до рабочих экранов: ' + лишнее.join(', '));

  /* ⚠ ХЕШ КЛИЕНТА, С КОТОРОГО СНЯТО. Без него файл видимости устаревает
     МОЛЧА: поправили `tabList()` или вход в app.js, прибор не перегнали —
     страница печатает прежнее «видят», и всё зелёное. Сверку делает
     tools/catalog.py при сборке (возврат arhitector-47, 27.10.2026). */
  let хеш;
  try {
    хеш = crypto.createHash('sha256').update(fs.readFileSync('/app/app.js')).digest('hex');
  } catch (e) {
    не_выполнено('не прочитался /app/app.js, с которого снимается видимость: ' +
      String((e && e.message) || e) + ' — хеш поставить нечем, и файл видимости ' +
      'без него нельзя сверить со клиентом');
  }

  fs.writeFileSync('/work/vidimost.json', JSON.stringify({
    снято: new Date().toISOString(),
    клиент_sha256: хеш,
    предел: 'вывод по коду клиента, не наблюдение под человеком',
    роли_откуда: 'club_test, замер devops5 27.10.2026 06:29:59 UTC, только чтение',
    люди: вышло
  }, null, 1));
  for (const ч of вышло) {
    console.log(ч.имя.padEnd(10), ч.виды.map((в) => в.уровень + ': ' + в.вкладки.join(' · ')).join('   |   '),
      '   права:', Object.entries(ч.виды[0].права).filter(([, v]) => v).map(([k]) => k).join(',') || '—');
    for (const в of ч.виды) {
      const за = Object.keys(в.достижимо).filter((к) => в.достижимо[к][0] !== 'вкладка');
      console.log(' '.repeat(10), в.уровень + ': за дверью ' + за.length + ' —',
        за.map((к) => к + '←' + в.достижимо[к].join('/')).join(', ') || '—');
      const пд = Object.keys(в.при_данных);
      if (пд.length) console.log(' '.repeat(10), в.уровень + ': при непустой афише ещё —',
        пд.map((к) => к + '←' + в.при_данных[к].join('/')).join(', '));
      const сб = Object.keys(в.сбои);
      if (сб.length) console.log(' '.repeat(10), в.уровень + ': НЕ ОТРИСОВАЛИСЬ (обход сквозь них ' +
        'мог недосчитать): ' + сб.join(', '));
    }
  }
  console.log('\nнаписан vidimost.json:', вышло.length, 'ролей,', наборы.size, 'разных набора вкладок');
  await b.close();
})();
