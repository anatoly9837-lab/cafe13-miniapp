/* tools/vidimost.cjs — кто из живых людей клуба какие вкладки и права видит.
 *
 *   docker run --rm -v "$PWD:/app:ro" -v <куда писать>:/work -w /work \
 *     --entrypoint node agenthost/playwright:1.59.1 /work/vidimost.cjs
 *
 * Пишет vidimost.json рядом с описью; его читает tools/catalog.py и печатает
 * колонку «кто видит» на странице «Экраны» (Cafe13KPG#407).
 *
 * ⚠ ОТКУДА ЧИСЛА. Права и вкладки считает САМ КЛИЕНТ: страница грузится,
 * в неё кладётся состояние человека, и дальше спрашиваются `tabList()`,
 * `mayCards()`, `mayBook()`, `mayPeople()`, `canTopup()` — то есть те же
 * функции, по которым работает приложение. Второй реализации правил на
 * питоне нарочно нет: она разошлась бы с клиентом молча.
 *
 * ⚠ ЧЕГО ПРИБОР НЕ ЗНАЕТ, названо, чтобы не считалось проверенным:
 *   — это ВЫВОД ПО КОДУ, а не наблюдение: ни под одним человеком экран не
 *     открывали. Наблюдение ставится отдельным шагом — прогоном под каждой
 *     ролью (предел назвал координатор, Cafe13KPG#407);
 *   — `canOpenShift`/`canCloseShift` зависят от смены, пришедшей с сервера
 *     (`BAR`), и вне живого режима равны лжи у всех — здесь их нет вовсе;
 *   — состав ролей и членств взят из тестовой базы: замер `devops5` по
 *     `club_test`, 27.10.2026 06:29:59 UTC, только чтение. Я базу не читал.
 *
 * Коды: 0 — написано; 2 — НЕ ВЫПОЛНЕНО (нечем спрашивать).
 */
const { chromium } = require('/usr/lib/node_modules/playwright');
const fs = require('fs');

/* Шесть человек, названных владельцем 27.10.2026. `членство` — уровень
 * живого членства в ТЕСТОВОЙ базе или null; `роли` — как их отдаёт
 * `/me` (роль плюс направление, направления здесь не важны: ни одно
 * спрашиваемое право не смотрит на направление). */
const ЛЮДИ = [
  { имя: 'владелец', роли: ['admin', 'god_mentor', 'head'], членство: null,
    примечание: 'в бою членство бессрочное, в тесте его нет' },
  { имя: 'Нок', роли: ['staff'], членство: null },
  { имя: 'Саша', роли: ['curator'], членство: ['member', 'partner'],
    примечание: 'два живых членства с одним концом — уровень берётся одним из них, порядок не определён' },
  { имя: 'Юра', роли: ['curator'], членство: ['member', 'partner'],
    примечание: 'то же, что у Саши' },
  { имя: 'Сой', роли: ['bar', 'bar'], членство: null },
  { имя: 'Ольга', роли: [], членство: null }
];

const ПРАВА = ['mayCards', 'mayBook', 'mayPeople', 'canTopup'];

function не_выполнено(текст) {
  console.log('ПРОВЕРКА НЕ ВЫПОЛНЕНА: ' + текст);
  process.exit(2);
}

(async () => {
  const b = await chromium.launch({ args: ['--no-sandbox'] });
  const p = await (await b.newContext({ viewport: { width: 390, height: 844 }, locale: 'ru-RU' })).newPage();
  await p.goto('file:///app/index.html', { waitUntil: 'networkidle' });

  const есть = await p.evaluate((пр) => {
    const нет = пр.filter((и) => typeof window[и] !== 'function');
    if (typeof tabList !== 'function') нет.push('tabList');
    return нет;
  }, ПРАВА);
  if (есть.length) не_выполнено('в клиенте нет функций: ' + есть.join(', ') +
    ' — спрашивать нечем, и это НЕ «прав нет»');

  const спросить = (человек, уровень) => p.evaluate(([ч, у]) => {
    LIVE = true;
    DATA.role = у || 'guest';
    DATA.grants = ч.роли.map((р) => ({ role: р, dir: null }));
    DATA.barSide = ч.роли.some((р) => р === 'admin' || р === 'bar' || р === 'curator');
    const права = {};
    ['mayCards', 'mayBook', 'mayPeople', 'canTopup'].forEach((и) => { права[и] = !!window[и](); });
    return { вкладки: tabList().map((т) => т[1]), права, barSide: DATA.barSide };
  }, [человек, уровень]);

  const вышло = [];
  for (const ч of ЛЮДИ) {
    const уровни = ч.членство && ч.членство.length ? ч.членство : [null];
    const виды = [];
    for (const у of уровни) виды.push({ уровень: у || 'guest', ...(await спросить(ч, у)) });
    вышло.push({ имя: ч.имя, роли: ч.роли, членство: ч.членство, примечание: ч.примечание || '', виды });
  }

  // ── контроли: прибор, не различающий людей, неотличим от отсутствующего
  const ольга = вышло.find((ч) => ч.имя === 'Ольга').виды[0];
  if (ольга.вкладки.join(' ') !== 'Услуги Записи')
    не_выполнено('человек без ролей и без членства получил вкладки «' +
      ольга.вкладки.join(' ') + '», а не гостевые две — состояние не применяется');
  if (Object.values(ольга.права).some(Boolean))
    не_выполнено('у человека без ролей истинно право — состояние не применяется');
  const наборы = new Set(вышло.map((ч) => ч.виды[0].вкладки.join('·')));
  if (наборы.size < 3)
    не_выполнено('у шести человек всего ' + наборы.size +
      ' разных набора вкладок — прибор людей не различает');

  fs.writeFileSync('/work/vidimost.json', JSON.stringify({
    снято: new Date().toISOString(),
    предел: 'вывод по коду клиента, не наблюдение под человеком',
    роли_откуда: 'club_test, замер devops5 27.10.2026 06:29:59 UTC, только чтение',
    люди: вышло
  }, null, 1));
  for (const ч of вышло)
    console.log(ч.имя.padEnd(10), ч.виды.map((в) => в.уровень + ': ' + в.вкладки.join(' · ')).join('   |   '),
      '   права:', Object.entries(ч.виды[0].права).filter(([, v]) => v).map(([k]) => k).join(',') || '—');
  console.log('\nнаписан vidimost.json:', вышло.length, 'человек,', наборы.size, 'разных набора вкладок');
  await b.close();
})();
