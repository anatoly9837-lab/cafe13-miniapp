#!/usr/bin/env python3
"""Долг описи против ВЫЛОЖЕННОГО клиента — падающая проверка (Cafe13KPG#605).

    python3 -I tools/check-opis.py                  # спросить Pages и ствол
    python3 -I tools/check-opis.py --самопроверка

Коды: 0 — измерено (в том числе «опись отстала»: это ПРЕДУПРЕЖДЕНИЕ);
1 — КРАСНОЕ, настоящая поломка (опись ни ствольная, ни судимая; слепки
разошлись при равных номерах; номер описи спорит с её же клиентом);
2 — НЕ ВЫПОЛНЕНО (Pages не ответил, номер не прочитался, описи нет) —
читать как «не выполнено», а НЕ как «долга нет».

⚠ ПРЕДЕЛ БОЛЬШЕ НЕ ДЕРЖИТ ПУБЛИКАЦИЮ — решение владельца 29.10.2026: опись
нужна как ответ на «что человек видит», а не как ворота; расхождения идут
карточками, опись снимается ночным проходом. Отставание печатается строкой
при коде 0. **Не возвращать блокировку без нового слова владельца** — в
коде это выглядит очевидной починкой, и вернуть её легко по недосмотру.

Правило (координатор, 29.10.2026): по модели «показ раньше проверки» опись
едет позади выложенного клиента, предел отставания — ТРИ ОПУБЛИКОВАННЫХ
НОМЕРА. Публикуются только номера, поднятые правкой клиента, поэтому мердж,
не тронувший `app.js`, долга не делает.

Зовут двое, и ловят они разное: автор клиента — перед публикацией (его случай
«опубликовать поверх предела»), владелец описи — обходом (его случай
«накопилось»). Проверка без вызывающего — комментарий.

⚠ Эта проверка — НЕ четвёртые ворота необратимости. Ворот перед показом ТРИ
(Cafe13KPG#605: дым, имена и id, оба номера версии), и они стоят на КАЖДОЙ
публикации. Разводить обязательно: на счёте ворот у нас уже ошибались.

⚠ И ОТСТАВАНИЕ КРАСНЫМ НЕ БЫВАЕТ ВООБЩЕ, НИ ПРИ КАКОМ ДОЛГЕ. Красное здесь
даёт только поломка ПРИЗНАКА: опись не ствольная и не судимая, слепки
разошлись при равных номерах, номер описи спорит с её же клиентом. Долг
любого размера — строка при коде 0: при 1–2 он законен (опись едет позади
выложенного клиента), при ≥ 3 печатается «больше порога … расхождение идёт
карточкой, публикации не держит».

Прежняя редакция этого абзаца говорила «красное бывает только при долге ≥ 3
либо при описи с другого клиента, а при долге 1–2 проверка зелена НАРОЧНО».
Формально это кода не опровергало, а ЧИТАЛОСЬ против него: противопоставление
«1–2 зелена нарочно» оставляло единственное естественное чтение «≥ 3 →
красное». Цена такого чтения названа выше и она не косметическая: прочитавший
решит, что блокировка есть и сломалась, и «починит» её — то есть вернёт
ворота, снятые словом владельца. Поэтому — ещё раз: **не возвращать
блокировку без нового слова владельца.**

Два прибора в одном приговоре, второй сильнее первого:

  • СЧЁТ НОМЕРОВ: номер на Pages минус номер в `screens.html`. Видит
    накопление, но слеп к правке, не поднимавшей номер;
  • СЛИЧЕНИЕ КЛИЕНТА: свод слепков страницы из `screens/vidimost.json`
    против свода выложенной. Судит «опись снята с ДРУГОГО клиента» и
    краснеет там, где номера равны, а код разошёлся.

⚠ ПРИЗНАК СЛИЧЕНИЯ СМЕНИЛСЯ (Cafe13KPG#806). Прежде это был один sha256
`app.js`, и он был узок ДО разбивки тоже: правку `index.html`, `styles.css`
или водяного знака он не видел, то есть опись старела зелёной от правки
ОТРИСОВКИ, а не кода. После разбивки он умер совсем — файла `app.js` нет.
Теперь сличается КАРТА `файл → sha256` по составу из `index.html`
(tools/klient.py), свёрнутая в одно сравнимое число. Состав каждая сторона
называет СВОИМ `index.html`: иначе ствол с одним файлом и ветка с двадцатью
двумя сравнивались бы по списку одной из них.

⚠ Сличение судит ТОЛЬКО при равных номерах, и спрашивается трёхсторонне —
опись, ствол, Pages. Оба условия куплены дефектами первой редакции. Судя при
разных номерах, оно краснело на КАЖДОЙ здоровой публикации: номер лежит внутри
клиента, поэтому отставание описи на номер — это всегда другой свод, и при
долге 1–2 судит счёт номеров, а слепки молчат. Двухсторонним же оно врёт на
выкладке в пути: опись, снятая с нового ствола, не сойдётся с ещё не
обновлённым Pages, и это лаг сборки, а не долг; различает их ствол.

⚠ И почему приговор «НЕ ИЗМЕРЕН» заведён отдельным кодом. Первая редакция
этой проверки считала долг в оболочке: `grep -o 'app\\.js?v=[0-9]*'` плюс
`$(( P - O ))`. Шаблон `[0-9]*` совпадает с признаком БЕЗ числа, номер уезжает
пустым, а пустое в арифметике bash — ноль: на входе без номера проверка
печатала «долга нет», то есть самый успокаивающий из возможных ответов, и
предел при ней не срабатывал НИКОГДА. Замер пяти входов — в PR.
"""

import json
import os
import pathlib
import re
import importlib.util
import subprocess
import sys

ПРЕДЕЛ = 3
ВЫЛОЖЕНО = 'https://anatoly9837-lab.github.io/cafe13-miniapp/'
СТВОЛ = 'origin/main'
ОПИСЬ = 'screens.html'
ГЕНЕРАТОР = 'tools/catalog.py'
ВИДИМОСТЬ = 'screens/vidimost.json'

# Номер в разметке — форма `?v=NN`; в описи — `vNN · дата`. Диапазон в шаблоне
# (`v9[0-9]`) здесь мина: на трёхзначном номере он даёт ПУСТО, а пусто читается
# как «номера нет». Поэтому только `[0-9]+`, и ни одной цифры литералом.
# ⚠ Прежний признак был `app\.js\?v=([0-9]+)` и умер разбивкой (Cafe13KPG#806):
# `app.js` в разметке нет, а «не нашёл» здесь читается как «номера нет». Теперь
# берутся ВСЕ `?v=NN` и ТРЕБУЕТСЯ их совпадение — это не только переносимость,
# но и новая проверка: номер стоит в 25 ссылках, и поднять его в одной, забыв
# другие, прежний признак пропустил бы молча (взял бы первую).
НОМЕР_РАЗМЕТКИ = re.compile(r'\?v=([0-9]+)')
НОМЕР_ОПИСИ = re.compile(r'v([0-9]+) · [0-9.]+')
# ⚠ у генератора номер берётся СТРОКОЙ объявления: в `catalog.py` есть «v100»
# комментарием (признак автора запускателя, перемерено мной)
НОМЕР_ГЕНЕРАТОРА = re.compile(r"^VERSION = 'v([0-9]+) · ", re.M)


def не_выполнено(текст):
    print('ПРОВЕРКА НЕ ВЫПОЛНЕНА: ' + текст)
    sys.exit(2)


def номер(исходник, образец, что):
    """Номер версии числом. Пусто и не-число — НЕ ноль, а «не измерено»."""
    нашлось = образец.search(исходник)
    if not нашлось:
        не_выполнено(f'{что}: номера не видно (признак {образец.pattern!r} '
                     'не дал числа) — это НЕ «долга нет»')
    return int(нашлось.group(1))


def номер_разметки(разметка, что):
    """Номер версии из разметки: ВСЕ `?v=NN` и обязательно одинаковые.

    ⚠ Пусто — НЕ ноль, а «не измерено»; разные числа — тоже «не измерено», а не
    «возьмём первое»: после разбивки (Cafe13KPG#806) номер стоит в каждой
    ссылке, и половина поднятых номеров — поломка выкладки, при которой
    браузер берёт часть файлов из кеша. Прежний признак брал первое совпадение
    и такую выкладку пропускал бы молча."""
    нашлись = НОМЕР_РАЗМЕТКИ.findall(разметка)
    if not нашлись:
        не_выполнено(f'{что}: номера не видно (признак '
                     f'{НОМЕР_РАЗМЕТКИ.pattern!r} не дал ни одного числа) — '
                     'это НЕ «долга нет»')
    разные = sorted(set(нашлись), key=int)
    if len(разные) > 1:
        не_выполнено(f'{что}: в разметке РАЗНЫЕ номера — ' +
                     ', '.join('v' + н for н in разные) +
                     f' ({len(нашлись)} ссылок). Номер НЕ ИЗМЕРЕН, и это не '
                     'придирка: часть файлов браузер возьмёт из кеша')
    return int(разные[0])


def скачать(адрес, минимум):
    из = subprocess.run(['curl', '-sS', '-f', '-H', 'Cache-Control: no-cache',
                         адрес + ('&' if '?' in адрес else '?') + 'cb=' +
                         str(os.getpid())],
                        capture_output=True)
    if из.returncode != 0 or len(из.stdout) < минимум:
        не_выполнено(f'{адрес} не отдался: ' +
                     (из.stderr.decode('utf-8', 'replace').strip()
                      or f'код {из.returncode}, {len(из.stdout)} байт') +
                     ' — долг НЕ ИЗМЕРЕН')
    return из.stdout


def из_ствола_мягко(путь):
    """Байты из ствола или None. Ствол — СВИДЕТЕЛЬ, а не подлежащее: в образе
    запускателя git может не оказаться вовсе, и приговор обязан выноситься без
    него — по судимому дереву и по выложенному файлу."""
    из = subprocess.run(['git', 'show', f'{СТВОЛ}:{путь}'], capture_output=True)
    return из.stdout if из.returncode == 0 and из.stdout else None


_ПОМОЩНИК = None


def помощник():
    """Модуль tools/klient.py — ОДИН источник правды о составе страницы.
    Под `python3 -I` каталог скрипта в sys.path не кладётся, поэтому по пути."""
    global _ПОМОЩНИК
    if _ПОМОЩНИК is None:
        спец = importlib.util.spec_from_file_location(
            'klient', os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                   'klient.py'))
        м = importlib.util.module_from_spec(спец)
        спец.loader.exec_module(м)
        _ПОМОЩНИК = м
    return _ПОМОЩНИК


def свод_по(читатель, мягко=False):
    """Свод слепков страницы, собранный ЧИТАТЕЛЕМ (дерево, ствол, коммит, Pages).

    ⚠ Состав каждая сторона называет СВОИМ `index.html`, а не общим списком:
    иначе во время разбивки (Cafe13KPG#806) ствол с одним файлом и ветка с
    двадцатью двумя сравнивались бы по списку одной из них, и прибор назвал бы
    «пропал файл» там, где у стороны его и не было. Сличение судит только при
    РАВНЫХ номерах, и там составы обязаны совпадать.

    `мягко=True` — для ствола и коммита: они СВИДЕТЕЛИ, и без них приговор
    остаётся (возвращается None), а не превращается в «не выполнено»."""
    м = помощник()
    try:
        return м.свод(м.слепки_страницы(читатель))
    except м.НеВыполнено as е:
        if мягко:
            return None
        не_выполнено(f'состав страницы не собрался: {е} — долг НЕ ИЗМЕРЕН')


def читатель_ствола(путь):
    return из_ствола_мягко(путь)


def читатель_коммита(коммит):
    def читать(путь):
        из = subprocess.run(['git', 'show', f'{коммит}:{путь}'],
                            capture_output=True)
        return из.stdout if из.returncode == 0 and из.stdout else None
    return читать


def читатель_pages():
    """Файлы с Pages. Отказ любого — «не выполнено»: долг НЕ ИЗМЕРЕН.

    ⚠ ЦЕНА названа здесь, чтобы не считалась бесплатной: прежде скачивались
    ДВА файла (разметка и `app.js`), теперь — весь состав страницы. Замер мой
    02.11.2026 по ВЫЛОЖЕННОМУ (ещё не разбитому) клиенту: 5 запросов, 0,7 с.
    После выкладки разбивки состав станет 26 файлов — это не замер, а счёт
    строк карты по дереву ветки, сети на нём ещё не было. Поверхность отказа
    растёт ровно во столько же раз: не отдался один файл — приговора нет вовсе.
    Это сознательный выбор: свод по ЧАСТИ состава был бы правдоподобным
    числом, а оно хуже отказа."""
    память = {}

    def читать(путь):
        if путь not in память:
            память[путь] = скачать(ВЫЛОЖЕНО + путь, 1)
        return память[путь]
    return читать


def свод_на_коммите_описи():
    """Свод страницы на коммите, где ОПИСЬ правили последний раз, или None.

    ⚠ Этот слепок — ТРЕТИЙ приговор, и он разводит две причины, которые прежде
    склеивались в одну. Прежний текст говорил «значит уехала правка без
    подъёма номера» — вывод, которого прибор НЕ МЕРИЛ. 02.11.2026 он выбрал
    ровно неверную половину: опись v142 была самосогласованна в своём коммите
    `84d9aa1` (там `app.js` даёт тот же `d21d1657…`), а разошлась ПОСЛЕ —
    автор влил в ветку ствол, и влитый ствол принёс чужой `app.js` (правка
    `#224`, свой номер v141 у неё был поднят). Правки без номера не было
    вовсе. Нашёл и перемерил `cafe13kpg-coordinator-2`, различитель его.

    Ствол и история — СВИДЕТЕЛИ: без git приговор остаётся, но без причины."""
    гдe = subprocess.run(['git', 'log', '-1', '--format=%H', '--', ВИДИМОСТЬ],
                         capture_output=True)
    if гдe.returncode != 0 or not гдe.stdout.strip():
        return None
    коммит = гдe.stdout.decode('utf-8', 'replace').strip()
    return свод_по(читатель_коммита(коммит), мягко=True)


def из_ствола(путь):
    из = subprocess.run(['git', 'show', f'{СТВОЛ}:{путь}'], capture_output=True)
    if из.returncode != 0 or not из.stdout:
        не_выполнено(f'{СТВОЛ}:{путь} не прочитался: ' +
                     (из.stderr.decode('utf-8', 'replace').strip()
                      or f'код {из.returncode}') + ' — долг НЕ ИЗМЕРЕН')
    return из.stdout


def свод_описи(сырьё):
    """Свод страницы, с которой снята опись.

    ⚠ Файл несёт И карту `слепки_страницы`, И её свод, поэтому свод здесь
    ПЕРЕСЧИТЫВАЕТСЯ из карты и сверяется с записанным. Иначе правка одного
    числа руками (или прибором прежней редакции) давала бы согласованный с
    виду файл, и сличение судило бы по числу, которого ничто не подпирает."""
    try:
        дано = json.loads(сырьё)
    except ValueError as беда:
        не_выполнено(f'{ВИДИМОСТЬ} не разобрался: {беда} — долг НЕ ИЗМЕРЕН')
    карта = дано.get('слепки_страницы')
    if not isinstance(карта, dict) or not карта:
        не_выполнено(f'в {ВИДИМОСТЬ} нет карты «слепки_страницы» — файл снят '
                     'прибором прежней редакции (до Cafe13KPG#806), долг НЕ ИЗМЕРЕН')
    записан = дано.get('свод_слепков')
    пересчитан = помощник().свод(карта)
    if not isinstance(записан, str) or not re.fullmatch('[0-9a-f]{64}', записан):
        не_выполнено(f'в {ВИДИМОСТЬ} нет свода слепков — долг НЕ ИЗМЕРЕН')
    if записан != пересчитан:
        не_выполнено(f'в {ВИДИМОСТЬ} свод не сходится с его же картой '
                     f'({записан[:16]}… против {пересчитан[:16]}… по '
                     f'{len(карта)} строкам) — файл правлен не прибором, '
                     'долг НЕ ИЗМЕРЕН')
    return пересчитан


def приговор(на_pages, в_описи, sha_pages, sha_ствола, sha_дерева,
             sha_описи, в_описи_ствола=None, в_генераторе=None,
             sha_на_коммите=None):
    """Числа и слепки → (код, строки). Чистая, чтобы судить её подлогами."""
    долг = на_pages - в_описи
    # «долг −1» читался бы как долг; при описи впереди счёт называется иначе
    # «долг N из 3» читалось как ворота; порог больше не запрещает
    строки = [f'Pages v{на_pages} · опись v{в_описи} · ' +
              (f'опись впереди на {-долг}' if долг < 0
               else f'отставание {долг} (порог {ПРЕДЕЛ})')]
    красное = []

    if в_описи > на_pages:
        # ⚠ Опись ВПЕРЕДИ выложенного — состояние законное, и у него свой
        # случай: опись снимают ПОД голову, которая уедет в ствол, а Pages
        # отдаёт прежний файл до мерджа. Первая редакция звала это «признак
        # сломан» и держала публикацию ровно того релиза, ради которого опись
        # и снимали (замер мой на порядке архитектора: опись v109 при Pages
        # v108 → красное). Отличает одно: чей клиент у описи. Ствольный —
        # ждём публикации; ничей — признак правда сломан.
        # ⚠ Окон ДВА, и в нашем порядке работает ПЕРВОЕ. «Опись снята, ещё
        # НЕ смерджено»: ствол пока прежний, а клиент описи равен клиенту
        # СУДИМОЙ головы — дерева, которое поедет в ствол. «Смерджено, Pages
        # не выложил»: ствол уже новый. Первая редакция знала только второе и
        # держала публикацию в первом; чтение архитектора по коду, решение
        # координатора — сличать с судимой головой И со стволом, называя оба.
        свой = sha_описи == sha_дерева
        ствольный = sha_описи == sha_ствола
        if свой or ствольный:
            строки.append(
                f'опись снята под голову v{в_описи}, ещё не опубликованную '
                f'(на Pages v{на_pages}); клиент описи: судимое дерево — '
                f'{"сошёлся" if свой else "НЕ сошёлся"}, ствол — '
                f'{"сошёлся" if ствольный else "НЕ сошёлся"} — публикации '
                'не держит')
        else:
            красное.append(f'опись называет v{в_описи} впереди выложенного '
                           f'v{на_pages}, а её клиент {sha_описи[:16]}… не '
                           f'совпал ни с судимым деревом {sha_дерева[:16]}…, '
                           f'ни со стволом {sha_ствола[:16]}… — признак сломан')
    elif долг >= ПРЕДЕЛ:
        # ⚠ ПРЕДУПРЕЖДЕНИЕ, а не приговор: код остаётся 0. Предел снят решением
        # владельца 29.10.2026 (опись не ворота, расхождения идут карточками),
        # и красное, которое ничего не запрещает, выключают вместе с настоящим.
        строки.append(f'опись отстала на {долг} — больше порога {ПРЕДЕЛ}; '
                      'расхождение идёт карточкой, публикации не держит')

    # ⚠ Слепки судят ТОЛЬКО при равных номерах. Номер версии лежит ВНУТРИ
    # `app.js`, поэтому другой номер — это всегда другой слепок: при долге 1–2
    # расхождение слепков есть само законное отставание, и краснеть на нём
    # значит краснеть на КАЖДОЙ здоровой публикации. Судит там счёт номеров.
    if долг > 0:
        if sha_описи == sha_pages:
            красное.append(f'опись называет v{в_описи}, а её клиент — тот же, '
                           f'что у выложенного v{на_pages}: номер в описи '
                           'разошёлся с её же клиентом')
        else:
            строки.append(f'клиент описи отстал на {долг} — при разных номерах '
                          'так и положено, слепки здесь не судят')
    elif долг == 0:
        if sha_описи == sha_pages:
            строки.append('клиент описи = выложенный')
        elif sha_описи == sha_ствола:
            # Опись снята с нового ствола, а Pages ещё отдаёт прежний файл.
            # Работа сделана; сошлось бы и по сети — через минуты сборки.
            строки.append('клиент описи = ствол, а Pages отдаёт прежний — '
                          'выкладка в пути, это не долг')
        elif sha_на_коммите and sha_описи == sha_на_коммите:
            # ⚠ ТРЕТИЙ ПРИГОВОР: слепок был верен В СВОЁМ КОММИТЕ, разошёлся
            # ПОСЛЕ. Это наш записанный класс — влитый ствол тоже правка после
            # доказательства, причём чужая, — только обнулился не прогон, а
            # слепок описи. Лечение здесь ПЕРЕСЪЁМКА, и она не маскировка:
            # гасить нечего, правки без номера нет.
            красное.append('номера равны, а клиент описи другой — НО слепок был '
                           f'верен в своём коммите ({sha_описи[:16]}… = app.js '
                           'там же). Значит разошлось ПОСЛЕ съёмки: в ветку '
                           'влили ствол либо уехал чужой мердж. Правки без '
                           'подъёма номера здесь НЕТ — опись пересобрать')
        else:
            # Различителя нет (без git) либо слепок не сошёлся и с коммитом
            # описи. Причину НЕ НАЗЫВАЕМ: их две, и прибор не мерил, какая.
            чем = ('а на коммите описи — ' + sha_на_коммите[:16] + '…'
                   if sha_на_коммите else
                   'коммит описи не прочитался (git недоступен), причина НЕ РАЗВЕДЕНА')
            красное.append('номера равны, а клиент описи другой: её '
                           f'свод {sha_описи[:16]}… не совпал ни с '
                           f'выложенным {sha_pages[:16]}…, ни со ствольным '
                           f'{sha_ствола[:16]}…, {чем}. ДВЕ причины, и какая — '
                           'прибор не мерил: либо правка уехала без подъёма '
                           'номера, либо опись снята не с того дерева')

    # ⚠ Номер генератора против номера описи. По Cafe13KPG#605 `catalog.py`
    # едет ВМЕСТЕ С ОПИСЬЮ, а не с правкой клиента (замер: на голове dbc04dd
    # оба стояли на v105 при клиенте v109), поэтому ворота автора их не видят
    # нарочно — и внутри описного PR они могут разойтись молча. Предмет мой:
    # предел мерил только `screens.html` против Pages. Признак и разбор —
    # frontend-upravlenie-ec, перемерено мной.
    if в_генераторе is not None and в_генераторе != в_описи:
        красное.append(f'генератор на v{в_генераторе}, а опись на v{в_описи} — '
                       'опись собрана не под свой номер: либо номер поднят без '
                       'пересборки, либо пересобрана прежним генератором')
    if в_описи_ствола is not None and в_описи_ствола != в_описи:
        строки.append(f'свидетель: в стволе опись пока v{в_описи_ствола} — '
                      'судится опись СУДИМОГО дерева, она и поедет в ствол')
    return (1 if красное else 0), строки + ['КРАСНОЕ: ' + с for с in красное]


def слепок(номер, правка=False):
    """Слепок клиента версии `номер` — для фикстур самопроверки.

    ⚠ ИНВАРИАНТ ПРЕДМЕТА, записанный здесь кодом, а не прозой: номер версии
    лежит ВНУТРИ `app.js`, поэтому слепок выводится ИЗ номера — разный номер
    это ВСЕГДА разный слепок. `правка=True` — изменение клиента БЕЗ подъёма
    номера, то есть другой слепок при том же номере (невидимая выкладка).
    """
    return f'{номер:062d}ff' if правка else f'{номер:064d}'


ВОЗМОЖНЫЕ = {слепок(н, п) for н in range(1, 1000) for п in (False, True)}


def выводилка_исправна():
    """Свойства САМОЙ `слепок()`, проверенные не через неё же.

    ⚠ Сторож фикстуры `согласована()` выводит «возможное» той же функцией,
    которой строит фикстуры, поэтому СЛОМАННУЮ выводилку он видеть не может
    по построению (посадка архитектора, 29.10.2026: `слепок()` возвращает
    одно и то же всем номерам — сторож молчит). Приговор ловит это как
    расхождение трёх случаев, но ОДИН из них переворачивается в ложное
    зелёное («невидимая выкладка … → код 0, ждали 1»), а причину не называет
    ни один: читатель пойдёт искать дефект в предикате, которого там нет.
    Поэтому свойства выводилки проверяются отдельно и ПЕРЕД случаями:
    сломана выводилка — все фикстуры бессмысленны, и считать по ним нечего.
    """
    беды = []
    if слепок(105) == слепок(106):
        беды.append('слепок() не различает номера: номер лежит внутри '
                    'app.js, значит разный номер обязан давать разный слепок')
    if слепок(105) == слепок(105, True):
        беды.append('слепок() не различает правку БЕЗ подъёма номера — '
                    'невидимую выкладку станет нечем выразить')
    номера = range(100, 110)
    if len({слепок(н) for н in номера}) != len(list(номера)):
        беды.append('слепок() не взаимно однозначен на номерах 100–109')
    return беды


def согласована(на_pages, sha_pages, sha_ствола, sha_описи):
    """Беды фикстуры, описывающей НЕВОЗМОЖНОЕ состояние.

    Куплено дефектом: первая редакция подавала разные номера при одинаковом
    слепке клиента, и девять входов были зелены ПО ПОСТРОЕНИЮ, пока прибор
    краснел на каждой здоровой публикации. Проверка, которой нельзя скормить
    невозможный вход, этого не допускает — поэтому инвариант стоит прибором,
    а не только правилом.
    """
    беды = []
    for что, sha in (('выложенного', sha_pages), ('ствольного', sha_ствола),
                     ('описи', sha_описи)):
        if sha not in ВОЗМОЖНЫЕ:
            беды.append(f'слепок {что} клиента {sha[:8]}… не выводится ни из '
                        'одного номера — такого клиента не бывает')
    if sha_pages in ВОЗМОЖНЫЕ and sha_pages not in (слепок(на_pages),
                                                    слепок(на_pages, True)):
        беды.append(f'слепок выложенного клиента не выводится из его же '
                    f'номера v{на_pages} — номер лежит внутри app.js')
    return беды


def подлоги_состава():
    """Слепки страницы — своими входами. Фикстура тут ЧИТАТЕЛЬ, а не каталог.

    ⚠ Почему читателем, а не деревом на диске: тот же читатель применяется к
    стволу, коммиту и Pages, то есть подлог бьёт в ТУ дорогу, которой прибор
    ходит на бою. Каталог во временной папке проверял бы четвёртую.
    """
    м = помощник()
    беды = []

    def читатель(файлы):
        return lambda путь: файлы.get(путь)

    ЗДОРОВО = {
        'index.html': b'<link rel=x href="styles.css?v=7">'
                      b'<script src="https://telegram.org/js/t.js"></script>'
                      b'<script src="js/01.js?v=7"></script>',
        'styles.css': b'body{}',
        'js/01.js': b'var A = 1;',
    }
    карта = м.слепки_страницы(читатель(ЗДОРОВО))
    свод_здоровый = м.свод(карта)
    ждали = ['index.html', 'styles.css', 'https://telegram.org/js/t.js', 'js/01.js']
    ладно = list(карта) == ждали
    print(f'  {"сошлось" if ладно else "РАЗОШЛОСЬ"}: состав и ПОРЯДОК по разметке '
          f'→ {list(карта)}')
    if not ладно:
        беды.append('состав или порядок слепков не по разметке')
    ладно = карта['https://telegram.org/js/t.js'] == м.ВНЕ_ДЕРЕВА
    print(f'  {"сошлось" if ладно else "РАЗОШЛОСЬ"}: внешняя — строкой '
          f'«{карта["https://telegram.org/js/t.js"]}», а не слепком')
    if not ладно:
        беды.append('внешняя ссылка захеширована или пропущена')

    # ⚠ ГЛАВНЫЙ случай замены признака: правка СТИЛЯ меняет свод. Прежний
    # признак (один sha256 `app.js`) её не видел вовсе, и опись старела
    # зелёной от правки отрисовки. Без этого случая замена ничем не куплена.
    for что, чем in (('styles.css', b'body{color:red}'),
                     ('index.html', ЗДОРОВО['index.html'] + b'<!-- x -->')):
        иначе = dict(ЗДОРОВО, **{что: чем})
        assert иначе[что] != ЗДОРОВО[что], 'подлог не применился'
        новый = м.свод(м.слепки_страницы(читатель(иначе)))
        ладно = новый != свод_здоровый
        print(f'  {"сошлось" if ладно else "РАЗОШЛОСЬ"}: правка «{что}» меняет свод '
              f'({свод_здоровый[:8]}… → {новый[:8]}…)')
        if not ладно:
            беды.append(f'свод слеп к правке {что}')

    # Порядок подключения значащий: переставленные файлы — другая страница.
    переставлено = dict(ЗДОРОВО, **{'index.html':
        b'<script src="js/01.js?v=7"></script><link rel=x href="styles.css?v=7">'})
    новый = м.свод(м.слепки_страницы(читатель(переставлено)))
    ладно = новый != свод_здоровый
    print(f'  {"сошлось" if ладно else "РАЗОШЛОСЬ"}: перестановка подключений '
          f'меняет свод')
    if not ладно:
        беды.append('свод слеп к порядку подключения')

    # Отказы — «не выполнено», а не «сошлось»: пустая карта зелёной не бывает.
    отказы = (
        ('ссылка в ОДИНАРНЫХ кавычках',
         dict(ЗДОРОВО, **{'index.html': b"<script src='js/01.js'></script>"}),
         'ОДИНАРНЫХ'),
        ('ссылка есть, файла нет',
         dict(ЗДОРОВО, **{'index.html': b'<script src="js/no-such.js"></script>'}),
         'а файла нет'),
        ('самой разметки нет', {}, 'не прочитался'),
    )
    for имя, файлы, слово in отказы:
        try:
            м.слепки_страницы(читатель(файлы))
            print(f'  РАЗОШЛОСЬ: {имя} → ПРОПУЩЕНО, карта собралась')
            беды.append(имя + ' пропущен')
        except м.НеВыполнено as е:
            ладно = слово in str(е)
            print(f'  {"сошлось" if ладно else "РАЗОШЛОСЬ"}: {имя} → НЕ ВЫПОЛНЕНО '
                  f'«{str(е)[:54]}…»')
            if not ладно:
                беды.append(имя + ': отказ не о том')

    # ⚠ Подлог в САМ ПРИЗНАК: сторож «признаки разметки разошлись» обязан
    # краснеть, когда слепки перестают видеть скрипты. Без него признак можно
    # сузить и не заметить — ровно так умирают проверки на отсутствие.
    цел = м.ССЫЛКА
    сломан = re.compile(r'\bhref="([^"]*)"')
    assert сломан.pattern != цел.pattern, 'подлог не применился'
    м.ССЫЛКА = сломан
    try:
        м.слепки_страницы(читатель(ЗДОРОВО))
        print('  РАЗОШЛОСЬ: суженный признак слепков → ПРОПУЩЕНО')
        беды.append('сторож «признаки разметки разошлись» мёртв')
    except м.НеВыполнено as е:
        ладно = 'разошлись' in str(е)
        print(f'  {"сошлось" if ладно else "РАЗОШЛОСЬ"}: суженный признак слепков '
              f'→ НЕ ВЫПОЛНЕНО «{str(е)[:54]}…»')
        if not ладно:
            беды.append('сторож разошедшихся признаков сказал не о том')
    finally:
        м.ССЫЛКА = цел

    # Свод против своей же карты: правка одного числа руками не проходит.
    файл = json.dumps({'слепки_страницы': карта, 'свод_слепков': свод_здоровый},
                      ensure_ascii=False)
    из = subprocess.run([sys.executable, '-I', __file__, '--подлог-свода', файл],
                        capture_output=True, text=True)
    ладно = из.returncode == 0 and 'сошёлся' in из.stdout
    print(f'  {"сошлось" if ладно else "РАЗОШЛОСЬ"}: свод сходится со своей картой '
          f'→ {из.stdout.strip()[:48]}')
    if not ладно:
        беды.append('свод не сошёлся со своей же картой')
    кривой = json.dumps({'слепки_страницы': карта, 'свод_слепков': 'f' * 64},
                        ensure_ascii=False)
    из = subprocess.run([sys.executable, '-I', __file__, '--подлог-свода', кривой],
                        capture_output=True, text=True)
    ладно = из.returncode == 2 and 'не сходится с его же картой' in из.stdout
    print(f'  {"сошлось" if ладно else "РАЗОШЛОСЬ"}: свод правлен рукой → код '
          f'{из.returncode}, {из.stdout.strip()[:52]}')
    if not ладно:
        беды.append('подменённый свод прошёл мимо сверки с картой')
    return беды


