def не_выполнено(текст):
    print('ПРОВЕРКА НЕ ВЫПОЛНЕНА: ' + текст)
    sys.exit(2)


def номер(исходник, образец, что):
    """Номер версии числом. Пусто и не-число — НЕ ноль, а «не измерено»."""
    нашлось = образец.search(исходник)
    if not нашлось:
        не_выполнено(f'{что}: номера не видно (признак {образец.pattern!r} '
                     'не дал числа) — это НЕ «долга нет»')
    return int(нашлось.group(1))


def скачать(адрес, минимум):
    из = subprocess.run(['curl', '-sS', '-f', '-H', 'Cache-Control: no-cache',
                         адрес + ('&' if '?' in адрес else '?') + 'cb=' +
                         str(__import__('os').getpid())],
                        capture_output=True)
    if из.returncode != 0 or len(из.stdout) < минимум:
        не_выполнено(f'{адрес} не отдался: ' +
                     (из.stderr.decode('utf-8', 'replace').strip()
                      or f'код {из.returncode}, {len(из.stdout)} байт') +
                     ' — долг НЕ ИЗМЕРЕН')
    return из.stdout


def из_ствола_мягко(путь):
    """Байты из ствола или None. Ствол — СВИДЕТЕЛЬ, а не подлежащее: в образе
    запускателя git может не оказаться вовсе, и приговор обязан выноситься без
    него — по судимому дереву и по выложенному файлу."""
    из = subprocess.run(['git', 'show', f'{СТВОЛ}:{путь}'], capture_output=True)
    return из.stdout if из.returncode == 0 and из.stdout else None


def из_ствола(путь):
    из = subprocess.run(['git', 'show', f'{СТВОЛ}:{путь}'], capture_output=True)
    if из.returncode != 0 or not из.stdout:
        не_выполнено(f'{СТВОЛ}:{путь} не прочитался: ' +
                     (из.stderr.decode('utf-8', 'replace').strip()
                      or f'код {из.returncode}') + ' — долг НЕ ИЗМЕРЕН')
    return из.stdout


def клиент_описи(сырьё):
    try:
        дано = json.loads(сырьё)
    except ValueError as беда:
        не_выполнено(f'{ВИДИМОСТЬ} не разобрался: {беда} — долг НЕ ИЗМЕРЕН')
    sha = дано.get('клиент_sha256')
    if not isinstance(sha, str) or not re.fullmatch('[0-9a-f]{64}', sha):
        не_выполнено(f'в {ВИДИМОСТЬ} нет поля клиент_sha256 — долг НЕ ИЗМЕРЕН')
    return sha


def приговор(на_pages, в_описи, sha_pages, sha_ствола, sha_дерева,
             sha_описи, в_описи_ствола=None, в_генераторе=None):
    """Числа и слепки → (код, строки). Чистая, чтобы судить её подлогами."""
    долг = на_pages - в_описи
    # «долг −1» читался бы как долг; при описи впереди счёт называется иначе
    # «долг N из 3» читалось как ворота; порог больше не запрещает
    строки = [f'Pages v{на_pages} · опись v{в_описи} · ' +
              (f'опись впереди на {-долг}' if долг < 0
               else f'отставание {долг} (порог {ПРЕДЕЛ})')]
    красное = []

    if в_описи > на_pages:
        # ⚠ Опись ВПЕРЕДИ выложенного — состояние законное, и у него свой
        # случай: опись снимают ПОД голову, которая уедет в ствол, а Pages
        # отдаёт прежний файл до мерджа. Первая редакция звала это «признак
        # сломан» и держала публикацию ровно того релиза, ради которого опись
        # и снимали (замер мой на порядке архитектора: опись v109 при Pages
        # v108 → красное). Отличает одно: чей клиент у описи. Ствольный —
        # ждём публикации; ничей — признак правда сломан.
        # ⚠ Окон ДВА, и в нашем порядке работает ПЕРВОЕ. «Опись снята, ещё
        # НЕ смерджено»: ствол пока прежний, а клиент описи равен клиенту
        # СУДИМОЙ головы — дерева, которое поедет в ствол. «Смерджено, Pages
        # не выложил»: ствол уже новый. Первая редакция знала только второе и
        # держала публикацию в первом; чтение архитектора по коду, решение
        # координатора — сличать с судимой головой И со стволом, называя оба.
        свой = sha_описи == sha_дерева
        ствольный = sha_описи == sha_ствола
        if свой or ствольный:
            строки.append(
                f'опись снята под голову v{в_описи}, ещё не опубликованную '
                f'(на Pages v{на_pages}); клиент описи: судимое дерево — '
                f'{"сошёлся" if свой else "НЕ сошёлся"}, ствол — '
                f'{"сошёлся" if ствольный else "НЕ сошёлся"} — публикации '
                'не держит')
        else:
            красное.append(f'опись называет v{в_описи} впереди выложенного '
                           f'v{на_pages}, а её клиент {sha_описи[:16]}… не '
                           f'совпал ни с судимым деревом {sha_дерева[:16]}…, '
                           f'ни со стволом {sha_ствола[:16]}… — признак сломан')
    elif долг >= ПРЕДЕЛ:
        # ⚠ ПРЕДУПРЕЖДЕНИЕ, а не приговор: код остаётся 0. Предел снят решением
        # владельца 29.10.2026 (опись не ворота, расхождения идут карточками),
        # и красное, которое ничего не запрещает, выключают вместе с настоящим.
        строки.append(f'опись отстала на {долг} — больше порога {ПРЕДЕЛ}; '
                      'расхождение идёт карточкой, публикации не держит')

    # ⚠ Слепки судят ТОЛЬКО при равных номерах. Номер версии лежит ВНУТРИ
    # `app.js`, поэтому другой номер — это всегда другой слепок: при долге 1–2
    # расхождение слепков есть само законное отставание, и краснеть на нём
    # значит краснеть на КАЖДОЙ здоровой публикации. Судит там счёт номеров.
    if долг > 0:
        if sha_описи == sha_pages:
            красное.append(f'опись называет v{в_описи}, а её клиент — тот же, '
                           f'что у выложенного v{на_pages}: номер в описи '
                           'разошёлся с её же клиентом')
        else:
            строки.append(f'клиент описи отстал на {долг} — при разных номерах '
                          'так и положено, слепки здесь не судят')
    elif долг == 0:
        if sha_описи == sha_pages:
            строки.append('клиент описи = выложенный')
        elif sha_описи == sha_ствола:
            # Опись снята с нового ствола, а Pages ещё отдаёт прежний файл.
            # Работа сделана; сошлось бы и по сети — через минуты сборки.
            строки.append('клиент описи = ствол, а Pages отдаёт прежний — '
                          'выкладка в пути, это не долг')
        else:
            красное.append('номера равны, а клиент описи другой: её '
                           f'клиент_sha256 {sha_описи[:16]}… не совпал ни с '
                           f'выложенным {sha_pages[:16]}…, ни со ствольным '
                           f'{sha_ствола[:16]}… — значит уехала правка без '
                           'подъёма номера, и человек остался на прежнем файле')

    # ⚠ Номер генератора против номера описи. По Cafe13KPG#605 `catalog.py`
    # едет ВМЕСТЕ С ОПИСЬЮ, а не с правкой клиента (замер: на голове dbc04dd
    # оба стояли на v105 при клиенте v109), поэтому ворота автора их не видят
    # нарочно — и внутри описного PR они могут разойтись молча. Предмет мой:
    # предел мерил только `screens.html` против Pages. Признак и разбор —
    # frontend-upravlenie-ec, перемерено мной.
    if в_генераторе is not None and в_генераторе != в_описи:
        красное.append(f'генератор на v{в_генераторе}, а опись на v{в_описи} — '
                       'опись собрана не под свой номер: либо номер поднят без '
                       'пересборки, либо пересобрана прежним генератором')
    if в_описи_ствола is not None and в_описи_ствола != в_описи:
        строки.append(f'свидетель: в стволе опись пока v{в_описи_ствола} — '
                      'судится опись СУДИМОГО дерева, она и поедет в ствол')
    return (1 if красное else 0), строки + ['КРАСНОЕ: ' + с for с in красное]


def слепок(номер, правка=False):
    """Слепок клиента версии `номер` — для фикстур самопроверки.

    ⚠ ИНВАРИАНТ ПРЕДМЕТА, записанный здесь кодом, а не прозой: номер версии
    лежит ВНУТРИ `app.js`, поэтому слепок выводится ИЗ номера — разный номер
    это ВСЕГДА разный слепок. `правка=True` — изменение клиента БЕЗ подъёма
    номера, то есть другой слепок при том же номере (невидимая выкладка).
    """
    return f'{номер:062d}ff' if правка else f'{номер:064d}'


ВОЗМОЖНЫЕ = {слепок(н, п) for н in range(1, 1000) for п in (False, True)}


def выводилка_исправна():
    """Свойства САМОЙ `слепок()`, проверенные не через неё же.

    ⚠ Сторож фикстуры `согласована()` выводит «возможное» той же функцией,
    которой строит фикстуры, поэтому СЛОМАННУЮ выводилку он видеть не может
    по построению (посадка архитектора, 29.10.2026: `слепок()` возвращает
    одно и то же всем номерам — сторож молчит). Приговор ловит это как
    расхождение трёх случаев, но ОДИН из них переворачивается в ложное
    зелёное («невидимая выкладка … → код 0, ждали 1»), а причину не называет
    ни один: читатель пойдёт искать дефект в предикате, которого там нет.
    Поэтому свойства выводилки проверяются отдельно и ПЕРЕД случаями:
    сломана выводилка — все фикстуры бессмысленны, и считать по ним нечего.
    """
    беды = []
    if слепок(105) == слепок(106):
        беды.append('слепок() не различает номера: номер лежит внутри '
                    'app.js, значит разный номер обязан давать разный слепок')
    if слепок(105) == слепок(105, True):
        беды.append('слепок() не различает правку БЕЗ подъёма номера — '
                    'невидимую выкладку станет нечем выразить')
    номера = range(100, 110)
    if len({слепок(н) for н in номера}) != len(list(номера)):
        беды.append('слепок() не взаимно однозначен на номерах 100–109')
    return беды


def согласована(на_pages, sha_pages, sha_ствола, sha_описи):
    """Беды фикстуры, описывающей НЕВОЗМОЖНОЕ состояние.

    Куплено дефектом: первая редакция подавала разные номера при одинаковом
    слепке клиента, и девять входов были зелены ПО ПОСТРОЕНИЮ, пока прибор
    краснел на каждой здоровой публикации. Проверка, которой нельзя скормить
    невозможный вход, этого не допускает — поэтому инвариант стоит прибором,
    а не только правилом.
    """
    беды = []
    for что, sha in (('выложенного', sha_pages), ('ствольного', sha_ствола),
                     ('описи', sha_описи)):
        if sha not in ВОЗМОЖНЫЕ:
            беды.append(f'слепок {что} клиента {sha[:8]}… не выводится ни из '
                        'одного номера — такого клиента не бывает')
    if sha_pages in ВОЗМОЖНЫЕ and sha_pages not in (слепок(на_pages),
                                                    слепок(на_pages, True)):
        беды.append(f'слепок выложенного клиента не выводится из его же '
                    f'номера v{на_pages} — номер лежит внутри app.js')
    return беды


def самопроверка():
    """Каждый приговор — своим входом; зелёное на подлоге хуже отсутствия.

    Фикстуры строятся `слепок()`, то есть инвариант предмета в них соблюдён
    по построению, а `согласована()` этого ещё и ТРЕБУЕТ — невозможный вход
    самопроверка отвергает сама, не дойдя до приговора.
    """
    сломана = выводилка_исправна()
    if сломана:
        for с in сломана:
            print('  ВЫВОДИЛКА СЛЕПКОВ СЛОМАНА: ' + с)
        print('самопроверка: РАЗОШЛАСЬ — фикстуры строить нечем')
        return 1

    случаи = [
        ('здоровый ход: опись на один номер позади',
         (106, 105, слепок(106), слепок(106), слепок(106), слепок(105)), 0),
        ('два позади — ещё можно',
         (107, 105, слепок(107), слепок(107), слепок(107), слепок(105)), 0),
        # ⚠ ждём 0: предел предупреждает, а не запрещает (решение владельца
        # 29.10.2026). Если кто-то вернёт здесь 1, этот случай покраснеет.
        ('порог перейдён — предупреждение, не приговор',
         (108, 105, слепок(108), слепок(108), слепок(108), слепок(105)), 0),
        ('номера сошлись, клиент сошёлся',
         (105, 105, слепок(105), слепок(105), слепок(105), слепок(105)), 0),
        ('выкладка в пути: опись = ствол, Pages прежний',
         (105, 105, слепок(105), слепок(105, True), слепок(105, True),
          слепок(105, True)), 0),
        ('невидимая выкладка: номера РАВНЫ, клиент другой',
         (105, 105, слепок(105, True), слепок(105, True),
          слепок(105, True), слепок(105)), 1),
        ('генератор и опись на одном номере',
         (109, 109, слепок(109), слепок(109), слепок(109), слепок(109)), 0,
         {'в_генераторе': 109}),
        ('генератор поднят, опись не пересобрана',
         (109, 109, слепок(109), слепок(109), слепок(109), слепок(109)), 1,
         {'в_генераторе': 110}),
        ('опись пересобрана прежним генератором',
         (109, 109, слепок(109), слепок(109), слепок(109), слепок(109)), 1,
         {'в_генераторе': 108}),
        ('номер описи врёт о её клиенте',
         (106, 105, слепок(106), слепок(106), слепок(106), слепок(106)), 1),
        # Окно 1 — наше: вход построен ПО ОКНУ, то есть ствол ещё v108.
        # Прежняя фикстура ставила ствол v109 и была зелена по построению:
        # до мерджа ствол таким быть НЕ МОЖЕТ (чтение архитектора, второй
        # раз за вечер на этом же приборе).
        ('окно 1: опись снята, ещё НЕ смерджено (ствол v108)',
         (108, 109, слепок(108), слепок(108), слепок(109), слепок(109)), 0),
        ('окно 2: смерджено (ствол v109), Pages не выложил',
         (108, 109, слепок(108), слепок(109), слепок(109), слепок(109)), 0),
        ('опись впереди, а её клиент ни ствольный, ни судимый',
         (108, 109, слепок(108), слепок(108), слепок(109), слепок(999)), 1),
    ]
    беды = []
    for случай in случаи:
        имя, довод, ждём = случай[0], случай[1], случай[2]
        ещё = случай[3] if len(случай) > 3 else {}
        плохо = согласована(довод[0], довод[2], довод[3], довод[5])
        if плохо:
            print(f'  ФИКСТУРА НЕВОЗМОЖНА: {имя} — {плохо[0]}')
            беды.append('фикстура: ' + имя)
            continue
        дано = приговор(*довод, **ещё)[0]
        print(f'  {"сошлось" if дано == ждём else "РАЗОШЛОСЬ"}: {имя} '
              f'→ код {дано}, ждали {ждём}')
        if дано != ждём:
            беды.append(имя)

    # ⚠ И сам сторож фикстуры судится подлогом: вход, который купил дефект, —
    # разные номера при одинаковом слепке, записанном РУКОЙ, а не из номера.
    рукой = ('фикстура первой редакции: 107/105 при слепке руками',
             (107, 105, 'a' * 64, 'a' * 64, 'a' * 64, 'a' * 64))
    плохо = согласована(рукой[1][0], рукой[1][2], рукой[1][3], рукой[1][5])
    print(f'  {"сошлось" if плохо else "РАЗОШЛОСЬ"}: сторож фикстуры на входе '
          f'«{рукой[0]}» → {плохо[0][:60] if плохо else "ПРОПУСТИЛ"}')
    if not плохо:
        беды.append('сторож фикстуры пропустил невозможный вход')

    # Подлоги под признак номера. Проверять надо не «нашёл число», а «не нашёл
    # и СКАЗАЛ об этом»: в первой редакции именно здесь рождался ложный ноль.
    for имя, разметка in (('признак есть, числа нет', '<script src="app.js?v=">'),
                          ('app.js нет вовсе', '<script src="other.js">'),
                          ('пусто', '')):
        из = subprocess.run([sys.executable, '-I', __file__, '--подлог-номера',
                             разметка], capture_output=True, text=True)
        ладно = из.returncode == 2 and 'НЕ ВЫПОЛНЕНА' in из.stdout
        print(f'  {"сошлось" if ладно else "РАЗОШЛОСЬ"}: {имя} → код '
              f'{из.returncode}, {из.stdout.strip()[:60]}')
        if not ладно:
            беды.append(имя)

    print('самопроверка: ' + ('сошлась' if not беды
                              else 'РАЗОШЛАСЬ — ' + '; '.join(беды)))
    return 1 if беды else 0


def main(доводы):
    if '--подлог-номера' in доводы:
        номер(доводы[доводы.index('--подлог-номера') + 1],
              НОМЕР_РАЗМЕТКИ, 'подлог')
        print('подлог прошёл мимо контроля')
        return 0
    if '--самопроверка' in доводы:
        return самопроверка()

    страница = скачать(ВЫЛОЖЕНО, 200).decode('utf-8', 'replace')
    выложен = скачать(ВЫЛОЖЕНО + 'app.js', 1000)
    ствол = из_ствола_мягко('app.js')
    # ⚠ ПОДЛЕЖАЩЕЕ — СУДИМОЕ ДЕРЕВО, а не ствол. Прибор зовут ПЕРЕД мерджем, из
    # того чекаута, который поедет в ствол: там и опись, и клиент. Первая
    # редакция читала опись из `origin/main` и на шаге «опись под v109 → прогон
    # → мердж» видела ствольную опись v105 при Pages v108 → «долг 3 из 3», то
    # есть держала релиз независимо от всех прочих ветвей (замер мой на
    # настоящих числах). Ствол остался СВИДЕТЕЛЕМ и печатается строкой.
    корень = pathlib.Path(__file__).resolve().parent.parent
    клиент = корень / 'app.js'
    опись = корень / ОПИСЬ
    видимость = корень / ВИДИМОСТЬ
    for путь in (клиент, опись, видимость):
        if not путь.is_file():
            не_выполнено(f'{путь} не найден — судить нечего, долг НЕ ИЗМЕРЕН')
    генератор = корень / ГЕНЕРАТОР
    if not генератор.is_file():
        не_выполнено(f'{генератор} не найден — номер генератора НЕ ПРОЧИТАН')
    в_генераторе = номер(генератор.read_text(encoding='utf-8'),
                         НОМЕР_ГЕНЕРАТОРА, str(генератор))
    ствол_описи = из_ствола_мягко(ОПИСЬ)
    код, строки = приговор(
        номер(страница, НОМЕР_РАЗМЕТКИ, ВЫЛОЖЕНО),
        номер(опись.read_text(encoding='utf-8'), НОМЕР_ОПИСИ, str(опись)),
        hashlib.sha256(выложен).hexdigest(),
        hashlib.sha256(ствол).hexdigest() if ствол else '—' * 32,
        hashlib.sha256(клиент.read_bytes()).hexdigest(),
        клиент_описи(видимость.read_bytes()),
        номер(ствол_описи.decode('utf-8', 'replace'), НОМЕР_ОПИСИ,
              f'{СТВОЛ}:{ОПИСЬ}') if ствол_описи else None,
        в_генераторе)
    print('\n'.join(строки))
    return код


