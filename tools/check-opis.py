#!/usr/bin/env python3
"""Долг описи против ВЫЛОЖЕННОГО клиента — падающая проверка (Cafe13KPG#605).

    python3 -I tools/check-opis.py                  # спросить Pages и ствол
    python3 -I tools/check-opis.py --самопроверка

Коды: 0 — опись догнала; 1 — КРАСНОЕ (долг достиг предела или опись снята с
другого клиента); 2 — НЕ ВЫПОЛНЕНО (Pages не ответил, номер не прочитался,
описи нет) — читать как «не выполнено», а НЕ как «долга нет».

Правило (координатор, 29.10.2026): по модели «показ раньше проверки» опись
едет позади выложенного клиента, предел отставания — ТРИ ОПУБЛИКОВАННЫХ
НОМЕРА. Публикуются только номера, поднятые правкой клиента, поэтому мердж,
не тронувший `app.js`, долга не делает.

Зовут двое, и ловят они разное: автор клиента — перед публикацией (его случай
«опубликовать поверх предела»), владелец описи — обходом (его случай
«накопилось»). Проверка без вызывающего — комментарий.

⚠ Эта проверка — НЕ четвёртые ворота необратимости. Ворот перед показом ТРИ
(Cafe13KPG#605: дым, имена и id, оба номера версии), и они стоят на КАЖДОЙ
публикации. Здесь исполняется ПРЕДЕЛ отставания: красное бывает только при
долге ≥ 3 либо при описи с другого клиента, а при долге 1–2 проверка зелена
НАРОЧНО. Разводить обязательно: на счёте ворот у нас уже ошибались.

Два прибора в одном приговоре, второй сильнее первого:

  • СЧЁТ НОМЕРОВ: номер на Pages минус номер в `screens.html`. Видит
    накопление, но слеп к правке, не поднимавшей номер;
  • СЛИЧЕНИЕ КЛИЕНТА: `клиент_sha256` из `screens/vidimost.json` против
    sha256 выложенного `app.js`. Судит «опись снята с ДРУГОГО клиента» и
    краснеет там, где номера равны, а код разошёлся.

⚠ Сличение судит ТОЛЬКО при равных номерах, и спрашивается трёхсторонне —
опись, ствол, Pages. Оба условия куплены дефектами первой редакции. Судя при
разных номерах, оно краснело на КАЖДОЙ здоровой публикации: номер лежит внутри
`app.js`, поэтому отставание описи на номер — это всегда другой слепок, и при
долге 1–2 судит счёт номеров, а слепки молчат. Двухсторонним же оно врёт на
выкладке в пути: опись, снятая с нового ствола, не сойдётся с ещё не
обновлённым Pages, и это лаг сборки, а не долг; различает их ствол.

⚠ И почему приговор «НЕ ИЗМЕРЕН» заведён отдельным кодом. Первая редакция
этой проверки считала долг в оболочке: `grep -o 'app\\.js?v=[0-9]*'` плюс
`$(( P - O ))`. Шаблон `[0-9]*` совпадает с признаком БЕЗ числа, номер уезжает
пустым, а пустое в арифметике bash — ноль: на входе без номера проверка
печатала «долга нет», то есть самый успокаивающий из возможных ответов, и
предел при ней не срабатывал НИКОГДА. Замер пяти входов — в PR.
"""

import hashlib
import json
import pathlib
import re
import subprocess
import sys

ПРЕДЕЛ = 3
ВЫЛОЖЕНО = 'https://anatoly9837-lab.github.io/cafe13-miniapp/'
СТВОЛ = 'origin/main'
ОПИСЬ = 'screens.html'
ВИДИМОСТЬ = 'screens/vidimost.json'

# Номер в разметке — форма `?v=NN`; в описи — `vNN · дата`. Диапазон в шаблоне
# (`v9[0-9]`) здесь мина: на трёхзначном номере он даёт ПУСТО, а пусто читается
# как «номера нет». Поэтому только `[0-9]+`, и ни одной цифры литералом.
НОМЕР_РАЗМЕТКИ = re.compile(r'app\.js\?v=([0-9]+)')
НОМЕР_ОПИСИ = re.compile(r'v([0-9]+) · [0-9.]+')


def не_выполнено(текст):
    print('ПРОВЕРКА НЕ ВЫПОЛНЕНА: ' + текст)
    sys.exit(2)


def номер(исходник, образец, что):
    """Номер версии числом. Пусто и не-число — НЕ ноль, а «не измерено»."""
    нашлось = образец.search(исходник)
    if not нашлось:
        не_выполнено(f'{что}: номера не видно (признак {образец.pattern!r} '
                     'не дал числа) — это НЕ «долга нет»')
    return int(нашлось.group(1))


def скачать(адрес, минимум):
    из = subprocess.run(['curl', '-sS', '-f', '-H', 'Cache-Control: no-cache',
                         адрес + ('&' if '?' in адрес else '?') + 'cb=' +
                         str(__import__('os').getpid())],
                        capture_output=True)
    if из.returncode != 0 or len(из.stdout) < минимум:
        не_выполнено(f'{адрес} не отдался: ' +
                     (из.stderr.decode('utf-8', 'replace').strip()
                      or f'код {из.returncode}, {len(из.stdout)} байт') +
                     ' — долг НЕ ИЗМЕРЕН')
    return из.stdout


def из_ствола(путь):
    из = subprocess.run(['git', 'show', f'{СТВОЛ}:{путь}'], capture_output=True)
    if из.returncode != 0 or not из.stdout:
        не_выполнено(f'{СТВОЛ}:{путь} не прочитался: ' +
                     (из.stderr.decode('utf-8', 'replace').strip()
                      or f'код {из.returncode}') + ' — долг НЕ ИЗМЕРЕН')
    return из.stdout


def клиент_описи(сырьё):
    try:
        дано = json.loads(сырьё)
    except ValueError as беда:
        не_выполнено(f'{ВИДИМОСТЬ} не разобрался: {беда} — долг НЕ ИЗМЕРЕН')
    sha = дано.get('клиент_sha256')
    if not isinstance(sha, str) or not re.fullmatch('[0-9a-f]{64}', sha):
        не_выполнено(f'в {ВИДИМОСТЬ} нет поля клиент_sha256 — долг НЕ ИЗМЕРЕН')
    return sha


def приговор(на_pages, в_описи, sha_pages, sha_ствола, sha_описи):
    """Числа и слепки → (код, строки). Чистая, чтобы судить её подлогами."""
    долг = на_pages - в_описи
    строки = [f'Pages v{на_pages} · опись v{в_описи} · долг {долг} из {ПРЕДЕЛ}']
    красное = []

    if в_описи > на_pages:
        красное.append(f'опись ВПЕРЕДИ выложенного (Pages v{на_pages}, '
                       f'опись v{в_описи}) — так не бывает, признак сломан')
    elif долг >= ПРЕДЕЛ:
        красное.append('предел достигнут — следующая версия не публикуется, '
                       'пока опись не приедет')

    # ⚠ Слепки судят ТОЛЬКО при равных номерах. Номер версии лежит ВНУТРИ
    # `app.js`, поэтому другой номер — это всегда другой слепок: при долге 1–2
    # расхождение слепков есть само законное отставание, и краснеть на нём
    # значит краснеть на КАЖДОЙ здоровой публикации. Судит там счёт номеров.
    if долг > 0:
        if sha_описи == sha_pages:
            красное.append(f'опись называет v{в_описи}, а её клиент — тот же, '
                           f'что у выложенного v{на_pages}: номер в описи '
                           'разошёлся с её же клиентом')
        else:
            строки.append(f'клиент описи отстал на {долг} — при разных номерах '
                          'так и положено, слепки здесь не судят')
    elif долг == 0:
        if sha_описи == sha_pages:
            строки.append('клиент описи = выложенный')
        elif sha_описи == sha_ствола:
            # Опись снята с нового ствола, а Pages ещё отдаёт прежний файл.
            # Работа сделана; сошлось бы и по сети — через минуты сборки.
            строки.append('клиент описи = ствол, а Pages отдаёт прежний — '
                          'выкладка в пути, это не долг')
        else:
            красное.append('номера равны, а клиент описи другой: её '
                           f'клиент_sha256 {sha_описи[:16]}… не совпал ни с '
                           f'выложенным {sha_pages[:16]}…, ни со ствольным '
                           f'{sha_ствола[:16]}… — значит уехала правка без '
                           'подъёма номера, и человек остался на прежнем файле')

    return (1 if красное else 0), строки + ['КРАСНОЕ: ' + с for с in красное]


def самопроверка():
    """Каждый приговор — своим входом; зелёное на подлоге хуже отсутствия.

    ⚠ Фикстура СОГЛАСОВАНА с предметом: номер версии лежит внутри `app.js`,
    поэтому слепок клиента здесь выводится ИЗ НОМЕРА (`сл`). Первая редакция
    подавала разные номера при одинаковом слепке — состояние, которого не
    бывает, — и девять входов были зелены по построению, пока ветвь сличения
    краснела на каждой здоровой публикации (нашли frontend-upravlenie-ec и
    координатор, не самопроверка).
    """
    def сл(н):                      # слепок клиента версии н
        return f'{н:064d}'
    ПРАВКА = 'f' * 64               # правка БЕЗ подъёма номера: номер тот же

    случаи = [
        ('здоровый ход: опись на один номер позади',
         (106, 105, сл(106), сл(106), сл(105)), 0),
        ('два позади — ещё можно', (107, 105, сл(107), сл(107), сл(105)), 0),
        ('предел достигнут', (108, 105, сл(108), сл(108), сл(105)), 1),
        ('номера сошлись, клиент сошёлся',
         (105, 105, сл(105), сл(105), сл(105)), 0),
        ('выкладка в пути: опись = ствол, Pages прежний',
         (105, 105, сл(105), ПРАВКА, ПРАВКА), 0),
        ('невидимая выкладка: номера РАВНЫ, клиент другой',
         (105, 105, ПРАВКА, ПРАВКА, сл(105)), 1),
        ('номер описи врёт о её клиенте',
         (106, 105, сл(106), сл(106), сл(106)), 1),
        ('опись впереди выложенного', (105, 107, сл(105), сл(105), сл(107)), 1),
    ]
    беды = []
    for имя, довод, ждём in случаи:
        дано = приговор(*довод)[0]
        print(f'  {"сошлось" if дано == ждём else "РАЗОШЛОСЬ"}: {имя} '
              f'→ код {дано}, ждали {ждём}')
        if дано != ждём:
            беды.append(имя)

    # Подлоги под признак номера. Проверять надо не «нашёл число», а «не нашёл
    # и СКАЗАЛ об этом»: в первой редакции именно здесь рождался ложный ноль.
    for имя, разметка in (('признак есть, числа нет', '<script src="app.js?v=">'),
                          ('app.js нет вовсе', '<script src="other.js">'),
                          ('пусто', '')):
        из = subprocess.run([sys.executable, '-I', __file__, '--подлог-номера',
                             разметка], capture_output=True, text=True)
        ладно = из.returncode == 2 and 'НЕ ВЫПОЛНЕНА' in из.stdout
        print(f'  {"сошлось" if ладно else "РАЗОШЛОСЬ"}: {имя} → код '
              f'{из.returncode}, {из.stdout.strip()[:60]}')
        if not ладно:
            беды.append(имя)

    print('самопроверка: ' + ('сошлась' if not беды
                              else 'РАЗОШЛАСЬ — ' + '; '.join(беды)))
    return 1 if беды else 0


def main(доводы):
    if '--подлог-номера' in доводы:
        номер(доводы[доводы.index('--подлог-номера') + 1],
              НОМЕР_РАЗМЕТКИ, 'подлог')
        print('подлог прошёл мимо контроля')
        return 0
    if '--самопроверка' in доводы:
        return самопроверка()

    страница = скачать(ВЫЛОЖЕНО, 200).decode('utf-8', 'replace')
    выложен = скачать(ВЫЛОЖЕНО + 'app.js', 1000)
    ствол = из_ствола('app.js')
    код, строки = приговор(
        номер(страница, НОМЕР_РАЗМЕТКИ, ВЫЛОЖЕНО),
        номер(из_ствола(ОПИСЬ).decode('utf-8', 'replace'), НОМЕР_ОПИСИ,
              f'{СТВОЛ}:{ОПИСЬ}'),
        hashlib.sha256(выложен).hexdigest(),
        hashlib.sha256(ствол).hexdigest(),
        клиент_описи(из_ствола(ВИДИМОСТЬ)))
    print('\n'.join(строки))
    return код


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
