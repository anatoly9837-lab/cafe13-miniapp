# ⚠ Признак клиента — ТОТ ЖЕ, что у ворот показа (`tools/pered-pokazom.cjs`,
#   «номер версии»): объявление `var VERSION = 'vN · …'`. Диапазона цифр здесь
#   быть не может — на трёхзначном номере он даёт ПУСТО, а пусто читается как
#   «номера нет» (мина названа в `check-opis.py`).
НОМЕР_СВОЙ = re.compile(r'^v([0-9]+) \u00b7 ')
НОМЕР_КЛИЕНТА = re.compile(r"var VERSION = 'v([0-9]+) \u00b7 ")


def сверить_номер_версии(своя, клиент, строго=False):
    """Беда|None — число, которое прибор ПЕЧАТАЕТ, против числа КЛИЕНТА дерева.

    ⚠ ПАРА, КОТОРОЙ НЕ ДЕРЖАЛ НИКТО. Замер 18.11.2026, поводом — предупреждение
    координатора «не возьмите старое число из карточки». Номер версии стоит в
    ЧЕТЫРЁХ местах, и сверены между собой были три: ворота показа держат клиент
    против всех `?v=` в `index.html`, `check-opis.py` — опись против Pages,
    против ствольной описи и против `VERSION` этого генератора. Пары «опись ↔
    клиент СВОЕГО дерева» не было: `приговор()` соседа числа клиента даже не
    принимает параметром. Цена названа прямым прогоном его чистой функции:
    опись, подписанная v153 при клиенте дерева v155 и Pages v154, даёт КОД 0 —
    «отставание 1 (порог 3)» и «при разных номерах так и положено, слепки здесь
    не судят». То есть страница и обложка листа печатают о клиенте число,
    которого у клиента нет, и говорят это зелёным.

    ⚠ Отставание ЛЕЖАЩЕЙ описи от клиента — состояние ЗАКОННОЕ (Cafe13KPG#605:
    генератор едет вместе с описью, а не с правкой клиента; порог и решение
    владельца 29.10.2026 — расхождение идёт карточкой, публикации не держит).
    Поэтому проверка стоит на ПРОГОНЕ генератора, а не на лежащем файле:
    лежащая опись законно старше клиента, а СОБИРАЕМАЯ сейчас описывает ровно
    тот клиент, который прибор в эту минуту читает, — и обязана называть его
    число. Отказ стоит ДО записи `screens.html`: иначе страница с чужим числом
    уже лежит в дереве, а код приходит после.

    ⚠ Чего НЕ сверяет: ДАТУ. Пересъёмка на следующий день после подъёма номера
    законна, и краснеть на ней значило бы краснеть на здоровой работе. Пусто и
    не-число — «не измерено», а не «сошлось»: сломанный признак номера
    неотличим от равенства, если о нём молчать.
    """
    м_своя = НОМЕР_СВОЙ.match(своя)
    if not м_своя:
        return (2, 'в VERSION прибора нет числа вида «vN \u00b7 » (стоит «%s») — '
                   'номер описи НЕ ПРОЧИТАН, и это не «сошлось»' % своя[:40])
    м_кл = НОМЕР_КЛИЕНТА.search(клиент)
    if not м_кл:
        return (2, "в клиенте дерева нет объявления `var VERSION = 'vN \u00b7 …'` — "
                   'номер клиента НЕ ПРОЧИТАН, сверять опись не с чем')
    своё, клиентское = int(м_своя.group(1)), int(м_кл.group(1))
    отставание = клиентское - своё
    if отставание < 0:
        return (2, 'прибор печатает опись как v%d, а клиент ЭТОГО дерева — v%d: '
                   'опись ВПЕРЕДИ клиента, и законного такого состояния нет — '
                   'собираемая страница назвала бы о клиенте число, которого у '
                   'него ещё нет. Номер берут ИЗ КЛИЕНТА (js/01-osnova.js, '
                   '`var VERSION`), а не из карточки'
                % (своё, клиентское))
    if отставание > ПОРОГ_ОТСТАВАНИЯ:
        # ⚠ КОД ЗДЕСЬ ВЫБИРАЕТ РЕЖИМ, и предметы у режимов РАЗНЫЕ:
        # пересборка судит СВОЮ работу («забыли поднять VERSION»), клиентский
        # мердж — ЧУЖУЮ, а в нём отставание законно: порог как ВОРОТА снят
        # решением владельца 29.10.2026 (`tools/check-opis.py` — расхождение
        # идёт карточкой, публикации не держит). Прежде эта ветвь возвращала 1
        # НЕ СМОТРЯ на `строго`, то есть порог, снятый у соседа, красил шаг 4
        # ворот мерджа ЧУЖОМУ PR (замер: `#339`, опись v162 при клиенте v166).
        # Решение координатора 19.11.2026. Текст приговора остаётся тот же:
        # число отставания читающему нужно в обоих режимах.
        return (1 if строго else 0,
                'опись отстала от клиента на %d при пороге %d (опись v%d, '
                   'клиент v%d) — пересобрать опись под это дерево: поднять '
                   'VERSION прибора и перегнать tools/shots.cjs с '
                   'tools/catalog.py' % (отставание, ПОРОГ_ОТСТАВАНИЯ, своё,
                                         клиентское))
    if отставание and строго:
        # ⚠ СТРОГИЙ РЕЖИМ — ПРОГОН ПЕРЕСБОРКИ, и предмет приговора здесь ДРУГОЙ.
        #   В клиентском PR отставание на мердж законно (порог выше), а при
        #   пересборке описи оно значит «забыли поднять VERSION»: собираемая
        #   СЕЙЧАС страница описывает ровно тот клиент, который прибор в эту
        #   минуту читает, и обязана называть его число. Равенство эту охрану
        #   держало, порог её снял (решение координатора 19.11.2026), и
        #   возвращается она СЮДА, где её предмет. Замер, по которому она нужна:
        #   19.11 номер описи я поднял руками дважды, и ни один прибор об этом
        #   не спросил.
        return (1, 'строгий режим пересборки: опись v%d, клиент дерева v%d — '
                   'отставание %d. Для прогона ПЕРЕСБОРКИ это «забыли поднять '
                   'VERSION», а не «законно»: собираемая страница назвала бы о '
                   'клиенте не его число. Поднять VERSION прибора до v%d'
                % (своё, клиентское, отставание, клиентское))
    if отставание:
        return (0, 'опись v%d, клиент дерева v%d: отставание %d (порог %d) — '
                   'законно, пересборка описи и есть следующий ход'
                % (своё, клиентское, отставание, ПОРОГ_ОТСТАВАНИЯ))
    return (0, None)


def проверить_номер_версии(строго=False):
    """Отказ прибора, если печатаемое число разошлось с клиентом дерева."""
    код, слово = сверить_номер_версии(VERSION, _клиент().text, строго)
    # ⚠ ТРИ ИСХОДА, И КОДЫ У НИХ РАЗНЫЕ. Прежняя редакция требовала РАВЕНСТВА
    #   и отказывала двойкой на любом расхождении — а это тупик: по решению
    #   координатора опись пересобирается ПОСЛЕ мерджа, значит каждый клиентский
    #   PR со сменой номера красен по построению (нашёл разработчик клиента на
    #   `#309`: опись v160 против клиента v161). Отставание на мердж ЗАКОННО и
    #   судится порогом — тем же, что у `check-opis.py`.
    if код == 2:
        не_выполнено(слово)
    if код == 1:
        sys.exit(слово)
    if слово:
        print(слово)

