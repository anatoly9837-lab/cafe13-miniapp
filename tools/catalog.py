def свежесть(каталог, вид):
    """Файл видимости снят С ЭТОЙ страницы или с другой — падающая проверка.

    ⚠ Без неё опись устаревает МОЛЧА: правят `tabList()` или вход, прибор не
    перегоняют, и страница печатает прежнее «видят», оставаясь зелёной. Возврат
    arhitector-47 27.10.2026; он же назвал признак — слепок того клиента, с
    которого снимали обход. Отсутствие слепков — «не выполнено», а не
    «сошлось»: старый файл видимости неотличим от свежего.

    ⚠ ПРИЗНАК СМЕНИЛСЯ (Cafe13KPG#806), и прежний был узок ДО разбивки тоже:
    один sha256 `app.js` не видел правок `index.html`, `styles.css` и водяного
    знака, то есть опись старела зелёной от правки ОТРИСОВКИ, а не кода. После
    разбивки он умер совсем — файла `app.js` нет. Теперь сверяется КАРТА
    `файл → sha256` по составу из `index.html` (tools/klient.py).

    Приговоры разведены: разошёлся СОСТАВ — названы пришедшие и ушедшие файлы;
    состав тот же, а содержимое разное — названы РАЗОШЕДШИЕСЯ файлы. Склеивать
    их нельзя: «добавили файл» и «правили код» лечатся одинаково (пересъёмка),
    но читаются по-разному, а прибор, назвавший не ту причину, учит неверному."""
    if вид is None:
        return
    было = вид.get('слепки_страницы')
    if not isinstance(было, dict) or not было:
        не_выполнено('в %s/vidimost.json нет карты «слепки_страницы» — '
                 'файл снят прибором прежней редакции (до Cafe13KPG#806), и свежесть его '
                 'проверить нечем. Перегнать tools/vidimost.cjs' % каталог)
    м = _помощник()
    try:
        стало = м.слепки_страницы(м.читатель_дерева(_корень()))
    except м.НеВыполнено as е:
        не_выполнено('слепки страницы по дереву не собрались: %s — '
                 'сверить видимость со страницей нечем' % е)
    пришли = [ф for ф in стало if ф not in было]
    ушли = [ф for ф in было if ф not in стало]
    if пришли or ушли:
        не_выполнено('видимость снята с ДРУГОГО СОСТАВА страницы — '
                 'пришли: %s; ушли: %s. Страница напечатала бы прежнее «видят» о новом '
                 'клиенте. Перегнать tools/vidimost.cjs'
                 % (', '.join(пришли) or '—', ', '.join(ушли) or '—'))
    разошлись = [ф for ф in стало if было[ф] != стало[ф]]
    if разошлись:
        не_выполнено('видимость снята с ДРУГОГО клиента — состав тот же, '
                 'а разошлись %d из %d: %s. Страница напечатала бы прежнее «видят» о новом '
                 'клиенте. Перегнать tools/vidimost.cjs'
                 % (len(разошлись), len(стало), ', '.join(разошлись[:6])
                    + (' и ещё %d' % (len(разошлись) - 6) if len(разошлись) > 6 else '')))


