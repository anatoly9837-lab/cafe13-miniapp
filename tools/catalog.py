def экранов_в_описи(items):
    """Сколько ЭКРАНОВ на странице — не строк.

    ⚠ Строка не равна экрану: у `home` два вида (светлый и ночной), значит
    строк 72 при 71 экране. Обложка листа печатала `len(items)` и называла это
    «72 экрана» — то есть расходилась со страницей, где стоит 71, на один и
    тем же словом. Один экран обложка обещала лишним.
    ⚠ Мутация архитектора (07.11.2026) вернула обложке `len(items)`, и
    `--самопроверка` осталась ЗЕЛЁНОЙ: число обложки не держал ни один случай.
    Поэтому счёт вынесен в ОДНУ функцию, которой пользуются и страница, и
    обложка, и у неё свой падающий случай: два вида одного экрана обязаны дать
    экранов N при строках N+1."""
    return len({i['screen'] for i in items})


def долг_снимков(items):
    """Строка о ДЫРЕ описи: сколько экранов «в тесте» снимка не имеют.

    ⚠ Решение координатора 07.11.2026, и довод его же: страница, на которой 27
    снимков и ни слова о неснятых, читается как ПОЛНАЯ — владелец делает из неё
    вывод о состоянии приложения, а она его не несёт. Расширять опись до всех
    экранов «в тесте» дороже и не лечит немедленно; НАЗВАННАЯ дыра лечит сразу
    и стоит строки. Тогда число перестаёт быть обещанием полноты и становится
    долгом С РАЗМЕРОМ.

    ⚠ Считается по ЭКРАНАМ, а не по строкам, и это замер: у `home` два вида
    (светлый и ночной), поэтому разбивка по стадиям даёт «в тесте — 47» строк
    при 46 ЭКРАНАХ. Счёт строками завысил бы снятое. Числа берутся из тех же
    `items`, что печатают разбивку, — иначе два числа на одной странице
    разойдутся молча."""
    экраны = {}
    for i in items:
        if i['стадия'] != 'в тесте':
            continue
        экраны[i['screen']] = экраны.get(i['screen'], False) or bool(i.get('file'))
    без = [э for э, есть in экраны.items() if not есть]
    return ('снимков %d &middot; экранов «в тесте» %d, из них БЕЗ снимка %d — '
            'у них нет исполненного рецепта, и снимка с них не спрашивает '
            'никто: опись растёт ЗА рецептами, а не впереди них'
            % (len([i for i in items if i.get('file')]), len(экраны), len(без)))


