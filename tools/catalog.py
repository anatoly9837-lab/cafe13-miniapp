    # по одним строкам стадий, и снятый экран без строки ронял генератор
    # ТРАССОЙ вместо приговора. Замер мой (дерево `c014829`, где `клиент_sha256`
    # описи и sha256 `app.js` сошлись, поэтому сборка доходит до страницы):
    # подложить в `manifest.json` экран, которого нет ни в TSV, ни в УСЛОВИЕ →
    # `IndexError: list index out of range` в `кто_видит` (пустое условие
    # уходит в `часть.split(':', 1)[1]`), rc=1 без единой фразы.
    #
    # ⚠ И ЦЕНА ОТСУТСТВИЯ этой проверки ИЗМЕРЕНА, а не предположена. Прежний
    # текст отказа обещал, что «страница соврала бы молча, показав их всем», —
