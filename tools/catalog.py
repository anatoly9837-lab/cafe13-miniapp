def стадии(каталог):
    """Строки СТАДИИ.tsv: экран → (кадр, стадия, карточка, дата, рецепт).

    Состав условий видимости судит не эта функция: её подлежащее — ОДИН файл,
    а у того проверки подлежащее шире (`экраны_страницы`), и считать его здесь
    значило бы завести ему вторую редакцию.

    Страница без стадий не собирается: стадия — не украшение, а то, ради чего
    страницу и читают. Отсутствие файла — «НЕ ВЫПОЛНЕНО», а не «стадий нет»."""
    путь = os.path.join(каталог, 'СТАДИИ.tsv')
    if not os.path.isfile(путь):
        не_выполнено('нет файла стадий %s — '
                 'страница без стадий не собирается' % путь)
    из = {}
    for н, строка in enumerate(io.open(путь, encoding='utf-8').read().splitlines(), 1):
        if not строка.strip() or строка.lstrip().startswith('#'):
            continue
        поля = [п.strip() for п in строка.split('\t')]
        if len(поля) != 6:
            не_выполнено('%s:%d: полей %d, а должно быть 6 — шестая колонка '
                     '«рецепт» (адрес рецепта экрана либо «—»); правило — '
                     'Cafe13KPG `_docs/screen-path.md`, долг Cafe13KPG#910'
                     % (путь, н, len(поля)))
        из[поля[0]] = tuple(поля[1:])
    if not из:
        не_выполнено('%s: ни одной строки стадии' % путь)
    чужая_стадия = sorted({с[1] for с in из.values()} - set(СТАДИИ_ЦВЕТ))
    if чужая_стадия:
        не_выполнено('в %s стадии вне словаря: %s'
                 % (путь, ', '.join(чужая_стадия)))
    # ⚠ СТАДИЯ «ОПИСАН» УТВЕРЖДАЕТ РЕЦЕПТ, и утверждение без адреса не
    # проверяется ничем: приговор шага 7 ищет рецепт по ключу экрана, а у
    # экрана без кода ключа нет вовсе — значит единственное место, где адрес
    # можно спросить, это шестая колонка. Пустая она у «описан» — «не
    # выполнено», а не зелёное (условие долга Cafe13KPG#910).
    # ⚠ Пометка же «до стадии 1» говорит о КАДРЕ, и её утверждение держит
    # колонка кадра со своим сторожем формы (`tools/svyaz-kadrov.py`). Два
    # утверждения в одну колонку не складываются — потому колонок и шесть.
    описан_без_рецепта = sorted(э for э, с in из.items()
                                if с[1] == 'описан' and с[4] in ('—', '', '?'))
    if описан_без_рецепта:
        не_выполнено('в %s стадия «описан» без адреса рецепта в шестой '
                 'колонке: %s — стадия утверждает рецепт, а утверждение без '
                 'адреса не проверяется ничем'
                 % (путь, ', '.join(описан_без_рецепта)))
    return из


def экраны_страницы(ст, снимки):
    """ПОДЛЕЖАЩЕЕ проверок условия видимости — экраны СТРАНИЦЫ.

    Источников у него два, и ровно те же два у строк страницы
    (`строки_страницы`): строки стадий и снятые экраны манифеста. Третьего
    места, где перечисляются экраны страницы, быть не должно — разъедется
    молча, и именно это уже случилось (Cafe13KPG#658)."""
    return set(ст) | {з['screen'] for з in снимки}


def проверить_состав_условий(подлежащее, каталог):
    """У каждого экрана СТРАНИЦЫ есть условие видимости — падающая проверка.

    Судит СОСТАВ, а не правдивость: правдивость — у `проверить_условия`.
    """
    # ⚠ ПОДЛЕЖАЩЕЕ ЭТОЙ ПРОВЕРКИ — ЭКРАНЫ СТРАНИЦЫ (`экраны_страницы`):
    # строки стадий ПЛЮС снятые экраны манифеста. Экран, написанный в клиенте
    # и не попавший НИ туда, НИ туда, здесь не проверяется вовсе, и молчание
    # читается как «условие есть». Пара исходов (замер мой, 30.10.2026): снять
    # условие у листового `masterEvent` → красное «нет условия видимости»;
    # убрать вместе с ним и строку стадии, когда у экрана нет снимка, →
    # красное ИСЧЕЗАЕТ, сборка проходит. Второй проверки — «написан, а строки
    # нет» — здесь не заводим: её несёт `check-stages.py`, и две редакции
    # одного требования расходятся молча; вместо неё предел назван строкой
    # вывода.
    #
    # ⚠ И У СОСЕДА, КОТОРЫЙ ЭТОТ СЛУЧАЙ СУДИТ, СВОЁ ПОДЛЕЖАЩЕЕ: по умолчанию
    # `check-stages.py` скачивает ВЫЛОЖЕННЫЙ `app.js`, а здесь собирается
    # дерево. Различающая пара (замер мой, 30.10.2026; ствол `42b5f97` плюс
    # подложенный новый экран в `SCREENS`, строки стадии и снимка нет):
    # `--файл app.js` → КРАСНОЕ «написан, а строки о нём нет»; тот же дефект
    # без `--файл` → ЗЕЛЁНОЕ, потому что в выложенном клиенте экрана ещё нет.
    # ⚠ Замер снят ДО разбивки; форма `--файл app.js` умерла вместе с файлом,
    # живая форма того же подлежащего — `--дерево .` (замер 06.11.2026).
