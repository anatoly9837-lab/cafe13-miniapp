_ПОМОЩНИК = None


def _помощник():
    """Модуль tools/klient.py — ОДИН источник правды о составе клиента и страницы.
    Подключается по пути: под `python3 -I` каталог скрипта в sys.path не кладётся."""
    global _ПОМОЩНИК
    if _ПОМОЩНИК is None:
        спец = importlib.util.spec_from_file_location('klient', os.path.join(os.path.dirname(os.path.abspath(__file__)), 'klient.py'))
        м = importlib.util.module_from_spec(спец)
        спец.loader.exec_module(м)
        _ПОМОЩНИК = м
    return _ПОМОЩНИК


def _корень():
    return os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def не_выполнено(текст):
    """Отказ прибора: слова — в stdout, код — 2, а НЕ 1.

    ⚠ Куплено замером 04.11.2026 (повод — четвёртое состояние, найденное
    `arhitector-47` у разборов самопроверок): все 17 отказов `catalog.py` шли
    через `sys.exit('ПРОВЕРКА НЕ ВЫПОЛНЕНА: …')`, а это код **1**. Ворота
    читают 1 как «КРАСНОЕ» и печатали «страница под это дерево не собирается»
    там, где НЕ ИЗМЕРЕНО ничего. Соседи по воротам (`check-opis.py`,
    `check-stages.py`, `reestr-oblika.py`, `klient.py`) держат код 2 — из пяти
    приборов не в шаге был один этот.
    """
    print('ПРОВЕРКА НЕ ВЫПОЛНЕНА: ' + текст)
    sys.exit(2)


def _клиент():
    """Текст клиента — склейкой файлов в порядке index.html (Cafe13KPG#806, tools/klient.py).
    НеВыполнено помощника — «не выполнено», а не догадка по одному файлу."""
    м = _помощник()
    try:
        return м.клиент(_корень())
    except м.НеВыполнено as е:
        не_выполнено(str(е))

