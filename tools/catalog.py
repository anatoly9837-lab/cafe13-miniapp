def самопроверка():
    """Свежесть описи — каждым своим входом, настоящей `свежесть()`.

    ⚠ ПОЧЕМУ ОНА ЗДЕСЬ ТОЛЬКО НА СВЕЖЕСТИ, и это названо, чтобы не считалось
    покрытием всего прибора. Замер 04.11.2026: у `catalog.py` самопроверки не
    было ВОВСЕ (у соседей по воротам — 13 упоминаний у `check-stages.py`, 6 у
    `ids-clean.cjs`, 2 у `live.cjs`), а подлоги на его падающие проверки жили
    ЗАПИСЯМИ прошлых замеров в комментариях — то есть однажды были прогнаны
    руками и повторить их нечем. Условие координатора 04.11.2026: следующая
    правка файла несёт самопроверку хоть на ЧАСТЬ проверок, чтобы 996 строк не
    брать разом. Правка была в `свежесть()` — с неё и начато.
    ⚠ Чего эта самопроверка НЕ покрывает: условие видимости у экранов, разбор
    `FROZEN`/`WIRED`, снятый экран без строки стадии, сборку страницы. Их
    целость по-прежнему не переснимает ничто.

    Фикстура — карта ЭТОГО дерева: прибор судит дерево, и подавать ему чужую
    карту значило бы проверять четвёртую дорогу.
    """
    м = _помощник()
    беды = []
    своя = м.слепки_страницы(м.читатель_дерева(_корень()))
    всего = len(своя)

    def проба(имя, вид, ждём):
        """ждём=None — приговора быть не должно; строка — она обязана быть в отказе.

        ⚠ Слова отказа читаются из STDOUT, а код проверяется ОТДЕЛЬНО: с
        04.11.2026 отказ идёт через `не_выполнено()` (код 2), и `str(е)` даёт
        «2», а не текст. Прежняя редакция случая на этом покраснела шестью
        случаями из девяти — отказ прибора увидеть можно, только читая то,
        что он ПЕЧАТАЕТ.
        """
        буфер = io.StringIO()
        try:
            with contextlib.redirect_stdout(буфер):
                свежесть('проба', вид)
            вышло = None
        except SystemExit as е:
            вышло = буфер.getvalue().strip()
            if е.code != 2:
                беды.append('%s: код отказа %r, а «не выполнено» — это 2'
                            % (имя, е.code))
        if ждём is None:
            ладно = вышло is None
            печать = 'приговора нет' if ладно else вышло[:60]
        else:
            ладно = вышло is not None and ждём in вышло
            печать = (вышло[:72] if вышло else 'ПРОПУЩЕНО — приговора нет')
        print('  %s: %s → %s' % ('сошлось' if ладно else 'РАЗОШЛОСЬ', имя, печать))
        if not ладно:
            беды.append(имя)
        return вышло

    проба('видимости нет вовсе (страница без имён)', None, None)
    проба('карта этого дерева', {'слепки_страницы': своя}, None)
    проба('поля нет (прибор до #806)', {'снято': 'x'}, 'нет карты «слепки_страницы»')
    проба('карта ПУСТАЯ', {'слепки_страницы': {}}, 'нет карты «слепки_страницы»')

    иначе = dict(своя)
    какой = sorted(иначе)[0]
    иначе[какой] = '0' * 64
    проба('содержимое одного файла разошлось',
          {'слепки_страницы': иначе}, 'разошлись 1 из %d' % всего)

    ушёл = dict(своя)
    имя_ушедшего = sorted(ушёл)[0]
    del ушёл[имя_ушедшего]
    # ⚠ Ждём ИМЯ файла, а не «ушли: —»: без имени случай зелен и на любом
    # другом расхождении состава, то есть не различает, о чём приговор.
    проба('файл ушёл из состава', {'слепки_страницы': ушёл},
          'пришли: %s; ушли: —' % имя_ушедшего)

    пришёл = dict(своя, **{'js/niktovnjom.js': '1' * 64})
    проба('файл пришёл в состав', {'слепки_страницы': пришёл},
          'ушли: js/niktovnjom.js')

    # ⚠ ПОДЛОГ В САМ ПРЕДИКАТ, а не в фикстуру: случай «содержимое разошлось»
    # обязан краснеть ИЗ-ЗА чтения дерева. Обезвредим чтение — пусть помощник
    # возвращает ту же карту, что в фикстуре, — и случай обязан ПЕРЕСТАТЬ
    # краснеть. Останется красным — значит он судит не то, чем объявлен.
    цел = м.слепки_страницы
    assert иначе != своя, 'подлог не применился'
    м.слепки_страницы = lambda читатель: dict(иначе)
    try:
        вышло = проба('ПОДЛОГ: чтение дерева обезврежено — случай обязан замолчать',
                      {'слепки_страницы': иначе}, None)
    finally:
        м.слепки_страницы = цел
    # и сразу обратно: предикат вернулся, случай снова краснеет
    проба('после подлога случай снова краснеет',
          {'слепки_страницы': иначе}, 'разошлись 1 из %d' % всего)

    # ⚠ КОД отказа — тоже приговор, и купить его можно только ПРОГОНОМ файла:
    # внутри процесса `не_выполнено()` перехватывает `проба()`, а ворота читают
    # именно код завершения. Ждём СВОЙ кусок отказа, а не «НЕ ВЫПОЛНЕНА»:
    # последнее верно про любой отказ и не различает ничего.
    with tempfile.TemporaryDirectory() as кат:
        io.open(os.path.join(кат, 'manifest.json'), 'w', encoding='utf-8').write('[]')
        из = subprocess.run([sys.executable, '-I', __file__, кат],
                            capture_output=True, text=True)
        ладно = (из.returncode == 2 and 'нет файла стадий' in из.stdout)
        print('  %s: отказ прибора прогоном — код %d (ждём 2), %s'
              % ('сошлось' if ладно else 'РАЗОШЛОСЬ', из.returncode,
                 из.stdout.strip()[:48] or '(ничего не напечатал)'))
        if not ладно:
            беды.append('код отказа прогоном')

    print('самопроверка свежести: ' + ('сошлась' if not беды
                                       else 'РАЗОШЛАСЬ — ' + '; '.join(беды)))
    return 1 if беды else 0


