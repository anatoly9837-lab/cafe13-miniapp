#!/usr/bin/env python3
"""Связь КАДР↔ЭКРАН с двух сторон — два приговора, больше ничего.

    python3 -I tools/svyaz-kadrov.py --база <каталог кадров> [--реестр <tsv>]
    python3 -I tools/svyaz-kadrov.py --самопроверка

Коды: 0 — связь сошлась; 1 — КРАСНОЕ; 2 — ПРОВЕРКА НЕ ВЫПОЛНЕНА.

ЗАЧЕМ. Вопрос «что ещё не нарисовано» до этого прибора не отвечал НИКТО, и
три существовавших признака врали — замер мой 05.11.2026 (ствол клиента
`e55c6c6`, база `Cafe13KPG` `dev`, 207 кадров):

  • «нет записи в SHOTS» — это про СНИМОК описи (png клиента), а не про КАДР
    базы экранов. Я сам назвал одно другим и чуть не послал дизайнера рисовать
    семь кадров поверх существующих;
  • колонка «кадр» в `screens/СТАДИИ.tsv` значит «НЕ ВПИСАН», а не «не
    нарисован»: «—» стояло у 25 строк из 60, среди них `consent`, `home`,
    `pass`, `events`, `topup`, `organizer`, `people`;
  • поиск ИМЕНИ экрана внутри кадров врёт в ОБЕ стороны на одном и том же
    экране: `manage` находился в 36 кадрах (кадры носят в себе куски кода
    клиента со списком вкладок, `t.push(['manage',` в `E54-master-offer`), а в
    своём собственном кадре `E46-manage-tab` слово `manage` встречается НОЛЬ
    раз.

Поэтому здесь связь судится ровно двумя приговорами, и оба — о СВЯЗИ, а не о
содержимом кадра:

  А) строка реестра называет код, которого в базе НЕТ;
  Б) семья кадров базы, на которую не ссылается НИ ОДНА строка реестра.

⚠ ЧЕГО ЗДЕСЬ НЕТ НАРОЧНО. Отчётов — ни одного: прибор отвечает «сошлась/не
сошлась», а не рассказывает о базе. Заполнения колонки «кадр» — тоже: «не
вписан» ≠ «не нарисован», и различать это — работа ЭТОГО прибора, а не повод
дописать 25 строк наугад. Привязки кадра к экрану по ПРЕДМЕТУ (кто на кадре
нарисован) — она у дизайнера, и прибора на неё быть не может: предмет читает
человек.

⚠ КОД КАДРА БЕРЁТСЯ ИЗ `<title>` САМОГО КАДРА, А НЕ ИЗ ИМЕНИ ФАЙЛА, и это
куплено замером: имя и `<title>` расходятся у 18 кадров из 207, потому что в
именах суффикс латинский, а в заголовках — кириллический (`E23b-cart-denied`
→ `E23б`; пары `b→б` ×6, `v→в` ×5, `g→г` ×4, `zh→ж`, `ya→я`, `yu→ю`). Прибор
на именах файлов краснел бы на этих восемнадцати, не находя их кодов.

⚠ И ОТТУДА ЖЕ ПЕРЕВОД СУФФИКСА. Реестр пишет латиницей (замер: `b d e g k v`,
ни одного кириллического), база в заголовках — смешанно. Значит сличать коды
в лоб нельзя: строка `E23b` и заголовок `E23б` — ОДИН кадр. Таблица ниже
снята с базы, а не придумана, и у неё есть сторож: кириллическая буква вне
таблицы останавливает прибор словами «не выполнено», а не уезжает молча в
«кода нет». Иначе таблица сгниёт первым же новым суффиксом.
"""
import io
import os
import re
import sys

РЕЕСТР_ПО_УМОЛЧАНИЮ = 'screens/СТАДИИ.tsv'

# Снято с базы 05.11.2026 (18 расхождений имени и заголовка). Сторож — ниже.
# ⚠ «д» дописана 05.11.2026 тем же днём, что и кадр `E46д` (`Cafe13KPG#863`,
# дверь шага 11): прибор на нём ОТКАЗАЛ, как и задумано его сторожем, и это
# первый случай, когда таблица пополнилась не задним числом. Перемер базы:
# 211 кадров, 52 семьи, кириллические суффиксы б 6, в 5, г 4, д 1, ж 1, ю 1,
# я 1 — других нет (замер мой, designer-55).
ПЕРЕВОД_СУФФИКСА = {'б': 'b', 'в': 'v', 'г': 'g', 'д': 'd',
                    'ж': 'zh', 'я': 'ya', 'ю': 'yu'}

# Пределы признаков: меньше — значит признак не тот, а не «предмета мало».
# Числа взяты ниже измеренных вдвое, чтобы не гнить от каждого нового кадра
# (в базе 207 кадров и 51 семья, в реестре 60 строк предмета и 34 кода).
НАДО_КАДРОВ = 50
НАДО_СТРОК = 20

КОД = re.compile(r'^(E\d+)([а-яёa-z]*)$')
КОД_В_ЗАГОЛОВКЕ = re.compile(r'<title>\s*(E\d+[а-яёa-z]*)\b')


def не_выполнено(почему):
    print('ПРОВЕРКА НЕ ВЫПОЛНЕНА: ' + почему)
    sys.exit(2)


def разобрать_код(кусок):
    """Код → (семья, нормальный суффикс) или None, если форма не та.

    ⚠ Суффикс переводится в латиницу ТАБЛИЦЕЙ, и неизвестная кириллическая
    буква — это `не выполнено`, а не «другой код»: без сторожа прибор
    молча объявил бы кадр ненайденным.
    """
    м = КОД.match(кусок)
    if not м:
        return None
    семья, суффикс = м.group(1), м.group(2)
    итог = ''
    for буква in суффикс:
        if буква in ПЕРЕВОД_СУФФИКСА:
            итог += ПЕРЕВОД_СУФФИКСА[буква]
        elif буква.isascii():
            итог += буква
        else:
            не_выполнено(
                'суффикс «%s» в коде %s не в таблице перевода (%s) — прибор '
                'не берётся решать, тот это кадр или другой; дописать букву в '
                'ПЕРЕВОД_СУФФИКСА тем же PR, что и кадр'
                % (буква, кусок, ' '.join(sorted(ПЕРЕВОД_СУФФИКСА))))
    return семья, итог


def кадры_базы(каталог):
    """Коды кадров ИЗ ЗАГОЛОВКОВ файлов базы: {нормальный код: [файлы]}.

    Файл без кода в `<title>` роняет прибор словами: кадр, которого прибор не
    опознал, неотличим от кадра, которого нет, — а это уже приговор Б.
    """
    if not os.path.isdir(каталог):
        не_выполнено('каталога кадров «%s» нет — связь НЕ СЛИЧЕНА. Это '
                     '`_docs/design/screens` репозитория Cafe13KPG; дать '
                     'путь к чекауту флагом --база' % каталог)
    коды, безымянные = {}, []
    файлов = 0
    for имя in sorted(os.listdir(каталог)):
        if not имя.endswith('.dc.html'):
            continue
        файлов += 1
        исходник = io.open(os.path.join(каталог, имя), encoding='utf-8',
                           errors='replace').read()
        м = КОД_В_ЗАГОЛОВКЕ.search(исходник)
        if not м:
            безымянные.append(имя)
            continue
        разобран = разобрать_код(м.group(1))
        if разобран is None:
            безымянные.append(имя)
            continue
        коды.setdefault('%s%s' % разобран, []).append(имя)
    if безымянные:
        не_выполнено('у %d кадров в `<title>` нет кода вида E12 или код не '
                     'разобран: %s — прибор не опознал кадр, а неопознанный '
                     'кадр неотличим от отсутствующего'
                     % (len(безымянные), ' '.join(безымянные[:6])))
    if файлов < НАДО_КАДРОВ:
        не_выполнено('в «%s» разобрано %d кадров (ждём не меньше %d) — '
                     'признак не тот или каталог не тот, числам верить нельзя'
                     % (каталог, файлов, НАДО_КАДРОВ))
    return коды


def коды_реестра(путь):
    """Колонка «кадр» из СТАДИИ.tsv: {нормальный код: [экраны]}.

    Колонка вторая, значения через запятую (`E27,E33`), «—» и пустое — это
    «не вписан», и таких строк законно много: заполнять их прибор не берётся.
    """
    if not os.path.isfile(путь):
        не_выполнено('реестра «%s» нет — связь НЕ СЛИЧЕНА' % путь)
    названо, строк, кривые = {}, 0, []
    for строка in io.open(путь, encoding='utf-8').read().splitlines():
        if not строка.strip() or строка.lstrip().startswith('#'):
            continue
        поля = строка.split('\t')
        if len(поля) < 2:
            continue
        строк += 1
        клетка = поля[1].strip()
        if клетка in ('—', ''):
            continue
        for кусок in re.split(r'[,\s]+', клетка):
            if not кусок:
                continue
            разобран = разобрать_код(кусок)
            if разобран is None:
                кривые.append('%s: %s' % (поля[0], кусок))
                continue
            названо.setdefault('%s%s' % разобран, []).append(поля[0])
    if кривые:
        не_выполнено('в колонке «кадр» есть значения не формы E12 или E12б: '
                     '%s — признак прибора уже их не видит, и приговор был бы '
                     'о меньшем предмете, чем кажется' % '; '.join(кривые[:6]))
    if строк < НАДО_СТРОК:
        не_выполнено('в «%s» строк предмета %d (ждём не меньше %d) — реестр '
                     'не тот, числам верить нельзя' % (путь, строк, НАДО_СТРОК))
    return названо


def семья(код):
    return re.match(r'E\d+', код).group(0)


def приговор(база, реестр):
    """Два приговора о СВЯЗИ. Возвращает (код выхода, строки для печати)."""
    красное = []

    # А) реестр называет код, которого в базе нет.
    нет_кадра = sorted(к for к in реестр if к not in база)
    for к in нет_кадра:
        красное.append(
            '⚠ реестр называет кадр %s, которого в базе НЕТ — строки: %s. '
            'Либо кадр не нарисован, а строка обещает, либо код в строке '
            'другой' % (к, ' '.join(sorted(set(реестр[к])))))

    # Б) семья кадров, на которую не ссылается ни одна строка реестра.
    семьи_базы = {}
    for к, файлы in база.items():
        семьи_базы.setdefault(семья(к), []).extend(файлы)
    названные = {семья(к) for к in реестр}
    сироты = sorted(set(семьи_базы) - названные, key=lambda с: int(с[1:]))
    for с in сироты:
        красное.append(
            '⚠ кадры %s (%d) не названы НИ ОДНОЙ строкой реестра — для '
            'владельца они нарисованы, а для страницы «Экраны» их нет'
            % (с, len(семьи_базы[с])))

    if красное:
        return 1, ['КРАСНОЕ:'] + ['  ' + с for с in красное]
    return 0, ['зелёное: связь кадр↔экран сошлась с двух сторон — реестр '
               'называет %d кодов, в базе %d кадров в %d семьях, и ни одна '
               'сторона не осталась без другой'
               % (len(реестр), sum(len(ф) for ф in база.values()),
                  len(семьи_базы))]


# ── самопроверка ────────────────────────────────────────────────────────────
# ⚠ Гоняется ТОТ ЖЕ `приговор`, что в бою, и каждая ветвь достаётся подлогом:
# ветвь без подлога не проверена. Сети и чекаута не требует.
def самопроверка():
    беды = []

    def проба(подпись, база, реестр, ждём_код, ждём_слова):
        код, строки = приговор(база, реестр)
        вывод = '\n'.join(строки)
        if код != ждём_код:
            беды.append('%s: код %d вместо %d' % (подпись, код, ждём_код))
        elif ждём_слова and ждём_слова not in вывод:
            беды.append('%s: в приговоре нет «%s» — дано: %s'
                        % (подпись, ждём_слова, вывод.replace('\n', ' | ')))
        return вывод

    чистая_база = {'E10': ['E10-a.dc.html'], 'E10b': ['E10b-b.dc.html'],
                   'E11': ['E11-c.dc.html']}
    чистый_реестр = {'E10': ['home'], 'E11': ['pass']}

    # Отрицательный контроль ПЕРВЫМ: без него «краснеет всегда» прошло бы.
    зелёный = проба('чистая пара', чистая_база, чистый_реестр, 0, 'зелёное')
    # Приговор А: строка обещает кадр, которого нет.
    а = проба('А: реестр называет небывший кадр', чистая_база,
              dict(чистый_реестр, E99=['soon']), 1, 'которого в базе НЕТ')
    # Приговор Б: семья кадров без строки.
    б = проба('Б: семья кадров без строки',
              dict(чистая_база, E12=['E12-d.dc.html'], E12b=['E12b-e.dc.html']),
              чистый_реестр, 1, 'не названы НИ ОДНОЙ строкой')
    if а == б:
        беды.append('два разных приговора дали один текст')
    if 'E10b' in а or 'E10b' in б:
        беды.append('приговор назвал вариант E10b, у которого строка есть '
                    'через семью E10 — предмет Б это СЕМЬЯ, а не вариант')
    # Вариант без своей строки, но со строкой у семьи, краснеть НЕ должен:
    # иначе прибор потребовал бы вписывать каждый вариант кадра отдельно.
    проба('вариант покрыт семьёй', чистая_база, {'E10': ['home'], 'E11': ['p']},
          0, 'зелёное')
    # Перевод суффикса: реестр латиницей, заголовок кириллицей — ОДИН кадр.
    проба('суффикс кириллицей равен латинскому',
          {'E23b': ['E23b-cart-denied.dc.html']}, {'E23b': ['cart']}, 0, 'зелёное')
    if разобрать_код('E23б') != ('E23', 'b'):
        беды.append('перевод суффикса не сработал: E23б дал %r'
                    % (разобрать_код('E23б'),))
    if разобрать_код('E23b') != ('E23', 'b'):
        беды.append('латинский суффикс испорчен переводом: E23b дал %r'
                    % (разобрать_код('E23b'),))
    if разобрать_код('не код') is not None:
        беды.append('форма «не код» принята за код')

    # Сторож таблицы суффиксов: неизвестная кириллическая буква обязана
    # ОСТАНОВИТЬ прибор, а не превратиться в «кадра нет». Ловится выходом 2.
    # ⚠ Строка отказа от этой пробы ПЕЧАТАЕТСЯ — сторож зовётся настоящий, а
    # не его копия. Предупреждаем читателя, иначе зелёная самопроверка с
    # «ПРОВЕРКА НЕ ВЫПОЛНЕНА» посередине читается как беда.
    print('  проба сторожа таблицы суффиксов — строка ниже ОЖИДАЕМАЯ:')
    буква = next((б for б in 'дезийлмнопрстуфхцчшщыэ'
                  if б not in ПЕРЕВОД_СУФФИКСА), None)
    if буква is None:
        беды.append('в пробе не нашлось кириллической буквы вне таблицы — '
                    'сторож таблицы не проверен')
    else:
        try:
            разобрать_код('E30' + буква)
            беды.append('суффикс «%s» вне таблицы прошёл молча' % буква)
        except SystemExit as е:
            if е.code != 2:
                беды.append('сторож таблицы дал код %r вместо 2' % (е.code,))

    if беды:
        print('самопроверка РАЗОШЛАСЬ:')
        for б in беды:
            print('  ' + б)
        return 1
    print('самопроверка: оба приговора достаются подлогом и различны, чистая '
          'пара зелена, семья покрывает свои варианты, суффикс кириллицей '
          'равен латинскому, буква вне таблицы останавливает прибор')
    return 0


def main(аргв):
    if '--самопроверка' in аргв:
        return самопроверка()
    база_путь = реестр_путь = None
    i = 0
    while i < len(аргв):
        if аргв[i] == '--база' and i + 1 < len(аргв):
            база_путь = аргв[i + 1]
            i += 2
        elif аргв[i] == '--реестр' and i + 1 < len(аргв):
            реестр_путь = аргв[i + 1]
            i += 2
        else:
            не_выполнено('непонятный довод «%s»; зовут так: --база <каталог '
                         'кадров> [--реестр <tsv>]' % аргв[i])
    if база_путь is None:
        не_выполнено('не дан --база. Кадры живут в ДРУГОМ репозитории '
                     '(Cafe13KPG, `_docs/design/screens`), и прибор их не '
                     'качает нарочно: 30 МБ на каждый прогон при том, что '
                     'чекаут есть у каждой сессии. Отсутствие пути — «не '
                     'выполнено», а не «связь сошлась»')
    реестр_путь = реестр_путь or РЕЕСТР_ПО_УМОЛЧАНИЮ
    база = кадры_базы(база_путь)
    реестр = коды_реестра(реестр_путь)
    print('предмет: кадры «%s», реестр «%s»' % (база_путь, реестр_путь))
    код, строки = приговор(база, реестр)
    for с in строки:
        print(с)
    return код


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
