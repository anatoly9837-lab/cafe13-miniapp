// Общая фикстура людей у api и клиента: 200000001…200000014.
for (let i = 1; i <= 14; i++) ALLOW[String(2e8 + i)] = 'выдуманный человек общей фикстуры';

const SKIP_DIRS = new Set(['.git', 'node_modules']);
// Дата и время вырезаются только в ДОПУСТИМЫХ значениях: форма без диапазонов
// пропускала номер, записанный «датой» с месяцем 73 или «временем» 91:82, а год
// без диапазона — любой номер вида ГГГГ-ММ-ДД (подлоги в SELF ниже), —
// та же «форма вместо свойства», только у разрешающей стороны (нашёл
// arhitector-47 на #55).
const YY = '(?:19|20)\\d{2}', MM = '(?:0[1-9]|1[0-2])', DD = '(?:0[1-9]|[12]\\d|3[01])', HM = '(?:[01]?\\d|2[0-3]):[0-5]\\d';
// ⚠ Левая граница — `(?<!\d)`, а НЕ `\b`: `\b` не срабатывает между буквой и
// цифрой, и дата, стоящая в исходнике сразу за литералом табуляции
// (`'…#1\t2026-10-27\n'` в питоне), под вырезание не попадала — страж
// краснел на законной дате в tools/check-stages.py 15 раз и завалил ствол
// 27.10.2026. Диапазоны полей при этом те же, то есть послабление ровно
// шириной случая: «номер, записанный датой с месяцем 73», по-прежнему красный.
const ISO = new RegExp('(?<!\\d)' + YY + '-' + MM + '-' + DD + '(?:T' + HM + '(?::[0-5]\\d(?:\\.\\d+)?)?(?:Z|[+-]' + HM + ')?)?(?!\\d)', 'g');
const DMY = new RegExp('\\b' + DD + '\\.' + MM + '\\.' + YY + '\\b', 'g');
const CLOCK = new RegExp('\\b' + HM + '(?::[0-5]\\d)?\\b', 'g');
const ORDER_NO = /\b\d{6}-\d{2}\b/g;
const CENTS = /(?<![\d.])\d{1,6}\.\d{2}(?![\d.])/g;
const SVG = /\b(?:d|viewBox|points)="[^"]*"/g;
// Хеш — законный формат, как дата: РОВНО 40 (sha1) или 64 (sha256) знака
// `[0-9a-f]`, с якорями на обе границы, и обязательно хотя бы одна БУКВА.
// ⚠ Якоря и точная длина — не придирка: шаблон «много шестнадцатеричных»
// съел бы и чужой номер, потому что любой телефон — тоже `[0-9a-f]+`.
// Буква обязательна по той же причине: 64 цифры подряд остаются красными.
// Куски хеша в ALLOW не вносятся — при каждой пересъёмке они новые, и
// разрешающий список пришлось бы править каждым прогоном (довод
// arhitector-47, 27.10.2026). Случай — `клиент_sha256` в screens/vidimost.json.
const SHA = /(?<![0-9a-f])(?=[0-9a-f]*[a-f])(?:[0-9a-f]{64}|[0-9a-f]{40})(?![0-9a-f])/gi;
const HEX = /\b0x[0-9a-f]+\b/gi;
const RUN = /\d(?:[ \t_.\-/()+]{0,2}\d)+/g;

// Строка → числа из 7+ цифр, которых нет в списке: [[запись, цифры], …].
function scan(line) {
  const t = line.replace(SVG, ' ').replace(SHA, ' ')
                .replace(ISO, ' ').replace(DMY, ' ').replace(CLOCK, ' ')
                .replace(ORDER_NO, ' ').replace(CENTS, ' ')
                .replace(HEX, h => ' ' + BigInt(h).toString() + ' ');
  const out = [];
  for (const m of t.matchAll(RUN)) {
    const d = m[0].replace(/\D/g, '');
    if (d.length >= 7 && !ALLOW[d]) out.push([m[0].trim(), d]);
  }
  return out;
}

