#!/bin/bash
# ВОРОТА ПЕРЕД МЕРДЖЕМ клиентского PR — наряд arhitector-47 (30.10.2026).
#
#     tools/pered-mergem.sh <каталог дерева мерджа>
#
# Коды: 0 — все приговорные шаги нули; 1 — КРАСНОЕ; 2 — ПРОВЕРКА НЕ ВЫПОЛНЕНА.
#
# ⚠ ПОДЛЕЖАЩЕЕ — ДЕРЕВО МЕРДЖА, а не рабочее дерево и не выложенный клиент.
# Это сказано в каждой строке вывода нарочно: у соседних приборов подлежащее
# другое, и приговор, прочитанный не о том предмете, дороже отсутствия
# приговора. `tools/check-stages.py` без `--файл` судит ВЫЛОЖЕННЫЙ клиент —
# здесь он зовётся только с `--файл`.
#
# ⚠ ЧЕГО ЗДЕСЬ НЕТ, и это не забывчивость:
#   • ворот номера версии — их держит `tools/pered-pokazom.cjs` на РАБОЧЕМ
#     дереве, перед показом владельцу. Вторая редакция того же требования
#     разошлась бы молча;
#   • предела отставания описи — он предупреждение, а не ворота (решение
#     владельца 29.10.2026), и живёт в ночном проходе.
#
# ⚠ `ids-clean.cjs` зовут И ворота перед показом. Это НЕ вторая редакция
# требования: прибор тот же, а подлежащее другое — там рабочее дерево, здесь
# дерево мерджа. Утечка номера живого человека попадает в публичную историю
# именно мерджем, поэтому спрашивается на обоих предметах.
#
# ⚠ ОТЧЁТНЫЕ шаги (снимки, видимость, сверка страницы) ПЕЧАТАЮТ, но в код
# выхода не входят: долг описи — предупреждение, и склейка сделала бы ответ
# «можно ли мерджить» непрочитываемым. Решение архитектора.
# ⚠ ИМЕНА ПЕРЕМЕННЫХ — ТОЛЬКО ASCII: кириллическое имя bash читает как ИМЯ
# КОМАНДЫ, скрипт НЕ останавливается, а `$ОБРАЗ` уходит в приговор ЛИТЕРАЛОМ
# («нет образа $ОБРАЗ») — куплено на себе первым же прогоном. Имена ФУНКЦИЙ
# bash кириллицей принимает (замер 06.11.2026) — там это вкус, не дефект.
# ⚠ Признак этого класса жил ЗДЕСЬ, в комментарии, четырьмя ветвями grep — и
# ровно это координатор назвал «держится на привычке»: ни один прибор его не
# звал. Теперь он прибор, зовётся шагом 8 и считает ДЕРЕВО, а не этот файл;
# второй редакции тут нарочно нет (копия признака расходится с прибором молча).
# Что он умеет, чего нет и чем это измерено — проза `tools/imena-ascii.py`.
set -u

IMAGE=agenthost/playwright:1.59.1
T=${1:-}
rc_total=0
# ⚠ Отчёты мердж не держат — и всё же «ЗЕЛЁНОЕ» не должно читаться как «всё
# измерено»: умерший отчёт это «не выполнено» для СВОЕЙ половины. Поэтому они
# считаются отдельно и называются в приговоре числом. Поймано одиннадцатым
# входом: при подложенной битой арифметике ворота доходили до конца и печатали
# «ЗЕЛЁНОЕ» — верно по приговору и слишком гладко по виду.
reports_dead=0
die() { echo "ПРОВЕРКА НЕ ВЫПОЛНЕНА: $1" >&2; exit 2; }
step()   { printf '\n── %s ──\n' "$1"; }

# ── 0. предмет ──────────────────────────────────────────────────────────────
# ⚠ Сторож предмета стоит ПЕРВЫМ, и куплен он чужой ошибкой (arhitector-47,
# 30.10.2026): дерево, названное SHA вместо каталога, давало rc=0 и зелёную
# последнюю строку — то есть «проверено» о том, чего не открывали.
[ -n "$T" ] || die 'не назван каталог дерева мерджа: tools/pered-mergem.sh <каталог>'
[ -d "$T" ] || die "«$T» не каталог — дерево мерджа распаковывают, а не называют sha"
T=$(cd "$T" && pwd) || die "в «$T» не зайти"
for f in index.html tools/catalog.py tools/check-stages.py screens/СТАДИИ.tsv tools/klient.cjs tools/klient.py tools/imena-ascii.py tools/bez-zova.py; do
    [ -f "$T/$f" ] || die "в дереве «$T» нет $f — это не дерево клиента"
done
command -v docker >/dev/null 2>&1 || die 'на хосте нет docker — приборы не звались'
command -v node >/dev/null 2>&1 || die 'на хосте нет node — состав клиента не прочитать'
# Клиент — несколько <script> по index.html (Cafe13KPG#806). Состав читают ДВА близнеца (cjs для приборов страницы,
# py для описи), и они обязаны отдать один перечень в одном порядке: иначе приборы судят разные клиенты (форма frontend-11)
KJS=$(node "$T/tools/klient.cjs" "$T" 2>&1) || die "состав клиента (klient.cjs): $KJS"
KPY=$(cd "$T" && python3 -I tools/klient.py "$T" 2>&1) || die "состав клиента (klient.py): $KPY"
[ "$KJS" = "$KPY" ] || die "близнецы состава клиента разошлись: klient.cjs ≠ klient.py — приборы судили бы разные клиенты"
# и в where(): на нём держатся сообщения приборов описи — первый байт каждого файла обязан дать «файл:1» у обоих (frontend-events-9d)
WJS=$(node "$T/tools/klient.cjs" "$T" --where 2>&1) || die "where() клиента (klient.cjs): $WJS"
WPY=$(cd "$T" && python3 -I tools/klient.py "$T" --where 2>&1) || die "where() клиента (klient.py): $WPY"
[ "$WJS" = "$WPY" ] || die "близнецы разошлись в where(): одна находка показала бы разные файлы"
WANT=$(printf '%s' "$KJS" | python3 -I -c 'import json,sys; print(json.dumps([f+":1" for f in json.load(sys.stdin)],ensure_ascii=False,separators=(",",":")))')
[ "$WJS" = "$WANT" ] || die "where() первого байта не «файл:1» — смещения в сообщениях приборов врут"
docker image inspect "$IMAGE" >/dev/null 2>&1 || die "нет образа $IMAGE"
command -v python3 >/dev/null 2>&1 || die 'на хосте нет python3'
# ⚠ РАБОЧИЙ КАТАЛОГ — В ~/.cache, А НЕ В /tmp, и это не вкусовщина: на хосте
# /tmp — общая tmpfs (7.9 ГБ на все сессии), а один прогон кладёт туда копию
# дерева и 43 свежих снимка. 26.10.2026 мои 5.6 ГБ в /tmp уронили чужую
# батарею, и смерть от нехватки памяти выглядела как `ENOENT` на файле в
# смонтированном томе, а не как «убит». Поймано чтением вывода первого
# прогона: `mktemp -d` дал /tmp/tmp.yAsSFY9u59.
RUNS_BASE=${PM_WORK:-$HOME/.cache/cafe13-pered-mergem}
mkdir -p "$RUNS_BASE" || die "не создаётся $RUNS_BASE"
W=$(mktemp -d "$RUNS_BASE/run-XXXXXX") || die 'не создался рабочий каталог'
# ⚠ На ЗЕЛЁНОМ прогоне рабочий каталог убирается, на красном ОСТАЁТСЯ: в нём
# лежат свежие снимки, свежая видимость и собранная заново страница — то, чем
# человек смотрит, ЧЕМ именно разошлось. Прибор, уносящий своё свидетельство
# вместе с отказом, заставляет прогонять его второй раз руками.
trap '[ "$rc_total" -eq 0 ] && rm -rf "$W" || echo "рабочий каталог прогона ОСТАВЛЕН: $W"' EXIT
echo "предмет: ДЕРЕВО МЕРДЖА $T"
echo "образ:   $IMAGE"

# ⚠ ПРЕДЕЛ ПАМЯТИ СТАВИТСЯ КОНТЕЙНЕРУ, и только флагом `--memory`: обёртка
# `systemd-run --scope -p MemoryMax=` для него СЛЕПА — контейнер уезжает в
# свою cgroup (`0::/`, `memory.max=max`), и предел хоста до него не доходит
# (замер `designer-55` 31.10.2026). Нужны ОБА флага: без `--memory-swap`
# ядро отдаёт тот же объём ещё и свопом, и предел перестаёт быть пределом.
# Здесь он в ОДНОМ месте и закрывает все четыре вызова; 26.10.2026 прогон
# без предела увёл хост в нагрузку 78 и уронил чужую батарею.
indocker() { # <каталог для /work> <путь скрипта внутри образа> …
    local out=$1; shift
    docker run --rm --memory=2g --memory-swap=2g -v "$T:/app:ro" -v "$out:/work" -w /work \
        -e LANG=ru_RU.UTF-8 -e LC_ALL=ru_RU.UTF-8 \
        --entrypoint node "$IMAGE" "$@"
}

# ── 1. живой режим (приговор) ───────────────────────────────────────────────
step '1. живой режим — tools/live.cjs (приговор)'
mkdir -p "$W/live"
indocker "$W/live" /app/tools/live.cjs; rc=$?
[ "$rc" -eq 0 ] || { echo "КРАСНОЕ: live.cjs rc=$rc"; rc_total=1; }

# ── 2. снимки (отчёт) ───────────────────────────────────────────────────────
step '2. снимки — tools/shots.cjs против описи дерева (ОТЧЁТ, не приговор)'
mkdir -p "$W/shots"
indocker "$W/shots" /app/tools/shots.cjs; rcs=$?
if [ "$rcs" -ne 0 ]; then
    echo "⚠ съёмка не прошла (rc=$rcs) — сверка снимков НЕ ВЫПОЛНЕНА, а не «снимки те же»"
    reports_dead=$((reports_dead + 1))
else
  # ⚠ Счёт идёт в ПОДОБОЛОЧКЕ: отчётный шаг, умерший по своей причине, не
  # обязан уносить приговор. Возврат `#189` (arhitector-47, 30.10.2026) был
  # ровно про это: ошибка арифметического раскрытия ВЫХОДИТ из неинтерактивного
  # bash, и ворота умирали в шаге 2 с rc=1 — без строки приговора и без шагов
  # 4–7, то есть «не выполнено» читалось как «КРАСНОЕ».
  # ⚠ ИМЕНА, А НЕ ТОЛЬКО ЧИСЛО. Число отвечает «сколько», а спрошено было
  # «какие»: 31.10.2026 на Cafe13KPG#712 правка облика развела 45 снимков из
  # 47, и весь вес отчёта лёг на два, которые НЕ изменились. Свидетельство
  # уезжает на зелёном (`trap` выше, и это решение), поэтому имена печатаются
  # СРАЗУ — те два пришлось добывать второй съёмкой руками, уже после ворот.
  # Решение arhitector-47: лучше напечатать имена, чем описывать, что их нет.
  ( differ=0; absent=0
    for p in "$W/shots"/*.png; do
        nm=$(basename "$p")
        if [ -f "$T/screens/$nm" ]; then
            cmp -s "$p" "$T/screens/$nm" || { differ=$((differ + 1)); echo "  ≠ $nm"; }
        else
            absent=$((absent + 1)); echo "  + $nm"
        fi
    done
    total_png=$(ls "$W/shots"/*.png 2>/dev/null | wc -l)
    echo "снимков снято $total_png · отличается от описи дерева $differ · нет в описи $absent"
    # ⚠ ПОСЛЕДНЯЯ команда подоболочки задаёт её код возврата, поэтому цепочка
    # `[ … ] && [ … ] && echo` здесь НЕ годится: при «нет в описи 1» второе
    # условие ложно, подоболочка выходит с 1, и `||` ниже печатает ложное
    # «отчёт НЕ ВЫПОЛНЕН» о живом отчёте. Поймано десятым входом (дерево без
    # одного снимка): строка счёта и ложная тревога напечатались РЯДОМ.
    if [ "$differ" -eq 0 ] && [ "$absent" -eq 0 ]; then
        echo '(опись снимков под этот клиент уже собрана)'
    fi
  ) || { echo '⚠ отчёт о снимках НЕ ВЫПОЛНЕН (сам счёт умер) — и мердж он не держит'
         reports_dead=$((reports_dead + 1)); }
fi

# ── 3. видимость (отчёт) ────────────────────────────────────────────────────
step '3. видимость — tools/vidimost.cjs против описи дерева (ОТЧЁТ)'
mkdir -p "$W/vid"
indocker "$W/vid" /app/tools/vidimost.cjs >"$W/vid.log" 2>&1; rcv=$?
if [ "$rcv" -ne 0 ] || [ ! -s "$W/vid/vidimost.json" ]; then
    echo "⚠ обход видимости не прошёл (rc=$rcv) — сверка НЕ ВЫПОЛНЕНА"
    reports_dead=$((reports_dead + 1))
    tail -3 "$W/vid.log"
else
    # ⚠ СВЕРКИ ЗДЕСЬ ДВЕ, И ИХ НАРОЧНО НЕ СКЛЕИВАЮТ. В файле видимости лежат
    # два разных предмета: кто что видит (люди, вкладки, права, двери) и
    # слепки страницы, с которой снято (Cafe13KPG#806). Сличать их одним
    # `diff` нельзя: карта слепков — 28 строк шестнадцатеричного, и при любой
    # правке клиента она одна забивает `head -20`, пряча расхождение по
    # ВИДИМОСТИ, то есть ровно то, зачем шаг заведён. Поэтому слепки
    # докладываются ЧИСЛОМ и ИМЕНАМИ файлов, а из `diff` вынимаются.
    # ⚠ Шаг остаётся ОТЧЁТНЫМ. Красное по закоммиченной видимости было бы
    # возвратом блокировки, снятой словом владельца 29.10.2026; звальщик для
    # неё — ночной проход, кладущий карточку (решение координатора 04.11).
    slepki_report() { python3 -I -c '
import io, json, sys
новый = json.load(io.open(sys.argv[1], encoding="utf-8")).get("слепки_страницы")
старый = json.load(io.open(sys.argv[2], encoding="utf-8")).get("слепки_страницы")
if not isinstance(старый, dict) or not старый:
    print("  слепки страницы: в описи дерева карты нет — она снята прибором "
          "прежней редакции (до Cafe13KPG#806), сверить нечем")
elif not isinstance(новый, dict) or not новый:
    print("  слепки страницы: СВЕЖИЙ обход карты не дал — сверять нечем")
else:
    пришли = [ф for ф in новый if ф not in старый]
    ушли = [ф for ф in старый if ф not in новый]
    разошлись = [ф for ф in новый if ф in старый and новый[ф] != старый[ф]]
    if not (пришли or ушли or разошлись):
        print("  слепки страницы: сошлись все %d" % len(новый))
    else:
        if пришли or ушли:
            print("  слепки страницы: СОСТАВ разошёлся — пришли: %s; ушли: %s"
                  % (", ".join(пришли) or "—", ", ".join(ушли) or "—"))
        if разошлись:
            print("  слепки страницы: разошлись %d из %d — %s"
                  % (len(разошлись), len(новый), ", ".join(разошлись[:8])
                     + (" и ещё %d" % (len(разошлись) - 8) if len(разошлись) > 8 else "")))
' "$1" "$2"; }
    # «снято» — время прогона, оно обязано отличаться и о клиенте не говорит;
    # слепки и их свод вынимаются, потому что доложены отдельно (выше).
    strip_time() { python3 -I -c '
import io, json, sys
d = json.load(io.open(sys.argv[1], encoding="utf-8"))
for ключ in ("снято", "слепки_страницы", "свод_слепков"):
    d.pop(ключ, None)
print(json.dumps(d, ensure_ascii=False, sort_keys=True, indent=1))' "$1"; }
    slepki_report "$W/vid/vidimost.json" "$T/screens/vidimost.json" ||
        { echo '  ⚠ сверка слепков НЕ ВЫПОЛНЕНА'; reports_dead=$((reports_dead + 1)); }
    if strip_time "$W/vid/vidimost.json" > "$W/vid-new.json" &&
       strip_time "$T/screens/vidimost.json" > "$W/vid-old.json"; then
        if diff -q "$W/vid-new.json" "$W/vid-old.json" >/dev/null; then
            echo '  видимость (люди, вкладки, двери) совпала с описью дерева'
        else
            echo '  видимость РАЗОШЛАСЬ с описью дерева — опись под этот клиент не пересобрана:'
            diff "$W/vid-old.json" "$W/vid-new.json" | head -20
        fi
    else
        echo '  ⚠ видимость не разобралась — сверка НЕ ВЫПОЛНЕНА'
        reports_dead=$((reports_dead + 1))
    fi
fi

# ── 4. каталог (приговор) + сверка страницы (отчёт) ─────────────────────────
# ⚠ ПОДЛЕЖАЩЕЕ ШАГА 4 — СВЕЖИЙ манифест, написанный съёмкой, а НЕ
# `screens/manifest.json` дерева. Померено прогоном (30.10.2026): подлог
# «снятый экран без условия» ВНУТРЬ манифеста дерева даёт ЗЕЛЁНОЕ — шаг его не
# читает вовсе. Краснеет он на том же дефекте, поданном через подлежащее: у
# снимаемого экрана убрано условие в `tools/catalog.py` → «ПРОВЕРКА НЕ
# ВЫПОЛНЕНА: у экранов страницы нет условия видимости».
# Отсюда названный предел: ворота спрашивают «собирается ли страница ИЗ ЭТОГО
# клиента», и испорченный ЗАКОММИЧЕННЫЙ манифест они не судят — он производный
# артефакт, и расхождение с ним видно отчётами шагов 2–3, а не приговором.
step '4. каталог — tools/catalog.py на СВЕЖИХ снимках (приговор) + сверка страницы (отчёт)'
if [ "$rcs" -ne 0 ] || [ "$rcv" -ne 0 ]; then
    echo '⚠ каталог НЕ ВЫПОЛНЕН: нет свежих снимков или видимости — зелёного здесь быть не может'
    [ "$rc_total" -eq 0 ] && rc_total=2
else
    cp -r "$T" "$W/tree" 2>/dev/null
    rm -f "$W/tree/screens.html"
    cp "$T/screens/СТАДИИ.tsv" "$W/shots/" && cp "$W/vid/vidimost.json" "$W/shots/" || die 'не собрался каталог снимков'
    ( cd "$W/tree" && python3 -I tools/catalog.py "$W/shots" ); rcc=$?
    # ⚠ 2 и 1 — РАЗНЫЕ приговоры, и до 04.11.2026 шаг звал красным оба. Все 17
    # отказов catalog.py уходили кодом 1 (`sys.exit('текст')`), и «мерить было
    # нечем» печаталось как «страница под это дерево не собирается».
    if [ "$rcc" -eq 2 ]; then
        echo "каталог НЕ ВЫПОЛНЕН: catalog.py rc=2 — отказ прибора, мерить было нечем (строка отказа выше)"
        [ "$rc_total" -eq 0 ] && rc_total=2
    elif [ "$rcc" -ne 0 ]; then
        echo "КРАСНОЕ: catalog.py rc=$rcc — страница под это дерево не собирается"
        rc_total=1
    elif [ -f "$W/tree/screens.html" ] && [ -f "$T/screens.html" ]; then
        if cmp -s "$W/tree/screens.html" "$T/screens.html"; then
            echo 'страница дерева совпала с собранной заново'
        else
            echo "страница дерева ОТЛИЧАЕТСЯ от собранной заново на $(diff "$T/screens.html" "$W/tree/screens.html" | grep -c '^[<>]') строк — опись не пересобрана (отчёт, мердж не держит)"
        fi
    fi
fi

# ── 5–6. прибор стадий (приговоры) ──────────────────────────────────────────
step '5. прибор стадий — самопроверка (приговор)'
( cd "$T" && python3 -I tools/check-stages.py --самопроверка >"$W/sp.log" 2>&1 ); rc=$?
[ "$rc" -eq 0 ] || { echo "КРАСНОЕ: самопроверка прибора стадий rc=$rc"; grep -i 'провален' "$W/sp.log" | head -5; rc_total=1; }
[ "$rc" -eq 0 ] && echo 'самопроверка прибора стадий: rc=0'

