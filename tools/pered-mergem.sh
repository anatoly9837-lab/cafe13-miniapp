#!/bin/bash
# ВОРОТА ПЕРЕД МЕРДЖЕМ клиентского PR — наряд arhitector-47 (30.10.2026).
#
#     tools/pered-mergem.sh <каталог дерева мерджа>
#
# Коды: 0 — все приговорные шаги нули; 1 — КРАСНОЕ; 2 — ПРОВЕРКА НЕ ВЫПОЛНЕНА.
#
# ⚠ ПОДЛЕЖАЩЕЕ — ДЕРЕВО МЕРДЖА, а не рабочее дерево и не выложенный клиент.
# Это сказано в каждой строке вывода нарочно: у соседних приборов подлежащее
# другое, и приговор, прочитанный не о том предмете, дороже отсутствия
# приговора. `tools/check-stages.py` без `--файл` судит ВЫЛОЖЕННЫЙ клиент —
# здесь он зовётся только с `--файл`.
#
# ⚠ ЧЕГО ЗДЕСЬ НЕТ, и это не забывчивость:
#   • ворот номера версии — их держит `tools/pered-pokazom.cjs` на РАБОЧЕМ
#     дереве, перед показом владельцу. Вторая редакция того же требования
#     разошлась бы молча;
#   • предела отставания описи — он предупреждение, а не ворота (решение
#     владельца 29.10.2026), и живёт в ночном проходе.
#
# ⚠ `ids-clean.cjs` зовут И ворота перед показом. Это НЕ вторая редакция
# требования: прибор тот же, а подлежащее другое — там рабочее дерево, здесь
# дерево мерджа. Утечка номера живого человека попадает в публичную историю
# именно мерджем, поэтому спрашивается на обоих предметах.
#
# ⚠ ОТЧЁТНЫЕ шаги (снимки, видимость, сверка страницы) ПЕЧАТАЮТ, но в код
# выхода не входят: долг описи — предупреждение, и склейка сделала бы ответ
# «можно ли мерджить» непрочитываемым. Решение архитектора.
# ⚠ ИМЕНА ПЕРЕМЕННЫХ — ТОЛЬКО ASCII: кириллическое имя bash читает как ИМЯ
# КОМАНДЫ, скрипт НЕ останавливается, а `$ОБРАЗ` уходит в приговор ЛИТЕРАЛОМ
# («нет образа $ОБРАЗ») — куплено на себе первым же прогоном. Имена ФУНКЦИЙ
# bash кириллицей принимает (замер 06.11.2026) — там это вкус, не дефект.
# ⚠ Признак этого класса жил ЗДЕСЬ, в комментарии, четырьмя ветвями grep — и
# ровно это координатор назвал «держится на привычке»: ни один прибор его не
# звал. Теперь он прибор, зовётся шагом 8 и считает ДЕРЕВО, а не этот файл;
# второй редакции тут нарочно нет (копия признака расходится с прибором молча).
# Что он умеет, чего нет и чем это измерено — проза `tools/imena-ascii.py`.
# ⚠ ПРЕДЕЛ — ЧЕГО ВОРОТА НЕ ПРОВЕРЯЮТ (Cafe13KPG#789, замер arhitector-62; шаги 10–16 дописаны
# frontend-40 20.11.2026). Зелёное здесь значит «прошли шаги 1, 4–16», и НЕ значит:
#   • `svyaz-kadrov.py` — связь кадр↔экран: ему нужна база кадров `Cafe13KPG`, её в дереве мерджа
#     нет, а кадры заморожены. Гоняется руками по поводу правки кадров;
#   • `check-recepty.py` — рецепты README исполняются: прогон зовёт съёмку и обход образом, это
#     батарея, а не ворота: один из рецептов — весь live.cjs, замер 20.11.2026 — больше 18 мин, погашен
#     недоделанным. Гоняется по поводу правки README;
#   • САМОПРОВЕРКИ приборов (`--самопроверка`) — кроме прибора стадий (шаг 5): ворота судят
#     дерево, а не то, различает ли прибор; самопроверку гоняет автор правки прибора;
#   • шаг 14 с кодом 2 («рецепт не исполнен», «не измерено») МЕРДЖ НЕ ДЕРЖИТ: на стволе 20.11.2026
#     таких 23+52, и приговор «не выполнено» не дал бы смержить ничего. Число печатается в
#     последней строке — «зелёное» при нём читать «шаг 7 смотрел не на всё», а не «сошлось»;
#   • опись (снимки, видимость, страница) — отчёты, см. ниже; номер версии — `pered-pokazom.cjs`;
#   • сервер `cafe13-api` — у него свои ворота, `tools/pered-mergem.sh` в его клоне.
set -u

IMAGE=agenthost/playwright:1.59.1
T=${1:-}
rc_total=0
# ⚠ Отчёты мердж не держат — и всё же «ЗЕЛЁНОЕ» не должно читаться как «всё
# измерено»: умерший отчёт это «не выполнено» для СВОЕЙ половины. Поэтому они
# считаются отдельно и называются в приговоре числом. Поймано одиннадцатым
# входом: при подложенной битой арифметике ворота доходили до конца и печатали
# «ЗЕЛЁНОЕ» — верно по приговору и слишком гладко по виду.
reports_dead=0
die() { echo "ПРОВЕРКА НЕ ВЫПОЛНЕНА: $1" >&2; exit 2; }
step()   { printf '\n── %s ──\n' "$1"; }

# ── 0. предмет ──────────────────────────────────────────────────────────────
# ⚠ Сторож предмета стоит ПЕРВЫМ, и куплен он чужой ошибкой (arhitector-47,
# 30.10.2026): дерево, названное SHA вместо каталога, давало rc=0 и зелёную
# последнюю строку — то есть «проверено» о том, чего не открывали.
[ -n "$T" ] || die 'не назван каталог дерева мерджа: tools/pered-mergem.sh <каталог>'
[ -d "$T" ] || die "«$T» не каталог — дерево мерджа распаковывают, а не называют sha"
T=$(cd "$T" && pwd) || die "в «$T» не зайти"
for f in index.html tools/catalog.py tools/check-stages.py screens/СТАДИИ.tsv tools/klient.cjs tools/klient.py tools/imena-ascii.py tools/bez-zova.py \
         tools/api-on.cjs tools/recepty-index.py tools/check-sostav.py tools/reestr-oblika.py tools/sverka-recepta.py \
         tools/pometki-do-sborki.py tools/diffshape-test.cjs; do
    [ -f "$T/$f" ] || die "в дереве «$T» нет $f — это не дерево клиента"
done
command -v docker >/dev/null 2>&1 || die 'на хосте нет docker — приборы не звались'
command -v node >/dev/null 2>&1 || die 'на хосте нет node — состав клиента не прочитать'
# Клиент — несколько <script> по index.html (Cafe13KPG#806). Состав читают ДВА близнеца (cjs для приборов страницы,
# py для описи), и они обязаны отдать один перечень в одном порядке: иначе приборы судят разные клиенты (форма frontend-11)
KJS=$(node "$T/tools/klient.cjs" "$T" 2>&1) || die "состав клиента (klient.cjs): $KJS"
KPY=$(cd "$T" && python3 -I tools/klient.py "$T" 2>&1) || die "состав клиента (klient.py): $KPY"
[ "$KJS" = "$KPY" ] || die "близнецы состава клиента разошлись: klient.cjs ≠ klient.py — приборы судили бы разные клиенты"
# и в where(): на нём держатся сообщения приборов описи — первый байт каждого файла обязан дать «файл:1» у обоих (frontend-events-9d)
WJS=$(node "$T/tools/klient.cjs" "$T" --where 2>&1) || die "where() клиента (klient.cjs): $WJS"
WPY=$(cd "$T" && python3 -I tools/klient.py "$T" --where 2>&1) || die "where() клиента (klient.py): $WPY"
[ "$WJS" = "$WPY" ] || die "близнецы разошлись в where(): одна находка показала бы разные файлы"
WANT=$(printf '%s' "$KJS" | python3 -I -c 'import json,sys; print(json.dumps([f+":1" for f in json.load(sys.stdin)],ensure_ascii=False,separators=(",",":")))')
[ "$WJS" = "$WANT" ] || die "where() первого байта не «файл:1» — смещения в сообщениях приборов врут"
docker image inspect "$IMAGE" >/dev/null 2>&1 || die "нет образа $IMAGE"
command -v python3 >/dev/null 2>&1 || die 'на хосте нет python3'
# ⚠ РАБОЧИЙ КАТАЛОГ — В ~/.cache, А НЕ В /tmp, и это не вкусовщина: на хосте
# /tmp — общая tmpfs (7.9 ГБ на все сессии), а один прогон кладёт туда копию
# дерева и 43 свежих снимка. 26.10.2026 мои 5.6 ГБ в /tmp уронили чужую
# батарею, и смерть от нехватки памяти выглядела как `ENOENT` на файле в
# смонтированном томе, а не как «убит». Поймано чтением вывода первого
# прогона: `mktemp -d` дал /tmp/tmp.yAsSFY9u59.
RUNS_BASE=${PM_WORK:-$HOME/.cache/cafe13-pered-mergem}
mkdir -p "$RUNS_BASE" || die "не создаётся $RUNS_BASE"
# ⚠ УБОРКА СТАРЫХ ПРОГОНОВ — при СТАРТЕ, в приборе, а не в правиле (Cafe13KPG#938). Каталог красного прогона
# остаётся нарочно (ниже), но чистил его только автор, разбирающий красное. К 19.11.2026 скопилось 22 каталога
# (389 МБ), самый старый от 30.10. Сносятся только `run-*` старше 3 суток по времени изменения: прогон идёт
# минуты, поэтому трёхсуточный каталог живым быть не может, в том числе чужой. Свежий красный остаётся для
# разбора. Неудача уборки ворота НЕ роняет: она печатается, приговор о дереве от неё не зависит.
old_runs=$(find "$RUNS_BASE" -mindepth 1 -maxdepth 1 -type d -name 'run-*' -mmin +$((3 * 24 * 60)))
if [ -n "$old_runs" ]; then
    gone=0
    while IFS= read -r d; do
        if rm -rf "${d:?}"; then gone=$((gone + 1)); else echo "⚠ старый прогон не убран: $d"; fi
    done <<< "$old_runs"
    echo "убрано старых прогонов (старше 3 суток): $gone из $(printf '%s\n' "$old_runs" | wc -l)"
fi
W=$(mktemp -d "$RUNS_BASE/run-XXXXXX") || die 'не создался рабочий каталог'
# ⚠ Рабочий каталог убирается ТОЛЬКО на чистом зелёном: код выхода 0 И ни один
# отчётный шаг ничего не нашёл. На красном, на «не выполнено» (в том числе через
# die — код выхода, а не rc_total) и на ЗЕЛЁНОМ С НАХОДКОЙ отчёта он ОСТАЁТСЯ, и
# путь печатается: в нём свежие снимки, свежая видимость и собранная заново
# страница — то, чем человек смотрит, ЧЕМ именно разошлось.
# ⚠ Куплено Cafe13KPG#909 (замер frontend-events-9d, 06.11.2026): приговор
# зелёный, все контроли съёмки прошли, а шаг 2 напечатал «отличается от описи
# дерева 21» из 22 — и каталог был уже стёрт, улику стирала прежняя редакция
# (`[ "$rc_total" -eq 0 ] && rm -rf`) ровно тогда, когда она единственная:
# отклонение такого класса приговора не трогает. Отклонение редкое (1 из 5
# прогонов), второй прогон его не повторит.
keep_why=''
mark() { keep_why="${keep_why:+$keep_why; }$1"; }
trap 'ec=$?
if [ "$ec" -eq 0 ] && [ -z "$keep_why" ]; then rm -rf "$W"
else echo "рабочий каталог прогона ОСТАВЛЕН: $W${keep_why:+ — нашлось: $keep_why}"; fi' EXIT
echo "предмет: ДЕРЕВО МЕРДЖА $T"
echo "образ:   $IMAGE"

# ⚠ ПРЕДЕЛ ПАМЯТИ СТАВИТСЯ КОНТЕЙНЕРУ, и только флагом `--memory`: обёртка
# `systemd-run --scope -p MemoryMax=` для него СЛЕПА — контейнер уезжает в
# свою cgroup (`0::/`, `memory.max=max`), и предел хоста до него не доходит
# (замер `designer-55` 31.10.2026). Нужны ОБА флага: без `--memory-swap`
# ядро отдаёт тот же объём ещё и свопом, и предел перестаёт быть пределом.
# Здесь он в ОДНОМ месте и закрывает все четыре вызова; 26.10.2026 прогон
# без предела увёл хост в нагрузку 78 и уронил чужую батарею.
indocker() { # <каталог для /work> <путь скрипта внутри образа> …
    local out=$1; shift
    docker run --rm --memory=2g --memory-swap=2g -v "$T:/app:ro" -v "$out:/work" -w /work \
        -e LANG=ru_RU.UTF-8 -e LC_ALL=ru_RU.UTF-8 \
        --entrypoint node "$IMAGE" "$@"
}

# ── 1. живой режим (приговор) ───────────────────────────────────────────────
step '1. живой режим — tools/live.cjs (приговор)'
# ⚠ ДВЕ ЧАСТИ В ДВУХ КОНТЕЙНЕРАХ РАЗОМ (Cafe13KPG#912): батарея — 96 % времени ворот. Части делит сам
# live.cjs (`ONLY=1/2`, `ONLY=2/2`, метка `part(N)` у каждого случая); то, что одна часть судить не может
# (каждый случай прошёл РОВНО одну часть, реестр join-заглушек по объединению), судит live-svod.cjs. Приговор
# шага — все ТРИ кода. Частей две, не три — решение координатора: 28.10 веер контейнеров прибил чужую задачу.
# ⚠ Памяти на две разом нет (MemAvailable меньше двух пределов с запасом) — части идут ПО ОЧЕРЕДИ: медленнее,
# но приговор тот же. Отказа здесь нет нарочно: занятый хост — не повод не судить дерево.
mkdir -p "$W/live"
part_run() { # <k> — часть k/2 в свой лог
    docker run --rm --memory=2g --memory-swap=2g -v "$T:/app:ro" -v "$W/live:/work" -w /work \
        -e LANG=ru_RU.UTF-8 -e LC_ALL=ru_RU.UTF-8 -e "ONLY=$1/2" -e "ONLY_OUT=/work/part-$1.json" \
        --entrypoint node "$IMAGE" /app/tools/live.cjs > "$W/live/part-$1.log" 2>&1
}
avail_kb=$(awk '/^MemAvailable:/ {print $2}' /proc/meminfo)
[ -n "$avail_kb" ] || die 'не прочитан MemAvailable из /proc/meminfo'
t_live=$(date +%s)
if [ "$avail_kb" -ge $((5 * 1024 * 1024)) ]; then   # 5 ГБ в КБ: два предела по 2 ГБ и запас
    part_run 1 & p1=$!
    part_run 2 & p2=$!
    wait "$p1"; rc1=$?
    wait "$p2"; rc2=$?
    how='разом'
else
    echo "⚠ свободной памяти $((avail_kb / 1024)) МБ меньше 5 ГБ — части по очереди"
    part_run 1; rc1=$?
    part_run 2; rc2=$?
    how='по очереди'
fi
for k in 1 2; do echo "· часть $k/2:"; sed 's/^/    /' "$W/live/part-$k.log"; done
node "$T/tools/live-svod.cjs" "$W/live/part-1.json" "$W/live/part-2.json"; rcv=$?
echo "· live.cjs двумя частями ($how): $(( $(date +%s) - t_live )) с; коды частей $rc1 и $rc2, сводки $rcv"
if [ "$rc1" -eq 1 ] || [ "$rc2" -eq 1 ] || [ "$rcv" -eq 1 ]; then echo "КРАСНОЕ: live.cjs"; rc_total=1
elif [ "$rc1" -ne 0 ] || [ "$rc2" -ne 0 ] || [ "$rcv" -ne 0 ]; then
    echo "ПРОВЕРКА НЕ ВЫПОЛНЕНА: live.cjs (коды $rc1/$rc2/$rcv)"; [ "$rc_total" -eq 0 ] && rc_total=2
fi

# ── 2. снимки (отчёт) ───────────────────────────────────────────────────────
step '2. съёмка — tools/shots.cjs: СЛЕПОК разметки против описи дерева (признак) + снимки (справка)'
mkdir -p "$W/shots"
indocker "$W/shots" /app/tools/shots.cjs; rcs=$?
if [ "$rcs" -ne 0 ]; then
    echo "⚠ съёмка не прошла (rc=$rcs) — сверка снимков НЕ ВЫПОЛНЕНА, а не «снимки те же»"
    reports_dead=$((reports_dead + 1))
else
  # ⚠ Счёт идёт в ПОДОБОЛОЧКЕ: отчётный шаг, умерший по своей причине, не
  # обязан уносить приговор. Возврат `#189` (arhitector-47, 30.10.2026) был
  # ровно про это: ошибка арифметического раскрытия ВЫХОДИТ из неинтерактивного
  # bash, и ворота умирали в шаге 2 с rc=1 — без строки приговора и без шагов
  # 4–7, то есть «не выполнено» читалось как «КРАСНОЕ».
  # ⚠ ИМЕНА, А НЕ ТОЛЬКО ЧИСЛО. Число отвечает «сколько», а спрошено было
  # «какие»: 31.10.2026 на Cafe13KPG#712 правка облика развела 45 снимков из
  # 47, и весь вес отчёта лёг на два, которые НЕ изменились. Свидетельство
  # уезжает на зелёном (`trap` выше, и это решение), поэтому имена печатаются
  # СРАЗУ — те два пришлось добывать второй съёмкой руками, уже после ворот.
  # Решение arhitector-47: лучше напечатать имена, чем описывать, что их нет.
  # С Cafe13KPG#909 находка шага 2 держит рабочий каталог и на зелёном: имена
  # остаются, а снимки лежат рядом (`$W/shots`). Подоболочка наружу пишет только
  # ФАЙЛ-признак — переменная из неё не выходит.
  # ── 2а. СЛЕПОК РАЗМЕТКИ — признак (воспроизводим) ───────────────────────
  # ⚠ ПРИЗНАК ПЕРЕЕХАЛ С ПИКСЕЛЕЙ НА СЛЕПОК 19.11.2026 (Cafe13KPG#934, решение
  # координатора). Байтовая сверка снимков умерла как признак: замер
  # frontend-events-9d 18.11.2026 — два прогона ОДНОГО дерева, один образ, один
  # хост (fr-hbd06), дали 31 расхождение из 32, и это сглаживание текста
  # (0,08 % пикселей по краям глифов), а не содержание. Порог по доле пикселей
  # тоже мёртв: шум доходил до 0,245 %, а НАСТОЯЩАЯ смена номера версии на
  # экране дала 0,237 % — полосы перекрываются, и приговор по доле не построить.
  # Слепок классов воспроизводим тем же замером: razmetka.json без поля `снято`
  # совпал ЦЕЛИКОМ у четырёх прогонов (двух последовательных, двух одновременных).
  # ⚠ Предел слепка назван в самом приборе: он не видит ТЕКСТ (ту же смену
  # номера версии он пропускает) и не видит облик. Слова судит live.cjs, облик —
  # check-sostav.py и глаз по снимку, поэтому снимки ниже оставлены справкой.
  # ⚠ Зов по пути СУДИМОГО дерева, а не из `$W/tree`: копию дерева делает шаг 4,
  # здесь её ещё нет (прежняя редакция этой строки падала бы «нет каталога»).
  # Прибор берёт оба пути доводами и ничего не ищет рядом с собой.
  python3 -I "$T/tools/sverka-razmetki.py" \
      "$W/shots/razmetka.json" "$T/screens/razmetka.json"; rcr=$?
  if [ "$rcr" -eq 1 ]; then
      mark "шаг 2: СЛЕПОК разметки разошёлся с описью дерева — опись пересобрать (свежий съём в $W/shots)"
  elif [ "$rcr" -ne 0 ]; then
      echo "⚠ сверка слепка НЕ ВЫПОЛНЕНА (rc=$rcr) — это не «слепок тот же»"
      reports_dead=$((reports_dead + 1))
  fi

  # ── 2б. СНИМКИ — СПРАВКА, и приговор тут НЕ СТОИТ (Cafe13KPG#934) ───────
  # ⚠ УСЛОВНЫЙ ПРИГОВОР ОТСЮДА СНЯТ 19.11.2026, и причина названа замером
  # архитектора по диффу: условие «выпуск шрифтов тот же» отсекает ШУМ ШРИФТОВ,
  # но НЕ отсекает законную правку экрана. Клиентский PR экран и ДОЛЖЕН менять,
  # а опись пересобирается ПОСЛЕ мерджа — значит ворота краснели бы на каждой
  # фиче, законно по коду и бессмысленно по делу. Это та же причина, по которой
  # приговором не сделан и слепок (решение координатора утром 19.11).
  # ⚠ Условный приговор при этом НЕ ОТМЕНЁН — он переехал туда, где его предмет:
  # в прибор описи при ПЕРЕСБОРКЕ (`tools/sverka-razmetki.py --снимки`). Там
  # «снимки разошлись при том же выпуске шрифтов» значит «опись отстала от
  # дерева», и это приговор о моём предмете, а не о чужой фиче.
  # Признак разделения, падающий: прогон ворот по дереву с изменённым экраном
  # обязан дать ЗЕЛЁНОЕ со справкой, а прибор описи на том же дереве без
  # пересборки — КРАСНОЕ.
  # ⚠ ПРИЧИНА НЕДЕТЕРМИНИРОВАННОСТИ НАЙДЕНА 19.11.2026 И ИЗМЕРИМА: сеть отдаёт
  # ДВА выпуска `Golos Text`, и при смене выпуска сдвигаются почти все снимки
  # (сглаживание глифов, 0,08 % пикселей). Замер: прогон описи и прогон ворот
  # дали разные слепки у ТРЁХ ресурсов из пяти — таблица стилей и оба файла
  # `Golos Text`; оба `Prata` те же. Поэтому пиксельное расхождение —
  # ПРИГОВОР ТОГДА И ТОЛЬКО ТОГДА, когда выпуск шрифтов ТОТ ЖЕ; разошёлся
  # выпуск — расхождение остаётся справкой. Решение координатора 19.11.2026.
  # ⚠ Это СИЛЬНЕЕ локальной копии шрифтов, и альтернатива отклонена с доводом:
  # пикселю возвращается то, чего слепок не умеет (съехавшая вёрстка, пропавший
  # блок, смена слов — её слепок не видит по построению), и при этом опись не
  # начинает показывать шрифт из репозитория вместо того, что видит человек;
  # новой механики (перехвата запросов) не заводится вовсе.
  python3 -I "$T/tools/sverka-razmetki.py" --шрифты \
      "$W/shots/razmetka.json" "$T/screens/razmetka.json"; rcf=$?
  # ⚠ Выпуск шрифтов печатается ВСЕГДА и остаётся полезным: он отвечает, о чём
  # расхождение ниже — о сети или о клиенте, — но приговора здесь не выносит.
  case "$rcf" in
    0) echo '· снимки ниже — СПРАВКА: выпуск шрифтов тот же, значит расхождение о КЛИЕНТЕ (опись пересобирается после мерджа)' ;;
    1) echo '· снимки ниже — СПРАВКА: выпуск шрифтов разошёлся, расхождение о СЕТИ (Cafe13KPG#934)' ;;
    *) echo '· снимки ниже — СПРАВКА: о чём расхождение, спросить НЕЧЕМ (строка выше)' ;;
  esac
  ( differ=0; absent=0
    for p in "$W/shots"/*.png; do
        nm=$(basename "$p")
        if [ -f "$T/screens/$nm" ]; then
            cmp -s "$p" "$T/screens/$nm" || { differ=$((differ + 1)); echo "  ≠ $nm"; }
        else
            absent=$((absent + 1)); echo "  + $nm"
        fi
    done
    total_png=$(ls "$W/shots"/*.png 2>/dev/null | wc -l)
    echo "снимков снято $total_png · отличается от описи дерева $differ · нет в описи $absent"
    # ⚠ Файл-признак несёт ИМЕНА в сводку прогона; приговорность решается ниже,
    # по коду сверки шрифтов, а не здесь: подоболочка о нём не знает.
    { [ "$differ" -gt 0 ] || [ "$absent" -gt 0 ]; } && echo "$differ/$absent" > "$W/shots-found"
    # ⚠ ПОСЛЕДНЯЯ команда подоболочки задаёт её код возврата, поэтому цепочка
    # `[ … ] && [ … ] && echo` здесь НЕ годится: при «нет в описи 1» второе
    # условие ложно, подоболочка выходит с 1, и `||` ниже печатает ложное
    # «отчёт НЕ ВЫПОЛНЕН» о живом отчёте. Поймано десятым входом (дерево без
    # одного снимка): строка счёта и ложная тревога напечатались РЯДОМ.
    if [ "$differ" -eq 0 ] && [ "$absent" -eq 0 ]; then
        echo '(опись снимков под этот клиент уже собрана)'
    fi
  ) || { echo '⚠ отчёт о снимках НЕ ВЫПОЛНЕН (сам счёт умер) — и мердж он не держит'
         reports_dead=$((reports_dead + 1)); }
  if [ -f "$W/shots-found" ]; then
      found=$(cat "$W/shots-found")
      echo "· справка: снимки разошлись с описью (≠/+ $found), свежие в $W/shots — приговора тут нет; опись пересобирает frontend-events-9d своим прогоном"
  fi
  true
fi

