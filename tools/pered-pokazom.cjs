const { spawnSync } = require('child_process');
const fs = require('fs');
const path = require('path');

/* ВОРОТА ПЕРЕД ПОКАЗОМ — один запускатель на путь «код → коммит → владелец смотрит» (Cafe13KPG#605,
   #607). Ворот ТРИ, и каждое закрывает долг, который НЕ догоняется после показа:
     1. дым — приложение загружается и рисует главный экран (`tools/smoke.cjs`);
     2. имена и id живых людей — публичный git (`tools/ids-clean.cjs`). Не снимается НИКОГДА: «база не
        живая» сказано о ДАННЫХ стадии пред-МВП, а утечка — об истории публичного репозитория;
     3. номер версии — оба `?v=` в `index.html` равны номеру `app.js`, иначе владелец смотрит старый файл
        из кэша и правит нас по тому, чего мы не делали. И номер ПОДНЯТ, если клиент изменён: в `app.js`
        (кроме строки номера) или `styles.css` есть видимая правка против `origin/main` — номер обязан
        быть больше ствольного. Равенство трёх мест на это не отвечает: на v105 с изменённым `app.js` оно зелёное
        (поймано на себе 29.10.2026, решение координатора). Обратное — номер поднят БЕЗ правки
        клиента — тоже красное: `?v=` без правки врёт об изменении (правило архитектора 22.10).
        Правка одних комментариев и пустых строк номер НЕ требует — признак по строкам диффа, не разбор
        JS. Ствол — СВЕЖИЙ (`git fetch` при каждом запуске); не прочитан — «не выполнено».
   И отдельной строкой — ПРЕДЕЛ отставания описи (`tools/check-opis.py`, второй вызывающий). Это не
   четвёртые ворота, и в код выхода он НЕ входит (решение координатора #607): ворота отвечают «можно ли
   показывать ЭТУ правку», предел — «не накопили ли мы долга». Склейка делала бы первый ответ
   непрочитываемым, а пока прибора в стволе нет — «не выполнено» на каждом здоровом прогоне, и такую
   проверку выключают.

   Код выхода — по ТРЁМ воротам, и исходы НЕ склеиваются:
     0 — ворота зелёные;
     1 — красное хоть у одних — с их именем и текстом;
     2 — хоть одно «НЕ ВЫПОЛНЕНО» при отсутствии красного. «Не выполнено» НЕ перебивается зелёным
         остальных: оно значит «мерить нечем», а не «чисто». Красное важнее потому, что это найденный
         дефект; но строка «не выполнено» печатается и тогда — приговор по ТЕКСТУ.
   Предел печатает СВОЙ код строкой «ПРЕДЕЛ: N». 2 (прибора нет) публикацию не держит. 1 — держит, но
   решает это правило #605 («следующая версия не публикуется, пока долг не приедет»), а не код выхода:
   строка печатает долг и предел — первую строку прибора, «Pages vN · опись vM · долг K из 3».

   Код 3 — ворота зелёные, но предел ДЕРЖИТ публикацию (решение координатора #607, поправка к
   «держит правило по тексту»: вызывающий, читающий код, иначе предела не видит). Красное и «не
   выполнено» у ворот важнее 3. Чем держит — сказано текстом: «долг K из 3» или «опись с ДРУГОГО
   клиента» — это разные предметы, и строка у каждого своя (строки прибора).

   Запуск — НА ХОСТЕ, из корня дерева:  node tools/pered-pokazom.cjs
   Предел читает git, а в контейнере git слеп: у рабочего дерева (worktree) `.git` — файл со ссылкой
   за пределы тома, у полного клона — «dubious ownership» (замер arhitector-47 и мой, 29.10.2026).
   Поэтому в контейнер уходит только дым — ему нужен браузер, — и уходит сам: на хосте без
   playwright запускатель зовёт `docker run` образа ровно на `tools/smoke.cjs`. Запуск ВНУТРИ образа
   по-прежнему работает, но предел там даст «НЕ ВЫПОЛНЕНО» на каждом прогоне. */

const ROOT = process.env.APP || path.resolve(__dirname, '..');
const IMAGE = 'agenthost/playwright:1.59.1';
const rows = [];
const say = (kind, name, rc, text) => rows.push({ kind, name, rc, text });

function run(cmd, args) {
  const r = spawnSync(cmd, args, { cwd: ROOT, env: Object.assign({}, process.env, { APP: ROOT }), encoding: 'utf8', timeout: 60000 });
  const out = ((r.stdout || '') + (r.stderr || '')).trim();
  if (r.error) return { rc: 2, out: 'не запустился: ' + r.error.message };
  return { rc: r.status === null ? 2 : r.status, out };
}
const first = s => String(s || '').split('\n').filter(Boolean).slice(0, 4).join(' | ');

// 1. дым
{
  let here = true; try { require.resolve('playwright'); } catch (e) { here = false; }
  const r = here ? run('node', [ROOT + '/tools/smoke.cjs'])
    : run('docker', ['run', '--rm', '-v', ROOT + ':/app:ro', '--entrypoint', 'node', IMAGE, '/app/tools/smoke.cjs']);
  say('ворота', 'дым', [0, 1, 2].includes(r.rc) ? r.rc : 2, first(r.out));
}
// 2. имена и id — без флага «необязательно»: этих ворот не снимает ничто
try {
  const found = require(ROOT + '/tools/ids-clean.cjs').idsClean(ROOT);
  if (!Array.isArray(found)) say('ворота', 'имена и id', 2, 'страж вернул не список — разбор не тот');
  else say('ворота', 'имена и id', found.length ? 1 : 0, found.length ? found.slice(0, 3).join(' | ') : 'чисто');
} catch (e) { say('ворота', 'имена и id', 2, 'страж не запустился: ' + String(e.message).split('\n')[0]); }
// 3. номер версии: номер БЕРЁТСЯ из app.js и сверяется с обоими `?v=` в index.html
try {
  const app = fs.readFileSync(ROOT + '/app.js', 'utf8'), idx = fs.readFileSync(ROOT + '/index.html', 'utf8');
  const m = app.match(/var VERSION = 'v(\d+) · /);
  if (!m) say('ворота', 'номер версии', 2, 'в app.js нет `var VERSION = \'vN · …\'` — номер не прочитан');
  else {
    const n = m[1];
    const css = (idx.match(/styles\.css\?v=(\d+)"/) || [])[1], js = (idx.match(/app\.js\?v=(\d+)"/) || [])[1];
    if (!css || !js) say('ворота', 'номер версии', 2, 'в index.html не найдено `styles.css?v=` или `app.js?v=` — признак не тот');
    else if (css !== n || js !== n) say('ворота', 'номер версии', 1, `app.js v${n}, а в index.html styles.css?v=${css}, app.js?v=${js} — владелец увидит старый файл из кэша`);
    else {
      // ствол — СВЕЖИЙ: `git fetch` сейчас, а не ref из клона. Ворота стоят перед показом, и сравнение с
      // устаревшим стволом — ложное зелёное: номер ствола в клоне меньше настоящего (решение координатора)
      const sh = args => spawnSync('git', args, { cwd: ROOT, encoding: 'utf8', timeout: 30000, maxBuffer: 64 * 1024 * 1024 });
      const why = r => String(r.error ? r.error.message : r.stderr || '').trim().split('\n')[0];
      const f = sh(['fetch', '-q', 'origin', 'main']);
      const tApp = f.status === 0 ? sh(['show', 'origin/main:app.js']) : f;
      const tm = tApp.status === 0 ? tApp.stdout.match(/var VERSION = 'v(\d+) · /) : null;
      if (tApp.status !== 0) say('ворота', 'номер версии', 2,
        'ствол origin/main не прочитан (' + why(tApp) + ') — поднят ли номер, сравнить не с чем');
      else if (!tm) say('ворота', 'номер версии', 2, 'в app.js ствола нет `var VERSION = \'vN · …\'` — номер ствола не прочитан');
      else {
        // изменённые строки клиента — от ТОЧКИ ОТВЕТВЛЕНИЯ (merge-base), а не от головы ствола: ветка, отставшая
        // от ушедшего вперёд ствола, иначе читала бы ЧУЖИЕ правки ствола своими и краснела бы, ничего в клиенте
        // не тронув (поймано на #153 после мерджа v106). Рабочее дерево — вместе с незакоммиченным. Строка
        // номера — не правка, иначе сам подъём читался бы правкой и «поднят без правки» не наступало бы никогда
        const mb = sh(['merge-base', 'origin/main', 'HEAD']), base = mb.status === 0 ? mb.stdout.trim() : '';
        const bApp = base ? sh(['show', base + ':app.js']) : mb;
        const bm = bApp.status === 0 ? bApp.stdout.match(/var VERSION = 'v(\d+) · /) : null;
        const d = bm ? sh(['diff', '-U0', '--no-color', base, '--', 'app.js', 'styles.css']) : bApp;
        const lines = d.status === 0 ? d.stdout.split('\n').filter(x => /^[+-]/.test(x) && !/^(\+\+\+|---) /.test(x))
          .map(x => x.slice(1)).filter(x => !/var VERSION = 'v\d+ · /.test(x)) : null;
        /* Правка, НЕ видимая человеку, — когда КАЖДАЯ изменённая строка пустая или комментарий по началу
           строки (решение координатора 29.10.2026; правило 22.10: комментарий номер не поднимает, письмо
           владельцу о «новой версии» без перемены — ложь). Это не разбор JS, а признак по строке:
           код с комментарием в одной строке начинается НЕ с `//` и считается кодом. Строка на `*` — только
           без `{ } ; ( ) =`: иначе CSS `* { … }` (селектор «всё») прошёл бы комментарием — то есть ТИХИМ
           пропуском. Цена ужесточения — комментарий со скобками требует номер: ошибка в сторону подъёма. */
        const prose = x => /^\s*$/.test(x) || /^\s*(\/\/|\/\*)/.test(x) || /^\s*\*(\s|\/|$)[^{};()=]*$/.test(x);
        const t = tm[1], b = bm && bm[1], seen = lines && lines.some(x => !prose(x));
        if (!lines) say('ворота', 'номер версии', 2, 'дифф от точки ответвления не снят (' + why(d) + ') — поднят ли номер, сравнить не с чем');
        else if (seen && Number(n) <= Number(t)) say('ворота', 'номер версии', 1,
          `клиент изменён против ствола (v${t}), а номер v${n} не поднят — владелец увидит старый файл из кэша`);
        else if (!seen && n !== b) say('ворота', 'номер версии', 1,
          `номер v${n} при v${b} в точке ответвления, а видимой правки в app.js и styles.css нет — номер поднят без правки клиента`);
        else if (!seen && lines.length) say('ворота', 'номер версии', 0,
          `v${n} не тронут: изменены только комментарии и пустые строки (${lines.length}) — правка не видна человеку, номер не требуется`);
        else say('ворота', 'номер версии', 0, `v${n} во всех трёх местах` + (seen ? `, поднят над стволом v${t}`
          : b === t ? ', как у ствола' : `: клиент не тронут, ствол ушёл на v${t} — при слиянии номер возьмётся стволовой`));
      }
    }
  }
} catch (e) { say('ворота', 'номер версии', 2, 'файлы не прочитаны: ' + String(e.message).split('\n')[0]); }
// предел описи — второй вызывающий. Прибора нет — «не выполнено», а НЕ тихий пропуск
if (!fs.existsSync(ROOT + '/tools/check-opis.py')) say('предел', 'отставание описи', 2, 'прибора tools/check-opis.py в дереве нет — предел не измерен');
else {
  const r = run('python3', ['-I', ROOT + '/tools/check-opis.py']);
  say('предел', 'отставание описи', [0, 1, 2].includes(r.rc) ? r.rc : 2, first(r.out));
}

const WORD = { 0: 'зелёное', 1: 'КРАСНОЕ', 2: 'НЕ ВЫПОЛНЕНО' };
for (const x of rows) console.log(`${x.kind === 'ворота' ? 'ВОРОТА' : 'ПРЕДЕЛ'} ${x.name}: ${WORD[x.rc]} — ${x.text}`);
const gates = rows.filter(x => x.kind === 'ворота'), lim = rows.find(x => x.kind === 'предел');
const gc = gates.some(x => x.rc === 1) ? 1 : gates.some(x => x.rc === 2) ? 2 : 0;
const rc = gc === 0 && lim.rc === 1 ? 3 : gc;
console.log(`ВОРОТА: ${gc} — ` + (gc === 0 ? 'показывать можно'
  : gc === 1 ? 'НЕ ПОКАЗЫВАТЬ: есть красное'
  : 'НЕ ПОКАЗЫВАТЬ: красного нет, но не всё измерено — «не выполнено» не равно «зелёное»'));
console.log(`ПРЕДЕЛ: ${lim.rc} — ` + (lim.rc === 0 ? 'долг в пределе'
  : lim.rc === 1 ? 'ПУБЛИКАЦИЮ ДЕРЖАТЬ (правило #605' + (rc === 3 ? ', код 3' : '') + '): ' + lim.text
  : 'НЕ ВЫПОЛНЕНО — публикацию не держит, долг не измерен'));
console.log(`КОД: ${rc}` + (rc === 3 ? ' — ворота зелёные, публикацию держит предел' : ''));
process.exit(rc);
