import io
import json
import os
import re
import sys

# ⚠ ГЕОМЕТРИЯ — ТО, ЧТО НАПИСАНО, А НЕ ТО, ЧТО ВИДНО. Реестр читает
#    `styles.css`; отрисовка даёт другое число, и расхождение у нас уже
#    куплено: без Golos Text подпись расходится на 3–6 px, то есть кегль из
#    файла и ширина на экране — разные утверждения. Для «какие стили где»
#    написанного довольно; для «влезает ли» нужен прибор геометрии кадров.
ГЕОМЕТРИЯ = ('padding', 'border-radius', 'font-size', 'font-weight',
             'gap', 'min-height', 'border')

СТИЛИ = 'styles.css'
РОЛИ = '_docs/oblik-roli.json'

# Оси объявлены, а не угаданы: это суждение, и оно читается как суждение.
ВАРИАНТЫ = ('quiet', 'ghost', 'dense', 'mini', 'big', 'small', 'strong')
СОСТОЯНИЯ = ('on', 'now', 'paid', 'done', 'warm', 'deny', 'busy', 'soon',
             'wait', 'empty', 'none', 'cancelled', 'fixed')


class Отказ(Exception):
    """Проверка не выполнена."""


def правила(текст):
    """Селекторы и тела правил; `@`-блоки и `:root` — не элементы."""
    без = re.sub(r'/\*.*?\*/', '', текст, flags=re.S)
    вышло = []
    for сел, тело in re.findall(r'([^{}]+)\{([^}]*)\}', без):
        for часть in сел.split(','):
            часть = часть.strip()
            if часть and not часть.startswith('@') and not часть.startswith(':root'):
                вышло.append((часть, тело))
    return вышло


СТРАНИЦА_СТИЛИ = re.compile(r'\bbody\.([\w-]+)')
СТРАНИЦА_КЛИЕНТ = re.compile(
    r"document\.body\.classList\.(?:add|remove|toggle)\s*\(\s*['\"]([\w-]+)")


def состояния_страницы(стили, клиент=None):
    """Классы на `<body>`: признак, а не перечень.

    Половина в стилях (`body.X`) обязательна; вторая (`document.body.classList`
    в клиенте) подтверждает, что он переключается живьём. Клиента не дали —
    вид назначается по стилям, и это сказано вслух."""
    в_стилях = set(СТРАНИЦА_СТИЛИ.findall(стили))
    если = dict.fromkeys(sorted(в_стилях), 'по стилям')
    if клиент is not None:
        живьём = set(СТРАНИЦА_КЛИЕНТ.findall(клиент))
        for и in sorted(в_стилях):
            если[и] = 'подтверждён клиентом' if и in живьём else 'в клиенте не найден'
    return если


# ⚠ СУЖДЕНИЯ, А НЕ ВЫВОДЫ. Шесть классов встречаются И составными, И
#    потомками — за них решает ПОРЯДОК проверок, а порядок есть суждение.
#    Четыре не дают ни одного признака. У каждого здесь стоит причина, и
#    в отчёте они помечены словом «суждение» (условие координатора).
СУЖДЕНИЯ = {
    # и составной, и потомок — решено по тому, что класс ЗНАЧИТ
    'busy': ('состояние', 'занято — свойство предмета, не вид'),
    'img': ('часть', 'картинка внутри своего места'),
    'no': ('состояние', 'отрицательный исход'),
    'on': ('состояние', 'выбрано'),
    'photo': ('часть', 'фото внутри аватара'),
    'wait': ('состояние', 'ждём ответа'),
    # ни одного признака
    'box': ('элемент', 'ящик с пунктиром, живёт сам'),
    'fold': ('вариант', 'свёрнутый вид той же плашки'),
    'has-main': ('состояние страницы', 'на body, есть главная кнопка'),
    'open': ('состояние', 'раскрыто'),
}


def разобрать(текст):
    """Класс → чем рисуется и какого он ВИДА.

    ⚠ Вид берётся из ФОРМЫ СЕЛЕКТОРА, а не называется руками: автор стилей
    принял решение «часть или элемент» тогда, когда писал селектор.
    Контекстный селектор и есть запись о том, что вещь не живёт сама.
      раскладка — одиночное правило И цветом не рисует;
      элемент   — одиночное правило И рисует токенами;
      вариант/состояние — нет одиночного, встречается СОСТАВНЫМ (`.btn.quiet`);
      часть     — нет одиночного, встречается ПОТОМКОМ (`.card .avatar`).
    На живом `styles.css` так раскладываются 104 класса из 114; остальные
    десять — в `СУЖДЕНИЯ` выше, и они помечены как суждения."""
    собрано = {}
    for сел, тело in правила(текст):
        имена = re.findall(r'\.([\w-]+)', сел)
        одиночный = len(имена) == 1 and not re.search(r'[\s>+~\[:]', сел)
        составные = set(m.group(1) for m in re.finditer(r'\.[\w-]+\.([\w-]+)', сел))
        потомки = set()
        if re.search(r'[\s>+~]', сел):
            for кусок in re.split(r'[\s>+~]+', сел)[1:]:
                потомки.update(re.findall(r'\.([\w-]+)', кусок))
        токены = sorted(set(re.findall(r'var\((--[\w-]+)', тело)))
        геом = {}
        for свойство in ГЕОМЕТРИЯ:
            м = re.search(r'(?:^|;)\s*%s\s*:\s*([^;}]+)' % свойство, тело)
            if м:
                геом[свойство] = ' '.join(м.group(1).split())
        for имя in имена:
            это = собрано.setdefault(имя, {'селекторы': [], 'токены': set(),
                                           'одиночное': False, 'геометрия': {},
                                           'составной': False, 'потомок': False})
            это['селекторы'].append(сел)
            это['токены'].update(токены)
            # ⚠ Геометрия берётся ТОЛЬКО из одиночного правила: в контекстных
            #    селекторах лежит доводка под место, и смешав их, реестр
            #    назвал бы отступом то, что стоит лишь внутри одной карточки.
            if одиночный:
                это['геометрия'].update(геом)
            если = это
            if одиночный:
                если['одиночное'] = True
            if имя in составные:
                если['составной'] = True
            if имя in потомки:
                если['потомок'] = True
    for имя, это in собрано.items():
        это['токены'] = sorted(это['токены'])
        это['суждение'] = ''
        if имя in СУЖДЕНИЯ:
            это['вид'], это['суждение'] = СУЖДЕНИЯ[имя]
        elif это['одиночное']:
            это['вид'] = 'элемент' if это['токены'] else 'раскладка'
        elif это['составной']:
            это['вид'] = ('вариант' if имя in ВАРИАНТЫ else
                          'состояние' if имя in СОСТОЯНИЯ else 'вариант/состояние')
        elif это['потомок']:
            это['вид'] = 'часть'
        else:
            это['вид'] = 'не названо'
    return собрано


def прочитать_роли(путь):
    if not os.path.exists(путь):
        return {}
    try:
        return json.load(io.open(путь, encoding='utf-8'))
    except ValueError as e:
        raise Отказ('роли не разобрались (%s): %s' % (путь, e))


def судить(стили=СТИЛИ, роли_путь=РОЛИ, печатать=False, клиент=None):
    try:
        текст = io.open(стили, encoding='utf-8').read()
    except OSError as e:
        raise Отказ('не прочитать %s: %s' % (стили, e))
    текст_клиента = None
    if клиент:
        try:
            текст_клиента = io.open(клиент, encoding='utf-8').read()
        except OSError as e:
            raise Отказ('не прочитать клиента %s: %s' % (клиент, e))
    страницы = состояния_страницы(текст, текст_клиента)
    собрано = разобрать(текст)
    for и in страницы:
        if и in собрано:
            собрано[и]['вид'] = 'состояние страницы'
            собрано[и]['откуда'] = страницы[и]
    if not собрано:
        raise Отказ('в %s ни одного класса — признак сломан, а не классов нет'
                    % стили)
    роли = прочитать_роли(роли_путь)

    элементы = {и: з for и, з in собрано.items() if з['вид'] == 'элемент'}
    варианты = {и: з for и, з in собрано.items() if з['вид'] == 'вариант'}
    состояния = {и: з for и, з in собрано.items() if з['вид'] == 'состояние'}
    безымянные = {и: з for и, з in собрано.items() if з['вид'] == 'не названо'}
    стр = {и: з for и, з in собрано.items() if з['вид'] == 'состояние страницы'}

    # ⚠ Покрытие печатается ВСЕГДА: без него «ролей не хватает ноль» значит
    #    только то, что спросили не всех.
    # ⚠ Покрытие печатается ЦЕЛИКОМ: сумма по видам обязана сойтись с числом
    #    классов, иначе «без оси 0» значит только то, что спросили не всех.
    по_видам = {}
    for з in собрано.values():
        по_видам[з['вид']] = по_видам.get(з['вид'], 0) + 1
    print('классов %d: %s' % (len(собрано), ' · '.join(
        '%s %d' % (в, n) for в, n in sorted(по_видам.items(), key=lambda x: -x[1]))))
    сумма = sum(по_видам.values())
    if сумма != len(собрано):
        raise Отказ('сумма по видам %d не равна числу классов %d — '
                    'вид потерян' % (сумма, len(собрано)))
    суждений = [и for и, з in собрано.items() if з.get('суждение')]
    if суждений:
        print('  суждений (не выводов): %d — %s' % (
            len(суждений), ', '.join('%s: %s' % (и, собрано[и]['суждение'])
                                     for и in sorted(суждений))))
    if стр:
        print('  состояния страницы (признак: body.X в стилях + '
              'document.body.classList в клиенте): %s'
              % ', '.join('%s — %s' % (и, собрано[и].get('откуда', '?'))
                          for и in sorted(стр)))
    с_токенами = [и for и, з in собрано.items() if з['токены']]
    с_геом = [и for и, з in собрано.items() if з['геометрия']]
    print('рисуют токенами: %d из %d · геометрия снята у %d'
          % (len(с_токенами), len(собрано), len(с_геом)))

    if печатать:
        for имя in sorted(собрано):
            з = собрано[имя]
            г = '; '.join('%s: %s' % (к, v) for к, v in sorted(з['геометрия'].items()))
            print('  %-20s %-10s %-30s %s'
                  % (имя, з['вид'], роли.get(имя, '—'),
                     ', '.join(з['токены'])[:50] or 'цветом не рисуется'))
            if г:
                print('  %-20s %-10s %s' % ('', '', г[:150]))

    # Гниение списка в обе стороны, как у долга палитры: запись о месте,
    # которого нет, — красное.
    лишние = sorted(и for и in роли if и not in собрано)
    if лишние:
        print('КРАСНОЕ: в ролях %d запис(ь/и) о классе, которого нет в %s: %s'
              % (len(лишние), стили, ', '.join(лишние)))
        return 1

    # ⚠ Список гниёт в ОБЕ стороны, и вторая сторона тоньше первой: роль,
    #    названная КЛАССУ, у которого её быть не может (раскладка, часть,
    #    состояние), выглядит полезной записью и обещает смысл там, где его
    #    нет. Поймано на себе: я назвал роли `group`, `num`, `sum`, `tap` —
    #    все четыре раскладка.
    не_своим = sorted((и, собрано[и]['вид']) for и in роли
                      if и in собрано and собрано[и]['вид'] != 'элемент')
    if не_своим:
        print('КРАСНОЕ: роль названа %d класс(ам), у которых её быть не '
              'может: %s' % (len(не_своим),
                             ', '.join('%s (%s)' % (и, в) for и, в in не_своим)))
        return 1

    без_роли = sorted(и for и in элементы if и not in роли)
    без_оси = sorted(безымянные)
    if без_роли or без_оси:
        if без_роли:
            print('НЕ ВЫПОЛНЕНО: элементов без названной роли %d из %d: %s'
                  % (len(без_роли), len(элементы), ', '.join(без_роли[:12])
                     + (' …' if len(без_роли) > 12 else '')))
        if без_оси:
            print('НЕ ВЫПОЛНЕНО: классов без оси %d: %s'
                  % (len(без_оси), ', '.join(без_оси[:12])
                     + (' …' if len(без_оси) > 12 else '')))
        print('  (роль и ось в CSS не записаны — их называют руками в %s;'
              ' «не выполнено» читать как долг, а не как зелёное)' % роли_путь)
        return 2

    print('зелёное: у всех %d элементов названа роль, у всех классов — ось'
          % len(элементы))
    return 0


