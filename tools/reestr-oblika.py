#!/usr/bin/env python3
"""Реестр элементов облика — ИЗВЛЕКАЕТСЯ из styles.css, а не пишется рядом.

    python3 -I tools/reestr-oblika.py [--стили styles.css] [--роли <файл>]
                                      [--клиент app.js] [--печатать]
                                      [--самопроверка]

Коды: 0 — реестр собран и все элементы названы; 1 — КРАСНОЕ (запись о роли
без места в стилях); 2 — проверка НЕ ВЫПОЛНЕНА (элемент без названной роли,
стилей нет, классов ноль). Двойку читать как «не выполнено», а не как зелёное.

⚠ ПОЧЕМУ ИЗВЛЕКАЕТСЯ, А НЕ ПИШЕТСЯ (условие координатора, `Cafe13KPG#758`):
прозой написанный реестр разойдётся со `styles.css` на первой правке, и мы
получим ТРЕТИЙ источник облика вместо одного. Поэтому состав, селекторы и
токены перечитываются из файла стилей КАЖДЫЙ ПРОГОН, а руками называется
чего в CSS нет вовсе, — РОЛЬ.

⚠ ДВЕ ОСИ, А НЕ ОДНА (моя поправка к постановке, принята 02.11.2026):
  вариант   — тихое, призрачное, плотное, мини: тот же элемент, иной вид;
  состояние — недоступно, выбрано, опасно, занято: иной СМЫСЛ.
Сложив их в одну ось, реестр соврал бы о логике с первого дня: тихая кнопка
НАЖИМАЕТСЯ, погашенная — нет (`.btn.quiet` против `.btn[disabled]`).

⚠ ОСЬ СОСТОЯНИЙ СОБИРАЕТСЯ ИЗ ДВУХ ФАЙЛОВ. `aria-disabled` в `styles.css` не
встречается ни разу, а в `app.js` — семь раз (замер 02.11.2026). Значит
`styles.css` — источник ОБЛИКА (чем рисуется), `app.js` — источник
ДОСТУПНОСТИ (чем объявлено «нельзя»). Пересечение пустое, второго источника
облика это не создаёт.

⚠ ШЕСТОЙ ВИД — СОСТОЯНИЕ СТРАНИЦЫ, и он определяется ПРИЗНАКОМ, а не
перечнем: селектор `body.X` в стилях И `document.body.classList` с тем же
именем в `app.js`. Третий такой класс попадёт в вид сам, без правки списка.
Сегодня их два — `has-main` («есть главная кнопка», прячет `.dup-main`) и
`no-tabs` («вкладок нет», меняет нижний отступ), — но «два» это наблюдение,
а не определение. Найден побочным ответом признака «переключается ли класс
живьём»: для деления варианта и состояния тот признак ПУСТ (из 27
модификаторов живьём не трогается ни один), а вот на `<body>` сработал.

⚠ ЧЕГО ЭТОТ ПРИБОР НЕ ДЕЛАЕТ, и это границы, а не недоделки:
  — «класс в `app.js` без правила» судит `Cafe13KPG#673`, не он;
  — «токен без пары контраста» судит батарея палитры `frontend-11`;
  — палитра тонов плиток (`TONE` в `app.js`) — ОТДЕЛЬНАЯ семья цветов, в
    `:root` её нет, и сюда она не входит (замер и числа — `#758`, комментарий).
"""
import io
import json
import os
import re
import sys

СТИЛИ = 'styles.css'
РОЛИ = '_docs/oblik-roli.json'

# Оси объявлены, а не угаданы: это суждение, и оно читается как суждение.
ВАРИАНТЫ = ('quiet', 'ghost', 'dense', 'mini', 'big', 'small', 'strong')
СОСТОЯНИЯ = ('on', 'now', 'paid', 'done', 'warm', 'deny', 'busy', 'soon',
             'wait', 'empty', 'none', 'cancelled', 'fixed')


class Отказ(Exception):
    """Проверка не выполнена."""


def правила(текст):
    """Селекторы и тела правил; `@`-блоки и `:root` — не элементы."""
    без = re.sub(r'/\*.*?\*/', '', текст, flags=re.S)
    вышло = []
    for сел, тело in re.findall(r'([^{}]+)\{([^}]*)\}', без):
        for часть in сел.split(','):
            часть = часть.strip()
            if часть and not часть.startswith('@') and not часть.startswith(':root'):
                вышло.append((часть, тело))
    return вышло


СТРАНИЦА_СТИЛИ = re.compile(r'\bbody\.([\w-]+)')
СТРАНИЦА_КЛИЕНТ = re.compile(
    r"document\.body\.classList\.(?:add|remove|toggle)\s*\(\s*['\"]([\w-]+)")


def состояния_страницы(стили, клиент=None):
    """Классы на `<body>`: признак, а не перечень.

    Половина в стилях (`body.X`) обязательна; вторая (`document.body.classList`
    в клиенте) подтверждает, что он переключается живьём. Клиента не дали —
    вид назначается по стилям, и это сказано вслух."""
    в_стилях = set(СТРАНИЦА_СТИЛИ.findall(стили))
    если = dict.fromkeys(sorted(в_стилях), 'по стилям')
    if клиент is not None:
        живьём = set(СТРАНИЦА_КЛИЕНТ.findall(клиент))
        for и in sorted(в_стилях):
            если[и] = 'подтверждён клиентом' if и in живьём else 'в клиенте не найден'
    return если


def разобрать(текст):
    """Класс → чем рисуется, где встречается, элемент он или модификатор."""
    собрано = {}
    for сел, тело in правила(текст):
        имена = re.findall(r'\.([\w-]+)', сел)
        одиночный = len(имена) == 1 and not re.search(r'\[|:|\s|>', сел)
        токены = sorted(set(re.findall(r'var\((--[\w-]+)', тело)))
        for имя in имена:
            это = собрано.setdefault(имя, {'селекторы': [], 'токены': set(),
                                           'одиночное': False})
            это['селекторы'].append(сел)
            это['токены'].update(токены)
            if одиночный:
                это['одиночное'] = True
    for имя, это in собрано.items():
        это['токены'] = sorted(это['токены'])
        это['вид'] = ('элемент' if это['одиночное'] else
                      'вариант' if имя in ВАРИАНТЫ else
                      'состояние' if имя in СОСТОЯНИЯ else 'не названо')
    return собрано


def прочитать_роли(путь):
    if not os.path.exists(путь):
        return {}
    try:
        return json.load(io.open(путь, encoding='utf-8'))
    except ValueError as e:
        raise Отказ('роли не разобрались (%s): %s' % (путь, e))


def судить(стили=СТИЛИ, роли_путь=РОЛИ, печатать=False, клиент=None):
    try:
        текст = io.open(стили, encoding='utf-8').read()
    except OSError as e:
        raise Отказ('не прочитать %s: %s' % (стили, e))
    текст_клиента = None
    if клиент:
        try:
            текст_клиента = io.open(клиент, encoding='utf-8').read()
        except OSError as e:
            raise Отказ('не прочитать клиента %s: %s' % (клиент, e))
    страницы = состояния_страницы(текст, текст_клиента)
    собрано = разобрать(текст)
    for и in страницы:
        if и in собрано:
            собрано[и]['вид'] = 'состояние страницы'
            собрано[и]['откуда'] = страницы[и]
    if not собрано:
        raise Отказ('в %s ни одного класса — признак сломан, а не классов нет'
                    % стили)
    роли = прочитать_роли(роли_путь)

    элементы = {и: з for и, з in собрано.items() if з['вид'] == 'элемент'}
    варианты = {и: з for и, з in собрано.items() if з['вид'] == 'вариант'}
    состояния = {и: з for и, з in собрано.items() if з['вид'] == 'состояние'}
    безымянные = {и: з for и, з in собрано.items() if з['вид'] == 'не названо'}
    стр = {и: з for и, з in собрано.items() if з['вид'] == 'состояние страницы'}

    # ⚠ Покрытие печатается ВСЕГДА: без него «ролей не хватает ноль» значит
    #    только то, что спросили не всех.
    print('классов %d · элементов %d · вариантов %d · состояний %d · '
          'состояний страницы %d · без оси %d'
          % (len(собрано), len(элементы), len(варианты), len(состояния),
             len(стр), len(безымянные)))
    if стр:
        print('  состояния страницы (признак: body.X в стилях + '
              'document.body.classList в клиенте): %s'
              % ', '.join('%s — %s' % (и, собрано[и].get('откуда', '?'))
                          for и in sorted(стр)))
    с_токенами = [и for и, з in собрано.items() if з['токены']]
    print('рисуют токенами: %d из %d' % (len(с_токенами), len(собрано)))

    if печатать:
        for имя in sorted(собрано):
            з = собрано[имя]
            print('  %-20s %-10s %-28s %s'
                  % (имя, з['вид'], роли.get(имя, '—'),
                     ', '.join(з['токены'])[:60] or 'цветом не рисуется'))

    # Гниение списка в обе стороны, как у долга палитры: запись о месте,
    # которого нет, — красное.
    лишние = sorted(и for и in роли if и not in собрано)
    if лишние:
        print('КРАСНОЕ: в ролях %d запис(ь/и) о классе, которого нет в %s: %s'
              % (len(лишние), стили, ', '.join(лишние)))
        return 1

    без_роли = sorted(и for и in элементы if и not in роли)
    без_оси = sorted(безымянные)
    if без_роли or без_оси:
        if без_роли:
            print('НЕ ВЫПОЛНЕНО: элементов без названной роли %d из %d: %s'
                  % (len(без_роли), len(элементы), ', '.join(без_роли[:12])
                     + (' …' if len(без_роли) > 12 else '')))
        if без_оси:
            print('НЕ ВЫПОЛНЕНО: классов без оси %d: %s'
                  % (len(без_оси), ', '.join(без_оси[:12])
                     + (' …' if len(без_оси) > 12 else '')))
        print('  (роль и ось в CSS не записаны — их называют руками в %s;'
              ' «не выполнено» читать как долг, а не как зелёное)' % роли_путь)
        return 2

    print('зелёное: у всех %d элементов названа роль, у всех классов — ось'
          % len(элементы))
    return 0


def самопроверка():
    import tempfile
    случаи = [
        ('всё названо',
         '.btn { color: var(--ink); }\n.btn.quiet { opacity: .7; }\n',
         {'btn': 'главное действие', 'quiet': 'вариант'}, 0, 'зелёное'),
        ('элемент без роли',
         '.btn { color: var(--ink); }\n', {}, 2, 'без названной роли 1 из 1'),
        ('класс без оси',
         '.btn { color: var(--ink); }\n.btn.strannyj { opacity: .5; }\n',
         {'btn': 'главное действие'}, 2, 'без оси 1'),
        ('запись о несуществующем классе',
         '.btn { color: var(--ink); }\n',
         {'btn': 'главное действие', 'nety': 'выдумка'}, 1,
         'которого нет'),
        ('стилей нет вовсе', '', {}, 2, 'признак сломан'),
        # ⚠ Контроль признака состояния страницы: подложенный body.X обязан
        #    НАЙТИСЬ. Без него «ровно два» неотличимо от «признак видит два
        #    из трёх» (условие координатора, 02.11.2026).
        # Ждём код 0: подлог НАХОДИТСЯ и вид ему назначен, а долгов нет —
        # приговор про роли, а не про признак. Моё первое ожидание (код 2)
        # было неверным, и самопроверка это показала.
        ('подложенное состояние страницы найдено',
         '.btn { color: var(--ink); }\nbody.net-takogo { padding: 0; }\n',
         {'btn': 'главное действие'}, 0, 'net-takogo — по стилям'),
    ]
    беда = 0
    for имя, css, роли, код, кусок in случаи:
        д = tempfile.mkdtemp(prefix='reestr-')
        с, р = os.path.join(д, 's.css'), os.path.join(д, 'r.json')
        io.open(с, 'w', encoding='utf-8').write(css)
        io.open(р, 'w', encoding='utf-8').write(json.dumps(роли, ensure_ascii=False))
        прежний, sys.stdout = sys.stdout, io.StringIO()
        try:
            try:
                rc = судить(с, р)
            except Отказ as e:
                print('НЕ ВЫПОЛНЕНО: %s' % e)
                rc = 2
            вывод = sys.stdout.getvalue()
        finally:
            sys.stdout = прежний
        os.unlink(с); os.unlink(р); os.rmdir(д)
        плохо = []
        if rc != код:
            плохо.append('код %d, ждали %d' % (rc, код))
        if кусок not in вывод:
            плохо.append('нет %r' % кусок)
        print('%-32s %s' % (имя, 'ок' if not плохо else 'БЕДА: ' + '; '.join(плохо)))
        if плохо:
            беда = 1
            print('    вывод: %s' % вывод.replace('\n', ' | '))
    print('самопроверка: %s' % ('БЕДА' if беда else 'всё как ждали'))
    return 1 if беда else 0


if __name__ == '__main__':
    args = sys.argv[1:]
    if args == ['--самопроверка']:
        sys.exit(самопроверка())
    стили, роли_путь, печатать, клиент = СТИЛИ, РОЛИ, False, None
    try:
        о = 0
        while о < len(args):
            а = args[о]
            if а == '--стили':
                о += 1; стили = args[о]
            elif а == '--роли':
                о += 1; роли_путь = args[о]
            elif а == '--клиент':
                о += 1; клиент = args[о]
            elif а == '--печатать':
                печатать = True
            else:
                raise Отказ('неизвестный ключ %r' % а)
            о += 1
        sys.exit(судить(стили, роли_путь, печатать, клиент))
    except IndexError:
        print('НЕ ВЫПОЛНЕНО: у ключа нет значения'); sys.exit(2)
    except Отказ as e:
        print('НЕ ВЫПОЛНЕНО: %s' % e); sys.exit(2)
