"""Пометки состава по съёму ДО СБОРКИ: что скажет приговор шага 7, когда
признак сборки исполнится. Падающая проверка.

    python3 -I tools/pometki-do-sborki.py [--разметка screens/razmetka.json]
                                          [--рецепты _docs/recept/ekran]
                                          [--дерево .]
    python3 -I tools/pometki-do-sborki.py --самопроверка

Коды: 0 — предсказаний нет · 1 — ЕСТЬ ПРЕДСКАЗАНИЕ ПРИГОВОРА (пометка ветки
незаконна или её не хватает уже сегодня) · 2 — НЕ ВЫПОЛНЕНО (предмета нет,
контроль подмены не прошёл, соседа нет, съём негоден).

ЗАЧЕМ (`Cafe13KPG#955`, заводится по просьбе `designer-55` 19.11.2026).
Приговор шага 7 о классах экрана, чей признак сборки ещё не исполнен, МОЛЧИТ —
и молчит законно: «РЕЦЕПТ ЕЩЁ НЕ ИСПОЛНЕН … сверять нечего, это не
расхождение». Но пометки ветки (`ТОЛЬКО живой` / `ТОЛЬКО демо`) — утверждения
о СНЯТОМ съёме, и их законность спрашивается УЖЕ СЕЙЧАС, съёмом, который
лежит в дереве. Цена молчания названа числом: 19.11.2026 семья 17 держала
ШЕСТЬ дефектов пометок (пять незаконных `ТОЛЬКО живой` у `barCard` и одну
нехватку пометки у `.verbatim`), приговор о них молчал, и нашла их РУКА
(`frontend-events-ad`), воспроизведя предикат приговора функциями самого
прибора. Класс дизайнера о себе: «лечение класса считается законченным не на
новых местах, а на всех прежних» — и ловить это обязан прибор.

УСТРОЙСТВО, и оно — главное решение этого прибора:

  • РЕПЛИКИ ПРЕДИКАТА ЗДЕСЬ НЕТ. Предсказание выносит ТОТ ЖЕ `суд` из
    `tools/sverka-recepta.py`, с ОДНИМ подменённым входом: ответ
    `признак_сошёлся` «не исполнен» подменяется на «исполнен». Второе условие
    заявки («два приговора об одном предмете разойдутся молча») исполнено не
    сверкой двух редакций, а отсутствием второй редакции: расходиться нечему.
  • ПОДМЕНА МИНИМАЛЬНА И НАЗВАНА. Подменяется ровно `False → True`. Поломка
    формы признака (`сошёлся is None`) пролетает НАСКВОЗЬ: сломанный рецепт —
    не «ещё не собран», и предсказывать по нему значило бы судить о другом
    предмете. `НечемМерить` тоже пролетает насквозь.
  • ПРЕДСКАЗАНИЕ — это строки, которых у настоящего приговора НЕТ, а у
    подменённого ЕСТЬ, и только КРАСНЫЕ: `НЕ ИЗМЕРЕНО` подменённого прогона
    печатается СПРАВКОЙ и в код не идёт (законная пометка `ТОЛЬКО живой` на
    классе, которого в съёме нет, даёт ровно такую строку — и это не дефект).

⚠ ПРЕДЕЛ, И ПРИБОР ПЕЧАТАЕТ ЕГО САМ. Предсказание держится на съёме, снятом с
КЛИЕНТА ЭТОГО ДЕРЕВА, и на утверждении РЕЦЕПТА о том, что шаг не несёт новой
разметки. Это утверждение рецепта, а не замер прибора: после сборки числа
пересчитываются. Общие токены, приходящие от соседей по файлу, не изменятся;
класс, который кладёт сама сборка, — изменится.

⚠ И ПРЕДЕЛ ПРИГОВОРА, КОТОРЫЙ ЭТОТ ПРИБОР НЕ СНИМАЕТ: зелёный шаг 7 значит
«разметка на месте и в нужном числе». Прав он не судит вовсе, и предсказание
о правах не говорит ничего.
"""
import importlib.util
import io
import json
import os
import subprocess
import sys

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
РАЗМЕТКА = os.path.join('screens', 'razmetka.json')
РЕЦЕПТЫ = os.path.join('_docs', 'recept', 'ekran')
СОСЕД = 'sverka-recepta'

# ⚠ ПОМЕТКИ ПРИГОВОРА, ПО КОТОРЫМ ДЕЛИТСЯ ВЫВОД СОСЕДА. Они — договор с ним, и
#   договор назван здесь, а не рассыпан по коду: сменит он слова — покраснеет
#   контроль «подмена только добавляет», а не промолчит предсказание.
КРАСНОЕ = 'КРАСНОЕ: '
НЕ_ИЗМЕРЕНО = 'НЕ ИЗМЕРЕНО: '
# ⚠ `НЕ ВЫПОЛНЕНО` в контроль НЕ входит, и это не поблажка: строки о САМОМ
#   признаке («РЕЦЕПТ ЕЩЁ НЕ ИСПОЛНЕН», «сошёлся ЧАСТИЧНО») подмена убирает
#   нарочно — она ровно за этим и сделана, — а строка «в съёмке описи экрана
#   нет» наоборот ПОЯВЛЯЕТСЯ. То есть этот разряд и растёт и убывает законно, и
#   требование «только добавляет» на нём было бы ложным красным.


class НеВыполнено(Exception):
    pass


def сосед(дерево):
    """Модуль `tools/sverka-recepta.py` ИЗ СУДИМОГО ДЕРЕВА.

    ⚠ Берётся он у ДЕРЕВА, а не рядом с собой: предсказание выносит приговор
    того дерева, которое судим, иначе прибор свежей ветки объявлял бы о чужом
    дереве то, чего его собственный приговор не скажет.
    ⚠ «Нет рядом» и «есть, но не загружается» — РАЗНЫЕ адреса лечения, и
    пропущены они обе кодом 2, а не трейсбеком: единица здесь объявлена
    предсказанием, то есть своё падение читалось бы приговором о предмете.
    Класс взят у соседа — он купил его своим дефектом 07.11.2026."""
    путь = os.path.join(дерево, 'tools', СОСЕД + '.py')
    if not os.path.exists(путь):
        raise НеВыполнено('в дереве «%s» нет `tools/%s.py` — предсказание выносит ЕГО '
                          'приговор, и реплики предиката здесь нет НАРОЧНО'
                          % (дерево, СОСЕД))
    спец = importlib.util.spec_from_file_location(СОСЕД.replace('-', '_'), путь)
    м = importlib.util.module_from_spec(спец)
    try:
        спец.loader.exec_module(м)
    except Exception as e:
        raise НеВыполнено('`tools/%s.py` в дереве ЕСТЬ, но не загружается (%s: %s) — '
                          'чинить его, а не раскладку' % (СОСЕД, type(e).__name__, e))
    for имя in ('судить_с_охраной', 'признак_сошёлся', 'ревизия_дерева'):
        if not hasattr(м, имя):
            raise НеВыполнено('у `tools/%s.py` нет `%s` — договор о подмене сломан, '
                              'и подменять нечего' % (СОСЕД, имя))
    return м


def строки_разрядов(вывод):
    """{пометка: множество строк} по выводу приговора — только судимые разряды."""
    из = {КРАСНОЕ: set(), НЕ_ИЗМЕРЕНО: set()}
    for с in вывод.splitlines():
        for п in из:
            if с.startswith(п):
                из[п].add(с[len(п):])
    return из


def контроль_добавления(настоящие, предсказанные):
    """Беда, если подмена что-то УБРАЛА из судимых разрядов, а не только добавила.

    ⚠ ЭТО И ЕСТЬ РАЗЛИЧАЮЩИЙ КОНТРОЛЬ ПОДМЕНЫ, и он идёт на КАЖДОМ прогоне, по
    живым данным, а не только в самопроверке. Смысл: подменён ОДИН вход, значит
    о классах приговор обязан сказать всё, что говорил, плюс новое. Исчезла
    строка — подмена изменила больше, чем один вход (или сосед сменил слова
    разрядов), и тогда «предсказаний нет» читать нельзя ничем."""
    ушедшие = []
    for п in (КРАСНОЕ, НЕ_ИЗМЕРЕНО):
        for с in sorted(настоящие[п] - предсказанные[п]):
            ушедшие.append('%s%s' % (п, с))
    if ушедшие:
        return ('подмена признака УБРАЛА %d строк(и) судимых разрядов, а обязана была '
                'только добавлять: %s ⚠ значит подменён не один вход либо сосед сменил '
                'слова разрядов — «предсказаний нет» на этом прогоне не значит ничего'
                % (len(ушедшие), ' · '.join(с[:160] for с in ушедшие[:3])))
    return None


def предсказать(разметка_путь, каталог_рецептов, дерево, печать=True):
    м = сосед(дерево)
    настоящий = м.признак_сошёлся
    подменено = {'всего': 0, 'не_исполнен': 0, 'поломка': 0}

    def подменённый(признак, файлы_без_прозы, дерево_=None):
        # ⚠ НечемМерить НЕ ловится: он пролетает насквозь к соседу, и экран с
        #   неизмеримым признаком остаётся «не измерено» в ОБОИХ прогонах.
        сошёлся, пояснение, счёт = настоящий(признак, файлы_без_прозы, дерево_)
        подменено['всего'] += 1
        if сошёлся is None:
            подменено['поломка'] += 1
            return сошёлся, пояснение, счёт
        if сошёлся:
            return сошёлся, пояснение, счёт
        подменено['не_исполнен'] += 1
        return True, пояснение + ' ⚠ ПОДМЕНЕНО на «исполнен»', счёт

    def прогон(подмена):
        м.признак_сошёлся = подменённый if подмена else настоящий
        прежний, sys.stdout = sys.stdout, io.StringIO()
        try:
            код = м.судить_с_охраной(разметка_путь, каталог_рецептов, дерево, None)
            return код, sys.stdout.getvalue()
        finally:
            sys.stdout = прежний
            м.признак_сошёлся = настоящий

    код_как_есть, вывод_как_есть = прогон(False)
    код_с_подменой, вывод_с_подменой = прогон(True)
    настоящие = строки_разрядов(вывод_как_есть)
    предсказанные = строки_разрядов(вывод_с_подменой)

    сказать = (lambda с: print(с)) if печать else (lambda с: None)
    адрес = м.ревизия_дерева(дерево)
    сказать('предмет: ПОМЕТКИ СОСТАВА ПО СЪЁМУ ДО СБОРКИ · дерево %s (%s)'
            % (os.path.abspath(дерево), адрес))
    сказать('приговор шага 7 выносит `tools/%s.py` ТОГО ЖЕ дерева; реплики предиката '
            'здесь нет — подменён ОДИН его вход' % СОСЕД)

    # ⚠ ПРИГОВОР, УМЕРШИЙ НА СВОЁМ ВХОДЕ, ПРЕДСКАЗЫВАТЬ НЕЧЕМ. Съём с другого
    #   дерева, сломанная форма состава, отсутствие соседа у соседа — всё это
    #   он отдаёт кодом 2 БЕЗ разбора классов, и «предсказаний нет» тогда
    #   значило бы «прибор не работал».
    if не_судил(вывод_как_есть) or не_судил(вывод_с_подменой):
        сказать('НЕ ВЫПОЛНЕНО: приговор шага 7 не состоялся на своём входе (код %d/%d) '
                '— предсказывать нечем. Его строка:\n  %s'
                % (код_как_есть, код_с_подменой, первая_беда(вывод_как_есть)))
        return 2

    беда = контроль_добавления(настоящие, предсказанные)
    if беда:
        сказать('НЕ ВЫПОЛНЕНО (контроль подмены): %s' % беда)
        return 2

    # ⚠ ПУСТОЙ ПРЕДМЕТ — НЕ ЗЕЛЁНОЕ, и это правило канона («Положительный
    #   контроль, оказавшийся пустым, — не прибор»). Если ни один признак
    #   сборки не был «не исполнен», подменять было нечего, и ноль
    #   предсказаний означает «прибор не работал», а не «пометки законны».
    if not подменено['не_исполнен']:
        сказать('НЕ ИЗМЕРЕНО: предмета нет — признаков сборки спрошено %d, '
                'НЕ ИСПОЛНЕН ни один (поломок формы %d). До сборки нет ни одного '
                'экрана, значит все пометки судит сам шаг 7, и ноль предсказаний '
                'здесь не значит «пометки законны»'
                % (подменено['всего'], подменено['поломка']))
        return 2

    новые_красные = sorted(предсказанные[КРАСНОЕ] - настоящие[КРАСНОЕ])
    новые_справки = sorted(предсказанные[НЕ_ИЗМЕРЕНО] - настоящие[НЕ_ИЗМЕРЕНО])
    сказать('признаков сборки спрошено %d, подменено «не исполнен» → «исполнен» %d, '
            'поломок формы пропущено насквозь %d'
            % (подменено['всего'], подменено['не_исполнен'], подменено['поломка']))
    сказать('у самого приговора своих красных %d — их судит ОН, и здесь они не '
            'повторяются' % len(настоящие[КРАСНОЕ]))
    for с in новые_справки:
        сказать('  · справка (в код не идёт): %s' % с)
    for с in новые_красные:
        print('ПРЕДСКАЗАНИЕ ПРИГОВОРА: %s' % с)
    сказать('')
    сказать(ПРЕДЕЛ)
    if новые_красные:
        сказать('ПРЕДСКАЗАНИЙ %d — приговор шага 7 скажет это, как только признак '
                'сборки исполнится; чинить СОСТАВ сегодня · снято по %s'
                % (len(новые_красные), адрес))
        return 1
    сказать('предсказаний нет: у %d экрана(ов) до сборки пометки состава съёму не '
            'противоречат · снято по %s' % (подменено['не_исполнен'], адрес))
    return 0


ПРЕДЕЛ = (
    'ПРЕДЕЛ (прибор печатает его сам): предсказание держится на съёме ЭТОГО дерева и\n'
    'на утверждении РЕЦЕПТА, что шаг не несёт новой разметки — это утверждение\n'
    'рецепта, а не замер прибора. После сборки числа пересчитываются: общие токены\n'
    'от соседей по файлу не изменятся, класс, который кладёт сама сборка, изменится.\n'
    'И предел приговора, который этот прибор НЕ снимает: шаг 7 судит разметку, а\n'
    'прав не судит вовсе.')

# ⚠ ПРИЗНАК «ПРИГОВОР ДОШЁЛ ДО ПРИГОВОРА» — ЕГО ИТОГОВАЯ СТРОКА, А НЕ ПОИСК
#   СЛОВ «ПРОВЕРКА НЕ ВЫПОЛНЕНА» ПО ВЫВОДУ. Куплено прогоном: первая редакция
#   искала эти слова и краснела на ВСЕХ случаях сразу, потому что их печатает
#   СОСЕД СОСЕДА — `check-stages.экраны_кода` сообщает беду печатью плюс
#   `sys.exit(2)`, приговор эту беду законно переживает строкой отчёта, а слова
#   остаются в выводе. Признак по чужой печати судил о приговоре по строке,
#   которая не его.
ИТОГИ = ('расхождений ', 'зелёного нет: ', 'зелёное: ')


def не_судил(вывод):
    return not any(с.startswith(ИТОГИ) for с in вывод.splitlines())


def первая_беда(вывод):
    for с in вывод.splitlines():
        if с.startswith('ПРОВЕРКА НЕ ВЫПОЛНЕНА'):
            return с
    return ('итоговой строки приговора (%s) в выводе нет, и строки отказа тоже'
            % ' / '.join(repr(с) for с in ИТОГИ))


def с_охраной(*а, **к):
    """Любая необработанная беда — КОД 2, а не 1.

    ⚠ Единица здесь объявлена ПРЕДСКАЗАНИЕМ о предмете. Своё падение,
    отданное единицей, читалось бы находкой о составе — тот самый класс,
    которым куплен код 2 у соседа."""
    try:
        return предсказать(*а, **к)
    except НеВыполнено as e:
        print('ПРОВЕРКА НЕ ВЫПОЛНЕНА: %s' % e)
        return 2
    except Exception:
        import traceback
        traceback.print_exc()
        print('ПРОВЕРКА НЕ ВЫПОЛНЕНА: прибор упал на своём месте (трейсбек выше) — '
              'это код 2, «нечем проверить», а НЕ предсказание')
        return 2


# ── самопроверка ────────────────────────────────────────────────────────────
# ⚠ ФИКСТУРА БЕРЁТСЯ У СУДИМОГО ПРИБОРА, А НЕ ПИШЕТСЯ ВТОРАЯ. Состав, разметка
#   и клиент — его собственные образцы (`СОСТАВ_ОБРАЗЕЦ`, `РАЗМЕТКА_ОБРАЗЕЦ`,
#   `КЛИЕНТ_ОБРАЗЕЦ`): предмет предсказания — ЕГО приговор, и своя фикстура
#   разошлась бы с ним молча, ровно как разошлась бы реплика предиката.
КЛИЕНТ_БЕЗ_СБОРКИ = ("function home(){ return '<div class=\"card\">Пока пусто</div>'; }\n"
                     "function partnerApply(){ return 1; }\n")


def самопроверка():
    import shutil
    import tempfile
    д = tempfile.mkdtemp(prefix='pometki-')
    случаи, провал = [], []
    свой = os.path.dirname(os.path.abspath(__file__))
    м = сосед(os.path.dirname(свой))

    def дерево(состав, клиент, правка_разметки=None, без_соседа=False,
               правка_рецепта=None):
        корень = tempfile.mkdtemp(prefix='derevo-', dir=д)
        os.mkdir(os.path.join(корень, 'js'))
        os.mkdir(os.path.join(корень, 'tools'))
        # ⚠ ДЕРЕВО ОБЯЗАНО НЕСТИ ПРИБОРЫ, и это свойство предмета, а не удобство
        #   фикстуры: приговор берётся У СУДИМОГО ДЕРЕВА, а он сам зовёт соседей
        #   рядом с собой (`klient.py`, `check-stages.py`).
        for имя in sorted(os.listdir(свой)):
            if not имя.endswith('.py'):
                continue
            if без_соседа and имя == СОСЕД + '.py':
                continue
            shutil.copy(os.path.join(свой, имя), os.path.join(корень, 'tools', имя))
        io.open(os.path.join(корень, 'index.html'), 'w', encoding='utf-8').write(
            '<!doctype html><html><head><link rel="stylesheet" href="styles.css">'
            '</head><body><script src="js/01-osnova.js"></script>'
            '<script src="js/02-vtoroy.js"></script></body></html>')
        io.open(os.path.join(корень, 'styles.css'), 'w', encoding='utf-8').write(
            '.card { color: red }\n')
        io.open(os.path.join(корень, 'js', '01-osnova.js'), 'w', encoding='utf-8').write(клиент)
        io.open(os.path.join(корень, 'js', '02-vtoroy.js'), 'w', encoding='utf-8').write(
            м.КЛИЕНТ_ВТОРОЙ)
