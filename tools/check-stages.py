КЛЮЧЕВЫЕ_ПЕРЕД_РЕГУЛЯРКОЙ = frozenset((
    'return', 'typeof', 'instanceof', 'in', 'of', 'new', 'delete', 'void',
    'case', 'do', 'else', 'yield', 'await', 'throw'))

# Знаки, после которых ждут ВЫРАЖЕНИЕ, то есть `/` начинает регулярку, а не
# делит. Имя, число, `)` и `]` сюда не входят нарочно — после них деление.
ЖДУТ_ВЫРАЖЕНИЕ = frozenset('(,=:[!&|?{};+-*%/~^<>')


def _конец_литерала(исходник, i):
    r"""Индекс закрывающей кавычки `'`/`"` НА ТОЙ ЖЕ строке, иначе None.

    ⚠ Это не удобство, а защита класса: в JS одинарная и двойная строки
    перенос строки не переходят. Кавычка без пары на своей строке — не
    строка, а знак внутри чего-то другого (чаще всего внутри регулярки), и
    открывать ею строковое состояние значит сдвинуть чётность кавычек на
    весь остаток файла. Именно так и ломалось: `/[&<>"']/g` на `app.js:3289`
    открывал строку, а стреляло на `:4728`, где `/*` из
    `accept="image/*,video/*"` обнулял 280 строк живого кода.

    Назван ПРЕДЕЛ: строка, продолженная `\` перед переносом, здесь строкой
    не считается. В клиенте таких нет (замер 28.10.2026), а разница между
    «нет» и «нечем измерить» закрыта случаем самопроверки.
    """
    кавычка, j, n = исходник[i], i + 1, len(исходник)
    while j < n:
        з = исходник[j]
        if з == '\\':
            if j + 1 < n and исходник[j + 1] == '\n':
                return None
            j += 2; continue
        if з == '\n':
            return None
        if з == кавычка:
            return j
        j += 1
    return None


def _конец_регулярки(исходник, i):
    """Индекс закрывающего `/` регулярного литерала, иначе None.

    Знает класс символов (внутри `[…]` слеш не закрывает) и экранирование.
    Регулярка в JS перенос строки не переходит — поэтому поиск ограничен
    строкой, и «не нашлось» читается как «это было деление», а не как
    «ищем дальше».
    """
    j, n = i + 1, len(исходник)
    if j < n and исходник[j] in '/*':      # `//` и `/*` — комментарии
        return None
    класс = False
    while j < n:
        з = исходник[j]
        if з == '\\':
            j += 2; continue
        if з == '\n':
            return None
        if класс:
            if з == ']':
                класс = False
        elif з == '[':
            класс = True
        elif з == '/':
            return j
        j += 1
    return None


def снять_комментарии(исходник):
    r"""`//…` и `/*…*/` — пробелами; строки, шаблоны и регулярки НЕ трогая.

    Длина сохраняется, чтобы смещения счётчика скобок остались годными.
    ⚠ И это же делает прибор слепым к своим промахам: у копии те же знаки и
    те же строки, что у исходника, падает только счёт ВХОЖДЕНИЙ. Поэтому
    контроль здесь — не размер, а РАЗБОР копии родным парсером
    (`копия_разбирается`), и он падающий.

    ⚠ Возврат `arhitector-47` 28.10.2026, первый: разбор подстановок шёл по
    ВСЕМУ файлу, и строка пояснения `/* раньше было SCREENS['barShot'] */`
    объявляла экран показанным, не включая его.

    ⚠ Возврат его же, второй, и он о ДРУГОЙ стороне: снималка, не знающая
    обратных кавычек, съедала настоящий код. `` var t = `a // b`; `` — и всё
    до конца строки уходило в «комментарий» вместе с реальным `SCREENS[…]`
    за ним. Это ложный НЕГАТИВ: экран, который код подставляет, молча
    перестаёт считаться показанным, и стадия «нарисован» у него пройдёт
    зелёной. В app.js 135 обратных кавычек, случай не теоретический.
    Поэтому шаблонная строка знается как строка, вместе с подстановкой
    `${…}`: внутри неё снова КОД, и комментарий там законен.

    ⚠ Третий возврат, и он снял отсюда прежний «назван, а не обойдён»
    предел — Cafe13KPG#465, замер `frontend-events-9d` 28.10.2026 (остров).
    Прежний текст говорил: регулярный литерал не различим от деления, взято
    узкое правило про экранированный `\/`, и предел — `/[//]/`, где
    «теряется строка после него». ДОВОД ТОГО ТЕКСТА КОНЧИЛСЯ ДВАЖДЫ.
    · Предел был назван УЖЕ предмета. Отказ — не потеря одной строки:
      кавычка внутри класса символов (`/[&<>"']/g`, `app.js:3289`) сдвигала
      чётность кавычек на ВЕСЬ остаток файла, и через тысячу строк `/*`
      внутри литерала `accept="image/*,video/*"` обнулял `4728–5008` —
      280 строк, шесть объявлений экранов целиком. Предел, названный уже
      предмета, читается как «знаю и держу», и мимо него проходят.
    · Приговор прибора при этом оставался ВЕРЕН, и это не оправдание, а
      мера: оба `SCREENS[…]` лежали на `5397` и `5517`, то есть вне
      съеденного окна. Дефект был латентный, а окно ездит — его границы
      задают первый `/*` в литерале после сбоя и ближайший `*/` за ним.

    Лечится теперь СВОЙСТВО, а не вспомненный случай, двумя мерами:
      1) строка ограничена строкой файла (`_конец_литерала`) — сбой чётности
         не может уехать дальше своей строки по построению;
      2) регулярка распознаётся по предыдущей значимой лексеме и
         пропускается целиком (`_конец_регулярки`) — с классами символов и
         экранированием.

    ⚠ ПРЕДЕЛ, который остаётся названным, и теперь он УЖЕ предмета нарочно:
    `/` после `)` и `}` различим только настоящим разбором
    (`if (x) /re/.test(s)` против `(a + b) / c`), и здесь выбрано ДЕЛЕНИЕ
    как безопасное по умолчанию. Цена ошибки такого рода теперь ограничена
    одной строкой мерой (1), а не остатком файла. В клиенте таких мест нет
    (замер 28.10.2026), и самопроверка мерит это числом, а не словом.
    """
    вышло, i, n = [], 0, len(исходник)
    строка = None            # None | "'" | '"' | '`'
    шаблоны = []             # стек подстановок ${…} внутри шаблонных строк
    знак, слово = None, ''   # последняя значимая лексема КОДА: знак и слово
    while i < n:
        c = исходник[i]
        if строка:
            if c == '\\' and i + 1 < n:
                вышло.append(c); вышло.append(исходник[i + 1]); i += 2; continue
            if строка == '`' and исходник.startswith('${', i):
                шаблоны.append('`'); строка = None
                вышло.append('${'); знак, слово = '{', ''; i += 2; continue
            if c == строка:
                строка = None; знак, слово = c, ''
            вышло.append(c); i += 1
        elif c == '`':
            строка = c; вышло.append(c); i += 1
        elif c in '\'"':
            # Кавычка без пары на своей строке строкой НЕ открывается, см.
            # `_конец_литерала`: иначе чётность съезжает на остаток файла.
            if _конец_литерала(исходник, i) is None:
                вышло.append(c); знак, слово = c, ''; i += 1
            else:
                строка = c; вышло.append(c); i += 1
        elif c == '}' and шаблоны:
            строка = шаблоны.pop(); вышло.append(c); i += 1
        elif исходник.startswith('//', i) and not (i and исходник[i - 1] == '\\'):
            к = исходник.find('\n', i)
            к = n if к == -1 else к
            вышло.append(' ' * (к - i)); i = к
        elif исходник.startswith('/*', i):
            к = исходник.find('*/', i + 2)
            к = n if к == -1 else к + 2
            вышло.append(''.join(' ' if з != '\n' else '\n' for з in исходник[i:к])); i = к
        elif c == '/':
            ждут = (знак is None or знак in ЖДУТ_ВЫРАЖЕНИЕ
                    or (слово in КЛЮЧЕВЫЕ_ПЕРЕД_РЕГУЛЯРКОЙ))
            к = _конец_регулярки(исходник, i) if ждут else None
            if к is None:                       # деление
                вышло.append(c); знак, слово = c, ''; i += 1
            else:                               # регулярный литерал — дословно
                вышло.append(исходник[i:к + 1]); знак, слово = '/', ''; i = к + 1
        else:
            вышло.append(c)
            if c.strip():
                знак = c
                слово = (слово + c) if (c.isalnum() or c in '_$') else ''
            i += 1
    return ''.join(вышло)


def копия_разбирается(копия, откуда):
    """Копия БЕЗ комментариев обязана остаться разбираемым JS. Падающий контроль.

    ⚠ Контроль ДРУГОЙ механики, и он здесь единственный работающий: размер
    копии равен размеру исходника нарочно (комментарий заменяется пробелами),
    поэтому ни знаки, ни строки съеденного кода не видят — падает только счёт
    вхождений, а его никто не печатает. `node --check` не спрашивает, какой
    случай вспомнил автор: он разбирает весь файл и называет место.

    Заведено по Cafe13KPG#465, где снималка обнуляла 280 строк живого кода, а
    прибор оставался зелёным. Без этого контроля следующая правка вернёт ту же
    дыру МОЛЧА.

    `node` нет → «НЕ ВЫПОЛНЕНО» (код 2), а не зелёное: неразобранная копия и
    разобранная различаются только этим прогоном.
    """
    with tempfile.NamedTemporaryFile('w', suffix='.js', encoding='utf-8',
                                     delete=False) as ф:
        ф.write(копия); имя = ф.name
    try:
        из = subprocess.run(['node', '--check', имя], capture_output=True, text=True)
    except FileNotFoundError:
        не_выполнено('нет `node` — разбор копии без комментариев не прогнан; '
                     'это НЕ «копия цела»')
    finally:
        pathlib.Path(имя).unlink(missing_ok=True)
    if из.returncode != 0:
        место = ''
        for строка in (из.stderr or '').splitlines():
            if имя in строка or 'Error' in строка:
                место = строка.replace(имя, 'копия-без-комментариев').strip()
                break
        не_выполнено(f'копия {откуда} БЕЗ комментариев не разбирается как JS '
                     f'({место}) — снималка съела живой код, и счёт по такой '
                     'копии врёт в сторону НУЛЯ')

def подставляемые(исходник, откуда='исходнике'):
    """Экраны, которые код показывает САМ, минуя реестр.

    Ищем литералы внутри `SCREENS[...]`: `SCREENS['soon']` и тернарник
    `SCREENS[... ? 'soon' : current]`. Пусто — законный исход (таких
    экранов может не быть), поэтому контроля на непустоту здесь нет;
    число печатается, чтобы молчание было заметным.

    ⚠ Скобки считаются, а не берутся до первой закрывающей: первая
    редакция брала `[^\\]]*` и ломалась о вложенный `WIRED[current]` внутри
    самого выражения — отдавала ноль подстановок на файле, где они есть.
    Предел назван: имя, собранное из переменной, этим признаком не
    находится вовсе, здесь он уже предмета."""
    имена = set()
    без_пояснений = снять_комментарии(исходник)
    # ⚠ Падающий контроль СТОИТ ЗДЕСЬ, а не только в самопроверке: счёт идёт
    #    по этой копии, и если снималка съела код, то врёт именно этот счёт —
    #    в сторону НУЛЯ, то есть «экран не подставляется», то есть молча.
    копия_разбирается(без_пояснений, откуда)
    for м in re.finditer(r'SCREENS\[', без_пояснений):
        глубина, i = 1, м.end()
        while i < len(без_пояснений) and глубина:
            глубина += (без_пояснений[i] == '[') - (без_пояснений[i] == ']')
            i += 1
        выражение = без_пояснений[м.end():i - 1]
        имена.update(re.findall(r"'(\w+)'|\"(\w+)\"", выражение and выражение))
    return {и or д for и, д in имена} - {''}


def стадии(путь):
    файл = pathlib.Path(путь)
    if not файл.is_file():
        не_выполнено(f'нет файла стадий {путь}')
    строки = []
    for н, строка in enumerate(файл.read_text(encoding='utf-8').splitlines(), 1):
        if not строка.strip() or строка.lstrip().startswith('#'):
            continue
        поля = строка.split('\t')
        if len(поля) != 5:
            не_выполнено(f'{путь}:{н}: полей {len(поля)}, а должно быть 5 — '
                         'строка стадии разобрана неверно')
        строки.append((н, *[п.strip() for п in поля]))
    if not строки:
        не_выполнено(f'{путь}: ни одной строки стадии — сверять нечего')
    return строки


