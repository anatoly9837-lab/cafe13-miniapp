def проверить(исходник, откуда, путь=СТАДИИ):
    # ⚠ ПРЕДМЕТ НАЗЫВАЕТСЯ СЛОВАМИ, И СЛОВА МЕНЯЮТСЯ ВМЕСТЕ С НИМ. С `--файл`
    # прибор судит ДАННОЕ ДЕРЕВО, а не выложенный клиент, и прежние тексты
    # говорили «выложенный» в обоих режимах. Врали они ровно в том режиме,
    # которым прибор зовёт ночной проход (`Cafe13KPG#660`), а приговор оттуда
    # уезжает в карточку владельца БУКВОЙ: он прочитал бы «написан в
    # выложенном клиенте» про экран, которого на бою ещё нет.
    выложен = откуда == ВЫЛОЖЕНО
    ПРЕДМЕТ = (f'выложенный клиент ({откуда})' if выложен
               else f'проверяемое дерево ({откуда})')
    В_ПРЕДМЕТЕ = ('в выложенном клиенте' if выложен
                  else f'в проверяемом дереве ({откуда})')
    ПРЕДМЕТА = ('выложенного клиента' if выложен
                else f'проверяемого дерева ({откуда})')
    С_ПРЕДМЕТОМ = ('с выложенным клиентом' if выложен
                   else f'с проверяемым деревом ({откуда})')
    есть = реестр(исходник, откуда)
    написаны = экраны_кода(исходник, откуда)
    сам_код = подставляемые(исходник, откуда) & написаны
    показывается = есть | сам_код
    заморожено = заморожены(исходник, откуда) - показывается
    красное, без_стадии, служебные = [], [], []
    for н, экран, _кадр, стадия, _карточка, _дата in стадии(путь):
        if стадия == СЛУЖЕБНЫЙ:
            служебные.append(экран)
        elif стадия == '?':
            без_стадии.append(экран)
        elif стадия in ЖДУТ_РЕЕСТРА and экран not in показывается and экран not in заморожено:
            красное.append(f'{путь}:{н}: «{экран}» в стадии «{стадия}», а человеку он '
                           f'не показывается: ни в реестре {ПРЕДМЕТА}, ни '
                           'подстановкой из кода, и заморозкой (`FROZEN`) это не '
                           'объявлено — обещаем людям экран, которого они не видят')
        elif стадия == 'нарисован' and экран in показывается:
            как = 'в реестре' if экран in есть else 'подстановкой из кода'
            красное.append(f'{путь}:{н}: «{экран}» в стадии «нарисован», а человеку он '
                           f'показывается ({как}) — людям показывается то, что мы '
                           'считаем ненарисованным')
    названные = {с[1] for с in стадии(путь)}
    for экран in sorted(показывается - названные):
        как = f'есть в реестре {ПРЕДМЕТА}' if экран in есть else (
            'подставляет его САМ, минуя реестр — так делает сам код')
        красное.append(f'«{экран}» {как}, а строки о нём в {путь} нет — новый экран '
                       'проехал мимо реестра стадий, и опись молчит о работающем. '
                       'Стадию ставит автор правки экрана')
    for экран in sorted(написаны - показывается - названные):
        красное.append(f'«{экран}» написан {В_ПРЕДМЕТЕ} и человеку не '
                       f'показывается, а строки о нём в {путь} нет — опись молчит о '
                       'НАПИСАННОМ экране, и для владельца он неотличим от '
                       'несделанного')
    # ⚠ Подстрока «экранов написано» — ДОГОВОР с чужим вызывающим: блок
    # ночного прохода требует, чтобы прибор заговорил, и ищет именно её
    # (`Cafe13KPG#660`). Держит договор случай в самопроверке.
    print(f'{ПРЕДМЕТ}: {len(написаны)} экранов написано, из них показывается '
          f'{len(показывается)} ({len(есть)} реестром, {len(сам_код)} подстановкой '
          f'из кода)')
    if заморожено:
        print(f'заморожено (объявлено в FROZEN, не показывается законно): {len(заморожено)}')
    if служебные:
        print('служебные (вне пути раздела, стадии не имеют): ' + ' '.join(служебные))
    if без_стадии:
        print(f'стадия НЕ ПОСТАВЛЕНА у {len(без_стадии)} экранов: '
              + ' '.join(без_стадии[:12]) + (' …' if len(без_стадии) > 12 else ''))
        print('  (страж на них молчит нарочно — закрывает координатор задачей на тест)')
    if красное:
        print('КРАСНОЕ:')
        for с in красное:
            print('  ' + с)
        return 1, красное
    print(f'зелёное: ни одна стадия не спорит {С_ПРЕДМЕТОМ}')
    return 0, []


