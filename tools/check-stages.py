#!/usr/bin/env python3
"""Стадия экрана против ВЫЛОЖЕННОГО клиента — падающая проверка (Cafe13KPG#407).

    python3 -I tools/check-stages.py                    # скачать выложенный app.js
    python3 -I tools/check-stages.py --файл app.js      # сверить с данным файлом
    python3 -I tools/check-stages.py --самопроверка

Коды: 0 — сошлось; 1 — КРАСНОЕ (стадия разошлась с кодом); 2 — НЕ ВЫПОЛНЕНО
(файл не скачался, реестр не разобран, стадий нет) — читать как «не выполнено»,
а не как зелёное.

Правило и словарь стадий — Cafe13KPG `_docs/screen-path.md`; источник стадий —
`screens/СТАДИИ.tsv`, по строке на экран.

Два утверждения, каждое своим текстом:
  • стадия «рабочий» или «в тесте», а экрана в реестре `WIRED` нет
    → обещаем людям экран, которого они не видят;
  • стадия «нарисован», а экран в реестре есть
    → людям показывается то, что мы считаем ненарисованным.

Стадия «не готов» не ограничена нарочно: это «код есть, человеку не
показывается», и реестр о ней ничего не говорит. Строки со стадией «?»
печатаются числом — страж на них молчит, и молчит ЗАМЕТНО.
"""
import pathlib
import re
import subprocess
import sys
import tempfile

ВЫЛОЖЕНО = 'https://anatoly9837-lab.github.io/cafe13-miniapp/app.js'
СТАДИИ = 'screens/СТАДИИ.tsv'
ЖДУТ_РЕЕСТРА = ('рабочий', 'в тесте')


def не_выполнено(текст):
    print('ПРОВЕРКА НЕ ВЫПОЛНЕНА: ' + текст)
    sys.exit(2)


def реестр(исходник, откуда):
    """Множество экранов из `var WIRED = {...}` с контролем на разбор.

    ⚠ Контроль не украшение: первая редакция этого разбора искала `имя: true`,
    а в клиенте стоит `имя: 1` — и молча отдавала ПУСТОЙ реестр, то есть
    «ни одного выложенного экрана». Пустой реестр читался бы как красное у
    каждой строки, а причина была бы в приборе (замер 27.10.2026)."""
    кусок = re.search(r'var WIRED = \{(.*?)\};', исходник, re.S)
    if not кусок:
        не_выполнено(f'в {откуда} нет объявления `var WIRED = {{…}}` — '
                     'реестр не разобран, это НЕ «экранов нет»')
    имена = set(re.findall(r'(\w+) *: *[^,}\s]+', кусок.group(1)))
    if len(имена) < 10 or 'home' not in имена:
        не_выполнено(f'реестр из {откуда} разобран на {len(имена)} имён и '
                     f'{"без" if "home" not in имена else "с"} `home` — '
                     'признак не тот, числам верить нельзя')
    return имена


def стадии(путь):
    файл = pathlib.Path(путь)
    if not файл.is_file():
        не_выполнено(f'нет файла стадий {путь}')
    строки = []
    for н, строка in enumerate(файл.read_text(encoding='utf-8').splitlines(), 1):
        if not строка.strip() or строка.lstrip().startswith('#'):
            continue
        поля = строка.split('\t')
        if len(поля) != 5:
            не_выполнено(f'{путь}:{н}: полей {len(поля)}, а должно быть 5 — '
                         'строка стадии разобрана неверно')
        строки.append((н, *[п.strip() for п in поля]))
    if not строки:
        не_выполнено(f'{путь}: ни одной строки стадии — сверять нечего')
    return строки


def скачать():
    врем = pathlib.Path(tempfile.gettempdir()) / 'app-vylozhen.js'
    из = subprocess.run(['curl', '-sS', '-f', '-H', 'Cache-Control: no-cache',
                         ВЫЛОЖЕНО + '?cb=' + str(__import__('os').getpid()),
                         '-o', str(врем)], capture_output=True, text=True)
    if из.returncode != 0 or not врем.is_file() or врем.stat().st_size < 1000:
        не_выполнено('выложенный app.js не скачался: ' +
                     (из.stderr.strip() or f'код {из.returncode}') +
                     ' — это НЕ «расхождений нет»')
    return врем.read_text(encoding='utf-8'), ВЫЛОЖЕНО


def проверить(исходник, откуда, путь=СТАДИИ):
    есть = реестр(исходник, откуда)
    красное, без_стадии = [], []
    for н, экран, _кадр, стадия, _карточка, _дата in стадии(путь):
        if стадия == '?':
            без_стадии.append(экран)
        elif стадия in ЖДУТ_РЕЕСТРА and экран not in есть:
            красное.append(f'{путь}:{н}: «{экран}» в стадии «{стадия}», а в реестре '
                           'выложенного клиента его нет — обещаем людям экран, '
                           'которого они не видят')
        elif стадия == 'нарисован' and экран in есть:
            красное.append(f'{путь}:{н}: «{экран}» в стадии «нарисован», а в реестре '
                           'выложенного клиента он есть — людям показывается то, '
                           'что мы считаем ненарисованным')
    print(f'реестр: {len(есть)} экранов ({откуда})')
    if без_стадии:
        print(f'стадия НЕ ПОСТАВЛЕНА у {len(без_стадии)} экранов: '
              + ' '.join(без_стадии[:12]) + (' …' if len(без_стадии) > 12 else ''))
        print('  (страж на них молчит нарочно — закрывает координатор задачей на тест)')
    if красное:
        print('КРАСНОЕ:')
        for с in красное:
            print('  ' + с)
        return 1, красное
    print('зелёное: ни одна стадия не спорит с выложенным клиентом')
    return 0, []


def самопроверка():
    """Три исхода на одном входе: чистый, два подлога — и каждый своим текстом."""
    исходник = 'var WIRED = { home: 1, pass: 1, bar: 1, guest: 1, events: 1, event: 1, ' \
               'bookings: 1, staff: 1, demo: 1, consent: 1, topup: 1 };'
    итог = 0
    with tempfile.TemporaryDirectory() as врем:
        путь = pathlib.Path(врем) / 'СТАДИИ.tsv'
        целое = ('# проба\n'
                 'home\t—\tв тесте\t#1\t2026-10-27\n'
                 'pass\t—\tрабочий\t#2\t2026-10-27\n'
                 'barCards\tE39\tне готов\t—\t2026-10-27\n'
                 'занятость\tE31\tнарисован\t—\t2026-10-27\n'
                 'events\t—\t?\t—\t2026-10-27\n')
        путь.write_text(целое, encoding='utf-8')
        код, _ = проверить(исходник, 'проба', путь)
        if код != 0:
            не_выполнено('чистый случай уже красный — сверка сломана')
        print('контроль «чистый»: зелёное\n')

        подлоги = (
            ('обещаем невидимое', целое.replace('barCards\tE39\tне готов', 'barCards\tE39\tв тесте'),
             'которого они не видят'),
            ('показываем «ненарисованное»', целое.replace('events\t—\t?', 'events\t—\tнарисован'),
             'что мы считаем ненарисованным'),
        )
        for подпись, испорчено, ждём in подлоги:
            if испорчено == целое:
                не_выполнено(f'подлог «{подпись}» ничего не изменил — образец устарел')
            путь.write_text(испорчено, encoding='utf-8')
            код, строки = проверить(исходник, 'проба', путь)
            if код == 1 and any(ждём in с for с in строки):
                print(f'контроль «{подпись}»: краснеет своим текстом — «{ждём}»\n')
            else:
                print(f'КОНТРОЛЬ ПРОВАЛЕН «{подпись}»: код {код}\n')
                итог = 2
            путь.write_text(целое, encoding='utf-8')

        # ⚠ подлог на САМ прибор: признак реестра не тот → «не выполнено», а не зелёное
        из = subprocess.run([sys.executable, '-I', __file__, '--подлог-реестра'],
                            capture_output=True, text=True)
        if из.returncode == 2 and 'признак не тот' in из.stdout:
            print('контроль «реестр разобран не тем признаком»: код 2 своим текстом')
        else:
            print(f'КОНТРОЛЬ ПРОВАЛЕН «реестр не тем признаком»: код {из.returncode}, '
                  f'вывод: {из.stdout.strip()[:120]}')
            итог = 2
    return итог


if __name__ == '__main__':
    доводы = sys.argv[1:]
    if '--подлог-реестра' in доводы:          # служебный вход самопроверки
        реестр('var WIRED = { нечто: 1 };', 'подлог')
        print('подлог прошёл мимо контроля')
        sys.exit(0)
    if '--самопроверка' in доводы:
        sys.exit(самопроверка())
    if '--файл' in доводы:
        путь = pathlib.Path(доводы[доводы.index('--файл') + 1])
        if not путь.is_file():
            не_выполнено(f'нет файла {путь}')
        sys.exit(проверить(путь.read_text(encoding='utf-8'), str(путь))[0])
    текст, откуда = скачать()
    sys.exit(проверить(текст, откуда)[0])
