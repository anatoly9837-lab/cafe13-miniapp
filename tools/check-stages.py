def реестр(исходник, откуда):
    """Множество экранов из `var WIRED = {...}` с контролем на разбор.

    ⚠ Контроль не украшение: первая редакция этого разбора искала `имя: true`,
    а в клиенте стоит `имя: 1` — и молча отдавала ПУСТОЙ реестр, то есть
    «ни одного выложенного экрана». Пустой реестр читался бы как красное у
    каждой строки, а причина была бы в приборе (замер 27.10.2026)."""
    кусок = re.search(r'var WIRED = \{(.*?)\};', исходник, re.S)
    if not кусок:
        не_выполнено(f'в {откуда} нет объявления `var WIRED = {{…}}` — '
                     'реестр не разобран, это НЕ «экранов нет»')
    имена = set(re.findall(r'(\w+) *: *[^,}\s]+', кусок.group(1)))
    if len(имена) < 10 or 'home' not in имена:
        не_выполнено(f'реестр из {откуда} разобран на {len(имена)} имён и '
                     f'{"без" if "home" not in имена else "с"} `home` — '
                     'признак не тот, числам верить нельзя')
    return имена


def экраны_кода(исходник, откуда):
    """Имена экранов в `var SCREENS = {...}` — с тем же контролем, что у реестра.

    ⚠ Признак берётся по ФОРМЕ записи (`\n  имя: function`), поэтому у него
    обязан быть контроль: смена отступа в клиенте дала бы пустое множество,
    то есть «ни одного написанного экрана», и прибор промолчал бы обо всём
    сразу."""
    имена = set(re.findall(r'\n  (\w+): function', исходник))
    if len(имена) < 20 or 'home' not in имена:
        не_выполнено(f'в {откуда} разобрано {len(имена)} имён экранов и '
                     f'{"без" if "home" not in имена else "с"} `home` — '
                     'признак не тот, числам верить нельзя')
    return имена


def снять_комментарии(исходник):
    """`//…` и `/*…*/` — пробелами, литералы и длины НЕ трогая.

    ⚠ Возврат `arhitector-47` 28.10.2026: разбор подстановок шёл по ВСЕМУ
    файлу, и строка пояснения вроде `/* раньше было SCREENS['barShot'] */`
    объявляла экран показанным, не включая его, — послабление шире предмета,
    и в `app.js` такие пояснения обычны. Литералы при этом трогать нельзя:
    вместе с ними пропала бы сама `'soon'`. Длина сохраняется, чтобы смещения
    остались годными."""
    вышло, i, n = [], 0, len(исходник)
    строка = None            # None | "'" | '"'
    while i < n:
        c = исходник[i]
        if строка:
            вышло.append(c)
            if c == '\\' and i + 1 < n:
                вышло.append(исходник[i + 1]); i += 2; continue
            if c == строка:
                строка = None
            i += 1
        elif c in '\'"':
            строка = c; вышло.append(c); i += 1
        elif исходник.startswith('//', i):
            к = исходник.find('\n', i)
            к = n if к == -1 else к
            вышло.append(' ' * (к - i)); i = к
        elif исходник.startswith('/*', i):
            к = исходник.find('*/', i + 2)
            к = n if к == -1 else к + 2
            вышло.append(''.join(' ' if з != '\n' else '\n' for з in исходник[i:к])); i = к
        else:
            вышло.append(c); i += 1
    return ''.join(вышло)


def подставляемые(исходник):
    """Экраны, которые код показывает САМ, минуя реестр.

    Ищем литералы внутри `SCREENS[...]`: `SCREENS['soon']` и тернарник
    `SCREENS[... ? 'soon' : current]`. Пусто — законный исход (таких
    экранов может не быть), поэтому контроля на непустоту здесь нет;
    число печатается, чтобы молчание было заметным.

    ⚠ Скобки считаются, а не берутся до первой закрывающей: первая
    редакция брала `[^\\]]*` и ломалась о вложенный `WIRED[current]` внутри
    самого выражения — отдавала ноль подстановок на файле, где они есть.
    Предел назван: имя, собранное из переменной, этим признаком не
    находится вовсе, здесь он уже предмета."""
    имена = set()
    без_пояснений = снять_комментарии(исходник)
    for м in re.finditer(r'SCREENS\[', без_пояснений):
        глубина, i = 1, м.end()
        while i < len(без_пояснений) and глубина:
            глубина += (без_пояснений[i] == '[') - (без_пояснений[i] == ']')
            i += 1
        выражение = без_пояснений[м.end():i - 1]
        имена.update(re.findall(r"'(\w+)'|\"(\w+)\"", выражение and выражение))
    return {и or д for и, д in имена} - {''}


def стадии(путь):
    файл = pathlib.Path(путь)
    if not файл.is_file():
        не_выполнено(f'нет файла стадий {путь}')
    строки = []
    for н, строка in enumerate(файл.read_text(encoding='utf-8').splitlines(), 1):
        if not строка.strip() or строка.lstrip().startswith('#'):
            continue
        поля = строка.split('\t')
        if len(поля) != 5:
            не_выполнено(f'{путь}:{н}: полей {len(поля)}, а должно быть 5 — '
                         'строка стадии разобрана неверно')
        строки.append((н, *[п.strip() for п in поля]))
    if not строки:
        не_выполнено(f'{путь}: ни одной строки стадии — сверять нечего')
    return строки


def скачать():
    врем = pathlib.Path(tempfile.gettempdir()) / 'app-vylozhen.js'
    из = subprocess.run(['curl', '-sS', '-f', '-H', 'Cache-Control: no-cache',
                         ВЫЛОЖЕНО + '?cb=' + str(__import__('os').getpid()),
                         '-o', str(врем)], capture_output=True, text=True)
    if из.returncode != 0 or not врем.is_file() or врем.stat().st_size < 1000:
        не_выполнено('выложенный app.js не скачался: ' +
                     (из.stderr.strip() or f'код {из.returncode}') +
                     ' — это НЕ «расхождений нет»')
    return врем.read_text(encoding='utf-8'), ВЫЛОЖЕНО


def проверить(исходник, откуда, путь=СТАДИИ):
    есть = реестр(исходник, откуда)
    написаны = экраны_кода(исходник, откуда)
    сам_код = подставляемые(исходник) & написаны
    показывается = есть | сам_код
    красное, без_стадии, служебные = [], [], []
    for н, экран, _кадр, стадия, _карточка, _дата in стадии(путь):
        if стадия == СЛУЖЕБНЫЙ:
            служебные.append(экран)
        elif стадия == '?':
            без_стадии.append(экран)
        elif стадия in ЖДУТ_РЕЕСТРА and экран not in показывается:
            красное.append(f'{путь}:{н}: «{экран}» в стадии «{стадия}», а человеку он '
                           'не показывается: ни в реестре выложенного клиента, ни '
                           'подстановкой из кода — обещаем людям экран, которого они '
                           'не видят')
        elif стадия == 'нарисован' and экран in показывается:
            как = 'в реестре' if экран in есть else 'подстановкой из кода'
            красное.append(f'{путь}:{н}: «{экран}» в стадии «нарисован», а человеку он '
                           f'показывается ({как}) — людям показывается то, что мы '
                           'считаем ненарисованным')
    названные = {с[1] for с in стадии(путь)}
    for экран in sorted(показывается - названные):
        как = 'есть в реестре выложенного клиента' if экран in есть else (
            'подставляет его САМ, минуя реестр — так делает выложенный клиент')
        красное.append(f'«{экран}» {как}, а строки о нём в {путь} нет — новый экран '
                       'проехал мимо реестра стадий, и опись молчит о работающем. '
                       'Стадию ставит автор правки экрана')
    for экран in sorted(написаны - показывается - названные):
        красное.append(f'«{экран}» написан в выложенном клиенте и человеку не '
                       f'показывается, а строки о нём в {путь} нет — опись молчит о '
                       'НАПИСАННОМ экране, и для владельца он неотличим от '
                       'несделанного')
    print(f'выложено: {len(написаны)} экранов написано, из них показывается '
          f'{len(показывается)} ({len(есть)} реестром, {len(сам_код)} подстановкой '
          f'из кода) ({откуда})')
    if служебные:
        print('служебные (вне пути раздела, стадии не имеют): ' + ' '.join(служебные))
    if без_стадии:
        print(f'стадия НЕ ПОСТАВЛЕНА у {len(без_стадии)} экранов: '
              + ' '.join(без_стадии[:12]) + (' …' if len(без_стадии) > 12 else ''))
        print('  (страж на них молчит нарочно — закрывает координатор задачей на тест)')
    if красное:
        print('КРАСНОЕ:')
        for с in красное:
            print('  ' + с)
        return 1, красное
    print('зелёное: ни одна стадия не спорит с выложенным клиентом')
    return 0, []


