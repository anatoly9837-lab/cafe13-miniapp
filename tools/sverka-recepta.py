def ревизия_дерева(дерево):
    """«<ветка>@<sha>[+правки]» судимого дерева — или честное «не git-дерево».

    ⚠ КАНОН ТРЕБУЕТ ЭТОГО ПРЯМО (`Cafe13KPG` `_docs/rules-pribory.md`, «Отчёт о
    приборе несёт АДРЕС ДЕРЕВА, а не только код возврата»): «рядом с `rc` стоит
    имя ветки или sha, по которому он снят. Число без адреса читатель относит к
    той заявке, в теле которой его нашёл, — и это единственное, что он может
    сделать». Правило существовало, а этот прибор печатал числа без адреса.
    Повод применить — доклад `designer-55` 07.11.2026: верное число «11» уехало
    в письмо БЕЗ ДЕРЕВА, и шесть его строк были про отсутствие соседа в чужом
    дереве. Её половину беды лечит форма письма, но числу дешевле носить адрес
    с собой — тогда переносить его без условий просто нечем.

    ⚠ И СРАВНЕНИЕ С КОРНЕМ ОБЯЗАТЕЛЬНО: `git rev-parse` из подкаталога отдаёт
    sha ОБЪЕМЛЮЩЕГО репозитория, и прибор приписал бы судимому дереву чужую
    ревизию — ту же подмену РЕВИЗИИ, против которой стоит прикалывание SHA."""
    def git(*довод):
        try:
            р = subprocess.run(('git', '-C', дерево) + довод, capture_output=True,
                               text=True, timeout=20)
        except (OSError, subprocess.SubprocessError):
            return None
        return р.stdout.strip() if р.returncode == 0 else None

    корень = git('rev-parse', '--show-toplevel')
    if not корень:
        return 'не git-дерево'
    if os.path.realpath(корень) != os.path.realpath(дерево):
        return ('не корень репозитория (корень %s) — ревизию судимому дереву '
                'приписывать нечем' % корень)
    sha = git('rev-parse', '--short', 'HEAD') or '?'
    ветка = git('rev-parse', '--abbrev-ref', 'HEAD') or '?'
    грязь = git('status', '--porcelain')
    return '%s@%s%s' % (ветка, sha, '+правки' if грязь else '')


def судить_с_охраной(*а, **к):
    """`суд` с последней охраной: ПАДЕНИЕ — это код 2, а не «расхождение».

    ⚠ Три кода объявлены (0 сошлось · 1 расхождение · 2 не выполнено), и
    необработанная беда отдаёт rc=1 — ровно «расхождение». То есть собственное
    падение прибора читается приговором О ПРЕДМЕТЕ, и читается тихо: текст
    трейсбека в сводку ворот не попадает. Трейсбек печатается (иначе беду не
    починить), но КОД говорит «не проверено».

    ⚠ Охрана СТОИТ НА ОБОИХ ПУТЯХ — и в `main`, и в каждом случае батареи:
    охрана, которой нет в батарее, не проверена ничем."""
    try:
        return суд(*а, **к)
    except НетПомощника as e:
        print('ПРОВЕРКА НЕ ВЫПОЛНЕНА: %s' % e)
        return 2
    except Exception:
        traceback.print_exc()
        print('ПРОВЕРКА НЕ ВЫПОЛНЕНА: прибор упал на своём месте (трейсбек выше) '
              '— это код 2, «нечем проверить», а НЕ расхождение')
        return 2


