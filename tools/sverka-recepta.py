_МОДУЛИ = {}


def _помощник(имя):
    """Сосед по tools/ подключается ПО ПУТИ: под `python3 -I` каталог скрипта в
    sys.path не кладётся. Берутся два: `klient.py` — состав страницы и слепки
    (один источник правды), `check-stages.py` — снималка комментариев.

    ⚠ Комментарии снимаются НЕ из брезгливости: у нас дважды куплено, что
    признак, найденный в пояснении, объявляет сделанным то, чего нет
    (`/* раньше было SCREENS['barShot'] */` объявляла экран показанным).
    Признак сборки рецепта — это строка для `rg` по клиенту, и в комментарии
    она лежит так же охотно, как в коде."""
    if имя not in _МОДУЛИ:
        путь = os.path.join(os.path.dirname(os.path.abspath(__file__)), имя + '.py')
        спец = importlib.util.spec_from_file_location(имя.replace('-', '_'), путь)
        м = importlib.util.module_from_spec(спец)
        спец.loader.exec_module(м)
        _МОДУЛИ[имя] = м
    return _МОДУЛИ[имя]


# ── разбор разметки markdown: таблицы и кодовые вставки ──────────────────────
def таблицы(текст):
    """Все таблицы файла: [[ячейки строки], …]. Разделитель `|---|` выброшен."""
    из, текущая = [], []
    for строка in текст.splitlines():
        с = строка.strip()
        if с.startswith('|'):
            ячейки = [я.strip() for я in с.strip('|').split('|')]
            if not all(re.fullmatch(r':?-{2,}:?', я) for я in ячейки if я):
                текущая.append(ячейки)
            continue
        if текущая:
            из.append(текущая)
            текущая = []
    if текущая:
        из.append(текущая)
    return из


def вставки(ячейка):
    """Кодовые вставки ячейки: `.card quiet` → ['.card quiet']."""
    return [в.strip() for в in re.findall(r'`([^`]+)`', ячейка)]


ПЕРВЫЙ_ТОКЕН = re.compile(r'\.[A-Za-z_][\w-]*')
ВИД_ТОКЕН = re.compile(r'\.?[A-Za-z_][\w-]*')


def токены(селектор):
    """`.card quiet` → ('card', 'quiet'); не класс → None.

    ⚠ ЗАПИСЬ СОСТАВА — НЕ СЕЛЕКТОР CSS, А АТРИБУТ РАЗМЕТКИ. Дизайнер пишет
    `.card quiet`, `.btn quiet`, `.st wait` — это ОДИН элемент с
    `class="card quiet"`, а не потомок `quiet` внутри `.card`. Поэтому второй
    и дальше токен читается как КЛАСС, и читается это вслух: такие строки
    печатаются отчётом, чтоб прочтение было видно, а не угадано. Строка
    `.listitem b` (потомок-ТЕГ) была бы прочитана тем же правилом как класс
    `b` — в составе шага 13 таких строк нет, и появление их правит ПРИЗНАК,
    а не приговор.

    Не класс вовсе (`styles.css`, `--muted`) → None: признак, принявший имя
    файла или токен цвета за класс, краснел бы на пустом месте."""
    части = селектор.split()
    if not части or not ПЕРВЫЙ_ТОКЕН.fullmatch(части[0]):
        return None
    if any(not ВИД_ТОКЕН.fullmatch(ч) for ч in части[1:]):
        return None
    return tuple(sorted(ч.lstrip('.') for ч in части))


def с_видом(селектор):
    """Есть ли в записи токен БЕЗ точки — то есть вид класса (`.card quiet`)."""
    return any(not ч.startswith('.') for ч in селектор.split()[1:])


def _таблица_по_заголовку(все, первая_ячейка):
    """Таблица, у которой первая ячейка заголовка начинается с названного слова.

    ⚠ Берёт УЖЕ РАЗОБРАННЫЙ список, а не текст, и это не стиль: таблицы
    сравниваются потом ПО ТОЖДЕСТВУ (таблица запретов исключается из привязок),
    а второй разбор того же текста даёт другие объекты — исключение не
    срабатывало бы МОЛЧА, и `.meter` оказывался бы разом и запрещённым, и
    ингредиентом. Поймано на своём же выводе: класс из таблицы запретов
    напечатался в «без экрана».

    Форма — ПАДАЮЩАЯ: ни одной такой таблицы или больше одной значит, что
    состав написан не по форме и читать его нечем. Молчаливый выбор первой
    подошедшей дал бы приговор о половине состава."""
    нашлись = [т for т in все
               if т and т[0] and т[0][0].strip('*` ').lower().startswith(первая_ячейка)]
    if len(нашлись) != 1:
        return None, ('таблиц с первой ячейкой «%s» в составе %d, нужна ровно одна'
                      % (первая_ячейка, len(нашлись)))
    return нашлись[0], None


# ── состав экрана ───────────────────────────────────────────────────────────
def словарь_состава(текст):
    """{селектор: {номера R}} из таблицы «что эти экраны берут из словаря».

    Экран берётся из ПОСЛЕДНЕЙ ячейки строки («где на шаге»), ключом R.
    Строка без R не привязана ни к одному экрану — она не судится и
    печатается числом: приговор о ней был бы приговором наугад."""
    все = таблицы(текст)
    словарная, беда = _таблица_по_заголовку(все, 'класс')
    if беда:
        return None, None, None, беда
    запретная, _ = _таблица_по_заголовку(все, 'запрещено')
    привязанные, без_экрана, не_классы = {}, [], []
    # ⚠ ПРИВЯЗКИ БЕРУТСЯ СО ВСЕХ ТАБЛИЦ СОСТАВА, а не только со словарной, и это
    #   не вольность: носители усечения (`.clamp1`, `.clamp2`) стоят в составе
    #   ОТДЕЛЬНЫМ РАЗРЯДОМ — «уровнем они быть не могут» — и своей таблицей со
    #   своим заголовком. Читая одну словарную, прибор молча не судил бы ровно
    #   те классы, которые сборка заводит сама (правило усечения в рецепте было,
    #   носителя в клиенте не было). Признак — ПУТЬ строки (класс в первой
    #   ячейке, ссылка R в последней), а не имя таблицы: имя стареет.
    for таблица in все:
        if таблица is запретная:
            continue
        for строка in таблица[1:]:
            if len(строка) < 2:
                continue
            номера = экраны_ячейки(строка[-1])
            for сел in вставки(строка[0]):
                if токены(сел) is None:
                    не_классы.append(сел)
                elif номера:
                    привязанные.setdefault(сел, set()).update(номера)
                else:
                    без_экрана.append(сел)
    if not привязанные:
        return None, None, None, ('в таблице словаря ни один класс не привязан к '
                                  'экрану (ни одной ссылки R<номер>)')
    return привязанные, без_экрана, не_классы, None


def запреты_состава(текст):
    """Классы из раздела «чего на этих экранах нет» + счёт запретов без класса.

    Запрет без класса (новое значение радиуса, усечение вне носителя) судит
    `tools/check-sostav.py` по стилям — здесь он печатается числом, а не
    пропускается молча."""
    таблица, беда = _таблица_по_заголовку(таблицы(текст), 'запрещено')
    if беда:
        return None, None, беда
    классы, прочие = [], 0
    for строка in таблица[1:]:
        свои = [с for с in вставки(строка[0]) if токены(с) is not None]
        if свои:
            классы.extend(свои)
        else:
            прочие += 1
    return классы, прочие, None


# ── рецепт экранов ──────────────────────────────────────────────────────────
ДИАПАЗОН = re.compile(r'\bR(\d+)\s*[-–—]\s*R?(\d+)\b')
ОДИН_R = re.compile(r'\bR(\d+)\b')


def экраны_ячейки(ячейка):
    """Номера экранов из ячейки «где на шаге»: `R1`, `R2, R4` и ДИАПАЗОН `R1–R5`.

    ⚠ Диапазон разбирается НАРОЧНО, и это не удобство: по одному признаку
    `R<номер>` запись «все подписи R1–R5» дала бы R1 и R5, молча потеряв три
    экрана посередине, — то есть прибор судил бы МЕНЬШЕ, чем решил состав, и
    зеленел бы на непроверенном. Тире принимается любое из трёх: в текст
    попадают и `-`, и `–`, и `—`."""
    номера = set()
    остаток = ячейка
    for м in ДИАПАЗОН.finditer(ячейка):
        а, б = int(м.group(1)), int(м.group(2))
        if а <= б:
            номера.update(range(а, б + 1))
        остаток = остаток.replace(м.group(0), ' ')
    номера.update(int(н) for н in ОДИН_R.findall(остаток))
    return номера


ЗАГОЛОВОК = re.compile(r'^##\s+R(\d+)\s*·\s*`([^`]+)`', re.M)
ЛЮБОЙ_R = re.compile(r'^##\s+R(\d+)\b', re.M)
ПРИЗНАК = re.compile(r'\*\*Признак сборки:\*\*(.*?)(?:\n\n|\n---|\Z)', re.S)
RG = re.compile(r"rg\s+-n\s+'([^']+)'")


def экраны_рецепта(текст):
    """{номер R: (ключ экрана, [признаки сборки])} по заголовкам рецепта.

    ⚠ ФОРМА ЗАГОЛОВКА — ПАДАЮЩАЯ: `## R1 · `home` — …`. Раздел R без ключа в
    кодовой вставке читать нечем, и это «не выполнено», а не «экрана нет»:
    переименование заголовков иначе тихо обнулило бы сверку целого шага."""
    всего = len(ЛЮБОЙ_R.findall(текст))
    места = [(int(м.group(1)), м.group(2).strip(), м.start()) for м in ЗАГОЛОВОК.finditer(текст)]
    if всего != len(места):
        return None, ('разделов `## R<номер>` в рецепте %d, а с ключом экрана в '
                      'кодовой вставке разобрано %d — форма заголовка рецепта '
                      'сменилась, сверять нечем' % (всего, len(места)))
    из = {}
    for i, (номер, ключ, начало) in enumerate(места):
        конец = места[i + 1][2] if i + 1 < len(места) else len(текст)
        кусок = текст[начало:конец]
        м = ПРИЗНАК.search(кусок)
        из[номер] = (ключ, RG.findall(м.group(1)) if м else [])
    return из, None


# ── съём разметки ───────────────────────────────────────────────────────────
def съём(путь, дерево):
    """Разобранный `razmetka.json` + сверка его слепков с ДЕРЕВОМ.

    Съём — утверждение о собранном экране, значит он портится: правка клиента
    меняет классы, а файл печатает прежние. Поэтому свод слепков страницы, с
    которой снято, сравнивается со сводом дерева, и расхождение — «не
    выполнено»: приговор по старому съёму был бы приговором о чужом предмете."""
    if not os.path.exists(путь):
        return None, 'съёма разметки нет: %s — перегнать tools/shots.cjs' % путь
    try:
        файл = json.load(io.open(путь, encoding='utf-8'))
    except ValueError as e:
        return None, 'съём разметки не разобрался как JSON: %s' % e
    экраны = файл.get('экраны')
    if not isinstance(экраны, dict) or not экраны:
        return None, 'в съёме разметки нет карты «экраны» — перегнать tools/shots.cjs'
    пустые = [и for и, в in экраны.items() if not (в or {}).get('классы')]
    if пустые:
        return None, ('в съёме %d вид(ов) БЕЗ классов (%s) — экран не отрисовался, '
                      'и сличать нечего' % (len(пустые), ', '.join(sorted(пустые)[:5])))
    свод_съёма = файл.get('свод_слепков')
    klient = _помощник('klient')
    try:
        свод_дерева = klient.свод(klient.слепки_страницы(klient.читатель_дерева(дерево)))
    except klient.НеВыполнено as e:
        return None, 'состав страницы дерева не собрался: %s' % e
    if not свод_съёма:
        return None, ('в съёме нет свода слепков — он снят прибором прежней редакции, '
                      'и с каким деревом сверять, неизвестно')
    if свод_съёма != свод_дерева:
        return None, ('съём разметки снят с ДРУГОГО дерева (свод %s против %s у дерева) '
                      '— перегнать tools/shots.cjs по этому дереву'
                      % (свод_съёма[:12], свод_дерева[:12]))
    return файл, None


def есть(карта_классов, токены_селектора, поле):
    """Есть ли в снятой карте элемент, НЕСУЩИЙ все токены селектора.

    Сравнение по вхождению набора, как у самого CSS: `.card` находится и на
    элементе `card quiet`, а `.card quiet` на простом `card` — нет."""
    for комбо, счёт in карта_классов.items():
        if set(токены_селектора) <= set(комбо.split()) and (счёт or {}).get(поле, 0) > 0:
            return True
    return False


# ── приговор ────────────────────────────────────────────────────────────────
def суд(разметка_путь, каталог_рецептов, дерево, печать=True):
    красное, не_выполнено, не_измерено, отчёт = [], [], [], []
    сказать = (lambda *а: print(*а)) if печать else (lambda *а: None)

    составы = sorted(ф for ф in os.listdir(каталог_рецептов)) if os.path.isdir(каталог_рецептов) else []
    составы = [ф for ф in составы if ф.endswith('-sostav.md')]
    if not составы:
        сказать('ПРОВЕРКА НЕ ВЫПОЛНЕНА: в %s нет ни одного файла `*-sostav.md` — '
                'составов экранов нет, сверять нечего' % каталог_рецептов)
        return 2

    файл, беда = съём(разметка_путь, дерево)
    if беда:
        сказать('ПРОВЕРКА НЕ ВЫПОЛНЕНА: %s' % беда)
        return 2
    виды = файл['экраны']

    # ── класс ОБОЛОЧКИ меряется, а не угадывается списком ─────────────────
    # ⚠ Один снятый вид делает «есть на всех видах» истиной даром, поэтому
    #   признак оболочки меряется только на двух и более.
    общие = None if len(виды) > 1 else set()
    for в in (виды.values() if len(виды) > 1 else ()):
        набор = {к for комбо, счёт in в['классы'].items()
                 if (счёт or {}).get('видимых', 0) > 0 for к in комбо.split()}
        общие = набор if общие is None else (общие & набор)
    общие = общие or set()

    klient, stages = _помощник('klient'), _помощник('check-stages')
    try:
        клиент_текст = stages.снять_комментарии(klient.клиент(дерево).text)
    except klient.НеВыполнено as e:
        сказать('ПРОВЕРКА НЕ ВЫПОЛНЕНА: клиент дерева не собрался: %s — признак '
                'сборки спросить нечем' % e)
        return 2

    сказать('съём: видов %d, экранов %d, свод слепков %s · составов %d'
            % (len(виды), len({в['экран'] for в in виды.values()}),
               файл['свод_слепков'][:12], len(составы)))

    for имя_состава in составы:
        шаг = имя_состава[:-len('-sostav.md')]
        текст_состава = io.open(os.path.join(каталог_рецептов, имя_состава), encoding='utf-8').read()
        рецепты = [ф for ф in sorted(os.listdir(каталог_рецептов))
                   if ф.startswith(шаг + '-') and ф != имя_состава and ф.endswith('.md')]
        сказать('\n── шаг %s: состав %s, рецепт%s %s'
                % (шаг, имя_состава, 'ы' if len(рецепты) != 1 else '',
                   ', '.join(рецепты) or '— НЕТ'))
        if not рецепты:
            не_выполнено.append('шаг %s: состав есть, рецепта рядом нет — ключи '
                                'экранов брать негде' % шаг)
            continue
        привязанные, без_экрана, не_классы, беда = словарь_состава(текст_состава)
        if беда:
            не_выполнено.append('шаг %s: %s' % (шаг, беда))
            continue
        запрещённые, запретов_прочих, беда = запреты_состава(текст_состава)
        if беда:
            не_выполнено.append('шаг %s: %s' % (шаг, беда))
            continue

        экраны = {}
        поломан = False
        for р in рецепты:
            свои, беда = экраны_рецепта(io.open(os.path.join(каталог_рецептов, р),
                                                encoding='utf-8').read())
            if беда:
                не_выполнено.append('шаг %s, рецепт %s: %s' % (шаг, р, беда))
                поломан = True
                break
            экраны.update(свои)
        if поломан:
            continue

        сказать('   классов привязано %d · без экрана %d · не классов %d · запретов '
                'классами %d, прочих %d · экранов в рецепте %d'
                % (len(привязанные), len(без_экрана), len(не_классы),
                   len(запрещённые), запретов_прочих, len(экраны)))
        if без_экрана:
            отчёт.append('шаг %s: НЕ СУДЯТСЯ (в составе без ссылки R<номер>, то есть '
                         'без экрана): %s' % (шаг, ', '.join(sorted(set(без_экрана)))))
        виды_записи = sorted({с for с in привязанные if с_видом(с)})
        if виды_записи:
            отчёт.append('шаг %s: запись «класс вид» прочитана как КОМБИНАЦИЯ классов '
                         'разметки (%s) — так её и пишет состав; потомок-тег той же '
                         'записью был бы прочитан классом' % (шаг, ', '.join(виды_записи)))
        if не_классы:
            отчёт.append('шаг %s: НЕ СУДЯТСЯ (вставка не из классов): %s'
                         % (шаг, ', '.join(sorted(set(не_классы)))))
        if запретов_прочих:
            отчёт.append('шаг %s: запретов без класса %d — их судит не этот прибор '
                         '(радиус и усечение — tools/check-sostav.py по стилям)'
                         % (шаг, запретов_прочих))

        # ── экран за экраном ──────────────────────────────────────────────
        нужны = sorted({н for набор in привязанные.values() for н in набор})
        for номер in нужны:
            if номер not in экраны:
                не_выполнено.append('шаг %s: состав ссылается на R%d, а раздела `## R%d` '
                                    'в рецептах нет' % (шаг, номер, номер))
                continue
            ключ, признаки = экраны[номер]
            мои = sorted(с for с, набор in привязанные.items() if номер in набор)
            if not признаки:
                не_выполнено.append('шаг %s R%d (%s): в рецепте нет признака сборки '
                                    'строкой `rg -n \'…\'` — собран ли экран, спросить '
                                    'нечем' % (шаг, номер, ключ))
                continue
            try:
                нашлись = [п for п in признаки if re.search(п, клиент_текст)]
            except re.error as e:
                не_выполнено.append('шаг %s R%d (%s): признак сборки не читается как '
                                    'регулярка (%s)' % (шаг, номер, ключ, e))
                continue
            # ⚠ СОБРАН — когда сошлись ВСЕ признаки рецепта, а не любой из них.
            #   Сошлась часть — это «не выполнено» своим текстом: сверка классов
            #   судила бы о половине экрана, называя её целым.
            if нашлись and len(нашлись) < len(признаки):
                не_выполнено.append('шаг %s R%d (%s): признак сборки сошёлся ЧАСТИЧНО '
                                    '(%d из %d; нет: %s) — сверять классы по половине '
                                    'экрана нечем' % (шаг, номер, ключ, len(нашлись),
                                                      len(признаки),
                                                      ' / '.join(п for п in признаки
                                                                 if п not in нашлись)))
                continue
            if not нашлись:
                не_выполнено.append('шаг %s R%d (%s): ЭКРАН НЕ СОБРАН — признака сборки '
                                    '(%s) в клиенте нет; сверять нечего, это не '
                                    'расхождение' % (шаг, номер, ключ,
                                                     ' / '.join(признаки)))
                continue
            свои_виды = {и: в for и, в in виды.items() if в['экран'] == ключ}
            if not свои_виды:
                не_выполнено.append('шаг %s R%d (%s): экран СОБРАН, а в съёмке описи его '
                                    'нет — опись отстала от клиента, добавить экран в '
                                    'tools/shots.cjs' % (шаг, номер, ключ))
                continue
            сказать('   R%d %s: собран, снят видами %d (%s), ингредиентов %d'
                    % (номер, ключ, len(свои_виды), ', '.join(sorted(свои_виды)), len(мои)))
            for сел in мои:
                т = токены(сел)
                видим_здесь = any(есть(в['классы'], т, 'видимых') for в in свои_виды.values())
                в_разметке = any(есть(в['классы'], т, 'всего') for в in свои_виды.values())
                if видим_здесь:
                    if set(т) <= общие:
                        отчёт.append('шаг %s R%d (%s): `%s` — класс ОБОЛОЧКИ: видим на '
                                     'всех %d снятых видах, его присутствие об этом '
                                     'экране не доказывает ничего'
                                     % (шаг, номер, ключ, сел, len(виды)))
                    continue
                if в_разметке:
                    красное.append('шаг %s R%d (%s): `%s` в разметке ЕСТЬ, но ПОГАШЕН — '
                                   'на экране его нет' % (шаг, номер, ключ, сел))
                    continue
                если_где_то = any(есть(в['классы'], т, 'видимых') for в in виды.values())
                if если_где_то:
                    не_измерено.append('шаг %s R%d (%s): `%s` на своём экране не найден, '
                                       'а у другого снятого вида есть — опись снимает ОДИН '
                                       'вид, и класс состояния (отказ, пусто, отправка) в '
                                       'неё не входит: мерить нечем, пока вид не снят '
                                       'фикстурой' % (шаг, номер, ключ, сел))
                else:
                    красное.append('шаг %s R%d (%s): `%s` НЕ НАЙДЕН ни на своём экране, ни '
                                   'на одном из %d снятых — состав назвал ингредиент, '
                                   'сборка его не положила' % (шаг, номер, ключ, сел, len(виды)))
            for сел in запрещённые:
                т = токены(сел)
                # ⚠ запрет — по РАЗМЕТКЕ, не по видимости: погашенный запрещённый
                #   класс из сборки не исчез и загорится первым же состоянием
                if any(есть(в['классы'], т, 'всего') for в in свои_виды.values()):
                    красное.append('шаг %s R%d (%s): `%s` ЗАПРЕЩЁН составом, а в разметке '
                                   'экрана есть' % (шаг, номер, ключ, сел))

    if печать:
        for о in отчёт:
            print('  · %s' % о)
        for с in не_измерено:
            print('НЕ ИЗМЕРЕНО: %s' % с)
        for с in не_выполнено:
            print('НЕ ВЫПОЛНЕНО: %s' % с)
        for с in красное:
            print('КРАСНОЕ: %s' % с)
        if красное:
            print('\nрасхождений %d — причину («рецепт неточен» или «сборка разошлась с '
                  'рецептом») называет дизайнер, не прибор' % len(красное))
        elif не_выполнено or не_измерено:
            print('\nзелёного нет: не выполнено %d, не измерено %d — читать как «не '
                  'проверено», а не как «сошлось»' % (len(не_выполнено), len(не_измерено)))
        else:
            print('\nзелёное: все ингредиенты состава найдены на своих экранах, '
                  'запрещённых классов на них нет')
    return 1 if красное else (2 if (не_выполнено or не_измерено) else 0)


